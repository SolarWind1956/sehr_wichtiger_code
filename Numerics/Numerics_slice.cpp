/*
	****************************************************************************************
	Срезы
 
	Срез — это множество индексов, имеющее три следующих свойства.
	
	1. 	Начальный индекс.
	
	2. 	Количество элементов (размер).
	
	3. 	Расстояние между элементами (шаг).
	
	Эти три свойства можно передать точно в таком же порядке, 
	как параметры конструктора класса std::slice. 
	
	Например, следующее выражение определяет четыре элемента, 
	начиная с индекса 2 и с шагом 3.
	
	std::slice(2, 4, 3)
	
	Иначе говоря, это выражение задает следующий набор индексов массива значений std::valarray:
 
	2 5 8 11
	
	Шаг может быть отрицательным. 
	
	Например, выражение
	
	std::slice(9, 5, —2)
	
	задает индексы
	
	9 7 5 3 1
 
	Для того чтобы определить подмножество массива значений, 
	можно использовать срез как аргумент операции индексации. 
	
	Например, следующее выражение определяет подмножество массива значений 'va', 
	содержащее элементы с индексами 2, 5, 8 и 11.
	
	va[std::slice(2, 4, 3)]
	
	Вызывающая сторона должна гарантировать, 
	что все эти индексы являются корректными. 

	Если подмножество квалифицировано как срез константного массива значений, 
	то оно считается новым массивом значений. 
	
	Если массив значений не является константным, 
	то подмножество содержит ссылки на исходный массив значений. 
	
	Вспомогательный класс std::slice_array используется следующим образом:
																--------------> #include "Numerics.hpp"
																
	Для объектов класса std::slice_array определены следующие операции.
	
	• 	Присваивание отдельного значения всем элементам.
	• 	Присваивание другого массива значений (или подмножества массива значений).
	• 	Вызов любой вычисляемой операции присваивания, например += или *=.
	
	Для любой другой операции требуется преобразование подмножества в массив значений. 
	
	Класс std::slice_array<T> является внутренним вспомогательным классом для срезов 
	и должен быть НЕдоступным для пользователя. 
	
	Таким образом, все конструкторы и операции присваивания в классе std::slice_array<T>
	являются "закрытыми". 																		
*/
//	Печать одномерного массива, ИНТЕРПРЕТИРУЕМОГО как трехмерный 
void 	test_print_3d	(	std::valarray<int>& 	v
						, 	int 					planes	//	Плоскости
						, 	int 					rows		//	Строки в плоскости
						, 	int 					cols		//	Столбцы в плоскости
						)		{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	//	Цикл по плоскостям
    for (int z = 0; z < planes; ++z)	    {
		//	Цикл по строкам плоскостей
        for (int r = 0; r < rows; ++r)	    {
			//	Цикл по столбцам плоскостей
			for (int c = 0; c < cols; ++c)	
                cout << v[z * rows * cols + r * cols + c] << ' ';
            cout << endl;
        }
        cout << endl;
    }
}

void 	slice_using_example_3()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	valarray<double> 	va(20);
	
    // assign values 0.0, 1.1, up to 9.9 to the first valarray
    for (int i = 0; i < 20; i++) {
        va[i] = i * 1.1;
    }
	printValarray(va);
	
	//	Например, оператор
	va[std::slice(2, 4, 3)] = 2;
	//	присваивает 2 третьему, шестому, девятому и двенадцатому элементам массива значений va. 
	//	Это эквивалентно следующим операторам:
	#if 0	
	va[2] 	= 	2; 
	va[5] 	= 	2; 
	va[8] 	= 	2; 
	va[11] 	= 	2;
	#endif	
	printValarray(va);
	//	В качестве другого примера рассмотрим следующий оператор, 
	//	который возводит в квадрат значения элементов с индексами 2, 5, 8 и 11.
	va[std::slice(2, 4, 3)] *= std::valarray<double>(va[std::slice(2, 4, 3)]);
	//	Как указано в разделе S.2.2, нельзя просто написать
	//va[std::slice(2, 4, 3)] *= va[std::slice(2, 4, 3)]; // ОШИБКА
	/*
		Передавая разные срезы одного и того же массива значений, 
		можно комбинировать разные подмножества 
		и сохранять результаты в других подмножествах массива значений. 

		Например, выражение
	*/
	va[std::slice(0, 4, 3)] 		= 	std::valarray<double>(va[std::slice(1, 4, 3)]) 
								*	std::valarray<double>(va[std::slice(2, 4, 3)])
								;
	printValarray(va);
	//	 эквивалентно следующим инструкциям:
	va[0] 	= 	va[1] 	* 	va[2];
	va[3] 	= 	va[4] 	* 	va[5];
	va[6] 	= 	va[7] 	* 	va[8];
	va[9] 	= 	va[10] 	* 	va[11];
	/*
		Если рассматривать массив значений как двумерную матрицу, 
		то этот пример представляет собой умножение векторов. 
		
		Однако порядок отдельных операций присваивания не определен. 
		
		Следовательно, поведение становится неопределенным, 
		если подмножество-получатель содержит элементы, 
		используемые в подмножествах-источниках.
	*/
	// 	3D-массив: 2 x 4 x 3 элемента
	std::valarray<int> 	v_for_3D 	= 	
									{	111, 112, 113, 	//	0,  1,  2,
										121, 122, 123, 	//	2,  4,  5,
										131, 132, 133, 	//	6,  7,  8, 
										141, 142, 143,	//	9,  10, 11,
									
										211, 212, 213, 	//	12, 13, 14,
										221, 222, 223, 	//	15, 16, 17,
										231, 232, 233, 	// 	18, 19, 20
										241, 242, 243	//	21, 22, 23
									};
	//	Из этого одномерного массива можно сформировать трехмерный массив:
	//	две плоскости, в каждой из двух плоскостей
	//	по четыре строки и по три столбца
	test_print_3d(v_for_3D, 2, 4, 3);
	//	Можно построить интерпретацию произведения второго столбца на третий с занесением результата в первый
	v_for_3D[std::slice(0, 8, 3)]	=	std::valarray<int>(v_for_3D[std::slice(1, 8, 3)]) 
									* 	std::valarray<int>(v_for_3D[std::slice(2, 8, 3)])
									;
	test_print_3d(v_for_3D, 2, 4, 3);
}
// print valarray line-by-line	-	построчный вывод массива значений 
template <typename T>
void printValarray_line_by_line 	(	const T& 	va			//	Массив одномерный
								, 	int 			num			//	условно разделенный на строки
								)
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	//	Цикл по количеству строк
    for (int i = 0; i < va.size() / num; ++i) {
		//	Цикл вывода элементов, условно принадлежащих очередной условной строке
        for (int j = 0; j < num; ++j) {
            cout << va[i * num + j] << ' ';
        }
        cout << endl;
    }
    cout << endl;
}
void 	slice_using_example_4()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	// 	массив значений из 12 элементов 
	// 	- четыре строки 
	// 	- три столбца 
	valarray<double> 	va(12);
	// 	заполняем массив значений значениями 
	for (int i =  0; i < 12; i++) 
		va[i] = i;
		
	printValarray_line_by_line (va, 3);
	// 	первый столбец 	= 	второй столбец, возведенный в степень, стоящую в третьем столбце
	va[slice(0, 4, 3)] 	= 	pow 	(	valarray<double>(va[slice(1, 4, 3)])
								, 	valarray<double>(va[slice(2, 4, 3)])
								); 
	printValarray_line_by_line (va, 3);
	
	cout << "создаем числовой массив 'vb', в котором трижды повторяется третий элемент массива значений 'va'" << endl; 
	valarray<double> 	vb	{va[slice(2, 4, 0)]};
	printValarray_line_by_line (vb, 3);
	
	// multiply the third column by the elements of vb -	 
	cout << "умножаем третий столбец на элементы массива значений 'vb'"  << endl;
    va[slice(2, 4, 3)] *= vb;
	printValarray_line_by_line  (va, 3);

    // print the square root of the elements in the second row	-  
	cout << "квадратный корень из элементов второй строки 'va'" << endl;
    printValarray_line_by_line  (sqrt(valarray<double>(va[slice(3, 3, 1)])), 3);

    // double the elements in the second column	-	
	cout << "удваиваем элементы второго столбца 'va'" << endl;
    va[slice(2, 4, 3)] = valarray<double>(va[slice(2, 4, 3)]) * 2.0;
    printValarray_line_by_line  (va, 3);
}	
