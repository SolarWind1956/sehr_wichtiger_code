/*
	**************************************************************************************
	Перечисляемые подмножества
	
	Перечисляемые массивы обеспечивают четвертый, и последний, 
	способ определения подмножества массива значений. 
	
	В данном случае можно просто определить подмножество массива значений, 
	передав массив индексов. 
	
	Индексы, задающие подмножество, 
	могут быть не упорядоченными 
	и указываться дважды.
 
	Во всем остальном перечисляемые массивы ничем не отличаются от обычных подмножеств.
	
	1. 	Для определения конкретного подмножества массива значений 
		достаточно передать массив элементов типа size_t операции индексации массива значений.
		
	2. 	Если массив значений является константным, 
		то результатом выражения является новый массив значений.
 
	3. 	Если массив значений является неконстантным, 
		то результатом выражения является объект класса indirect_array, 
		представляющий элементы массива значений с семантикой ссылок.
	
	4. 	Для объектов класса indirect_array предусмотрены присваивание и вычисляемые операции присваивания,
		модифицирующие элементы подмножества.
 
	5.	С помощью преобразования типов можно комбинировать перечислимые массивы 
		и другие массивы значений, а также подмножества массивов значений.
		
*/
// print valarray line-by-line
template <typename T>
void printValarray_indirect_array (const valarray<T>& va, int num)
{
    for (int i = 0; i < va.size()/num; ++i) {
        for (int j = 0; j < num; ++j) {
            cout << va[i * num + j] << ' ';
        }
        cout << endl;
    }
    cout << endl;
}
