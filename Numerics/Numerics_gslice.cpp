// print three-dimensional valarray line-by-line
template <typename T>
void 	printValarray3D 	(	const valarray<T>& 	va
						, 	int 					rows
						, 	int 					colm
						)
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	int groups = va.size() / (colm * rows);
    for (int i = 0; i < groups; ++i) {
        for (int j = 0; j < rows; ++j) {
            for (int k = 0; k < colm; ++k) {
                cout << va[i * colm * rows + j * colm + k] << ' ';
            }
            cout << endl;
        }
        cout << endl;
    }
	cout << endl;
}
