/*
	**************************************************************************************
	Библиотека Basic Linear Algebra Subprograms (BLAS) 
	содержит основные средства для реализации операций линейной алгебры, 
	таких как умножение матриц, решение треугольных систем и простые векторные операции.
	https://ru.wikipedia.org/wiki/Basic_Linear_Algebra_Subprograms
	**************************************************************************************

	Обобщенные срезы
	
	Обобщенные срезы (general slices, или gslices) 	— 	это универсальная форма срезов. 
	
	Подобно 'обычным срезам', 
	позволяющим обрабатывать 'одномерное подмножество', 
	"обобщенные срезы"
	позволяют работать с "подмножествами многомерных массивов". 
	
	В принципе "обобщенные срезы" имеют те же свойства, 
	что и 'обычные срезы'.
	
	• 	Начальный индекс.
	• 	Количество элементов (размер).
	• 	Расстояние между элементами (шаг).
 
	Тем не менее, в отличие от 'обычных срезов', 
	в "обобщенных срезах" 
	количество элементов и шаг 
	являются "массивами значений". 
	
	"Количество элементов" в таком массиве-"обобщенном срезе" 
	равно количеству "используемых размерностей". 
	
	--------------------------------------------------------------------------------------------
	Например, "обобщенный срез", имеющий состояние 
	
	start: 		2 
	sizes: 		[4] 
	strides: 	[3]
	
	эквивалентен 'обычному срезу', 
	потому что этот массив имеет 'одну размерность'. 
	
	Таким образом, такой "обобщенный срез" 
	определяют четыре элемента с шагом 3, начиная с индекса 2:
	
	2 5 8 11
	
	Повидимому, это некий протокол договоренности для такого формата обобщенного среза,
	формирующего одномерные массивы из другого одномерного.
	
	------------------------------------------------------------------------------------------------
	Однако "обобщенный срез", имеющий состояние
	
	start: 		2 
	sizes: 		[2,  4] 		-	2 	- 	две строки по 
									4 	- 	четыре элемента в строке
											можно сказать, 'количество столбцов'
	strides: 	[10, 3]			-	10	- 	шаг между 'одноиндексными элементами' в соседних строках,
											можно сказать, 'расстояние между строками'
									3	-	шаг между 'смежными элементами' при выборке из массива 
											
 	имеет "две размерности". 
								??? 'Наименьший индекс' имеет "высшую размерность". 
	
	Таким образом, этот "обобщенный срез" задает:

		-	начало с индексом 2	-	в одномерном массиве, в котором делается обобщенный срез,
										это же начало первой строки двумерного массива;
		
		-	2 (два) элемента с шагом 10:  	- для формирования строк двумерного массива
		
		и 
		
		-	4 (четыре) элемента с шагом 3:	- для формирования столбцов двумерного массива	
		
		2   5   8   11
		12  15  18  21
		
	Повидимому, это некий протокол договоренности для такого формата обобщенного среза,
	формирующего двумерные массивы из одномерного.
*/	
