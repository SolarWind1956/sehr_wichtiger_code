/*
	****************************************************************************************
	Маскированные подмножества
	
	Еще один способ определить подмножество массива значений обеспечивают 'маскированные массивы'. 
	
	Накладывать маску на элементы можно с помощью 'булевых выражений'. 
	
	Например, в выражении
	
	va[va > 7]
	
	подвыражение
	
	va > 7
	
	определяет массив значений размера 'va', 
	в котором булево значение указывает, 
	имеет ли данный элемент значение, большее 7. 
	
	Операция индексации использует булев массив знаений
	для определения всех элементов, 
	для который булево выражение возвращает значение true. 
	
	Таким образом, в массиве значений 'va' 
	выражение 
	
	va[va > 7]
	
	задает подмножество элементов, которые больше 7.
 
	Помимо этого, маскированные массивы ведут себя точно так же, 
	как и все остальные подмножества массива значений.
 
	1. 	Для определения конкретного подмножества массива значений 
		достаточно передать массив значений булевых значений 
		операции индексации массива значений.
 
	2. 	Если массив значений является константным, 
		то результатом выражения становится новый массив значений.
		
	3. 	Если массив значений является неконстантным, 
		то результатом выражения является объект класса mask_array, 
		представляющий элементы массива значений с семантикой ссылок:		-----------> Numerics.hpp
		
	4. 	Для объектов класса mask_array предусмотрены присваивание 
		и вычисляемые операции присваивания, модифицирующие элементы подмножества.
		
	5. 	С помощью преобразования типов 
		можно комбинировать маскированные массивы и другие массивы значений, 
		а также подмножества массивов значений.
*/
// print valarray line-by-line
template <typename T>
void printValarray_mask_array (const valarray<T>& va, int num)
{
    for (int i = 0; i < va.size()/num; ++i) {
        for (int j = 0; j < num; ++j) {
            cout << va[i * num + j] << ' ';
        }
        cout << endl;
    }
    cout << endl;
}

