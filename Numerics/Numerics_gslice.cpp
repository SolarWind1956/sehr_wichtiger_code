/*
	------------------------------------------------------------------------------------------------------
	Рассмотрим пример среза с тремя размерностями:
	
	start: 		2
	sizes: 		[3, 2, 4]
	strides: 	[30, 10, 3]
	
	Он задает:
		-	начало с индексом 2, 				-	индекс первого элемента выборки обобщенного среза
													в одномерном массиве
		
		-	3 (три) элемента с шагом 30, 		-	количество плоскостей
			-	30								-	шаг между 'одноиндексными элементами' в соседних плоскостях
													расстояние между плоскостями
													
		-	2 (два) элемента с шагом 10 		-	количество строк в каждой плоскости
			-	10								- 	шаг между 'одноиндексными элементами' в соседних строках,
													расстояние между строками одной плоскости		
		и 
		
		-	4 (четыре) элемента с шагом 3:	-	количество столбцов в каждой плоскости
			-	3								-	шаг между выбираемыми 'смежными элементами' для каждой строки
			
	2  5  8  11
	12 15 18 21
	
	32 35 38 41 
	42 45 48 51
	
	62 65 68 71 
	72 75 78 81
 
	Единственное отличие "обобщенных срезов" от 'обычных' 	— 
	это возможность использовать массивы 
	для определения размеров и шагов. 
	
	Помимо этого, обобщенные срезы ничем не отличаются от обычных срезов.
*/
template <typename T>
void printValarray_lines_by_plates 	(	const T& 	va			//	Массив одномерный
									,	int			plates		//	условно разделенный на плоскости,
									, 	int 			columns		//	столбцы и строки
									)
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	if (va.size() < (plates * columns)) {
		cout << "Ошибка параметров. Завершение работы!" << endl;
		return;
	}
		
	int rows		=	va.size() / plates / columns;						//	Количество строк в трехмерном срезе
	
	//	Цикл по количеству плоскостей
	for (int plt = 0; plt < plates; ++plt) {
		//	Цикл по количеству строк в каждой плоскости
		for (int r = 0; r < rows; ++r) {
			//	Цикл вывода элементов, условно принадлежащих очередной условной строке
			for (int c = 0; c < columns; ++c) {
				cout << va[plt * rows * columns  + r * columns + c] << ' ';
			}
			cout << endl;
		}
		cout << endl;
	}	
}
