/*
	----------------------------------------------------------------------------------------------------
	Операции над массивами значений
	
	Для доступа к элементу массива значений определен оператор индексации массивов значений. 
	
	Как обычно, первый индекс равен нулю.
*/
void 	valarray_operations()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	valarray<double> va(3.14, 10);
	va[0] 	= 	3 * va[1] + va[2];
	printValarray(va);
	
	/*
		Кроме того, для массивов значений определены обычные числовые операции: 
		сложение, вычитание, умножение, деление по модулю, отрицание, побитовые операции, 
		операции сравнения и логические операции, а также все операции присваивания. 
		
		Эти операции применяются к каждому элементу массива значений. 
		
		Таким образом, результат операции над массивом значений — 
		это массив значений, размер которого совпадает с размерами операндов, 
		а элементы являются результатами поэлементного вычисления. 
	*/
	valarray<double> va1(3);
	valarray<double> va2(3.14, 3);
	valarray<double> va3(3.14, 3);
	//	Например, инструкция
	va1 = va2 * va3;
	printValarray(va1);
	//	эквивалентна
	va1[0] = va2[0] * va3[0]; 
	va1[1] = va2[1] * va3[1]; 
	va1[2] = va2[2] * va3[2];
	/*
		Если количество элементов в комбинируемых массивах значений разное, 
		результат становится неопределенным. 
		
		Разумеется, можно выполнять только те операции, 
		которые предусмотрены для элементов массивов значений. 
		
		Точный смысл операции зависит от смысла операции над элементами. 
		
		Таким образом, все эти операции просто делают одно и то же 
		с каждым элементом или парой элементов обрабатываемого массива значений.
		
		В бинарных операциях один из операндов может быть отдельным значением, 
		тип которого совпадает с типом элементов массива. 
		
		В этом случае отдельное значение комбинируется 
		с каждым элементом массива значений, используемого в качестве второго операнда. 
		
		Например, инструкция
	*/
	va1 	= 	4.0 * va2;
	//	 эквивалентна инструкциям
	va1[0] 	= 4.0 * va2[0]; 
	va1[1] 	= 4.0 * va2[1]; 
	va1[2] 	= 4.0 * va2[2];
	/*
		Тип отдельного значения должен точно совпадать с типом элемента массива значений. 
		
		Следовательно, предыдущий пример будет работоспособным только в том случае, 
		если элементы имеют тип int. 
	*/
	std::valarray<double> 	va_dbl_1(20);
	//	Следующая запись оказывается ошибочной:
	va_dbl_1 	= 4 * va_dbl_1; 			// ОШИБКА: несовпадение типов
	//	У меня все выстрелило, так как сработало, повидимому, неявное преобразование типа
	std::valarray<double> 	va_int_1(20);
	va_int_1 	= 4.0 * va_dbl_1;		//	И так выстрелило
	//	Но где-нибудь да не стрельнет, где запрещены неявные преобразования
	
	/*
		Эта схема бинарных операций применима и к операциям сравнения. 
		
		Таким образом, операция == не возвращает отдельное булево значение, 
		означающее, что массивы значений равны. 
		
		Вместо этого операция возвращает новый массив значений 
		с тем же количеством элементов типа bool, 
		в котором каждый элемент является результатом индивидуального сравнения. 
		
		Например, в коде
	*/
	std::valarray<double> 	va_dbl_11	(10); 
	std::valarray<double> 	va_dbl_21	(10);
	std::valarray<bool> 		va_bool_21	(10);
	
	va_bool_21	=	(va_dbl_11 		== 	va_dbl_21);
	
	//	 последняя инструкция эквивалентна записи
	va_bool_21[0] = (va_dbl_11[0] 	==	va_dbl_21[0]); 	
	va_bool_21[1] = (va_dbl_11[1] 	==	va_dbl_21[1]); 
	va_bool_21[2] = (va_dbl_11[2]		==	va_dbl_21[2]);
	//	...
	va_bool_21[9] = (va_dbl_11[9] 	==	va_dbl_21[9]);
	
	/*
		По этой причине невозможно упорядочить массив значений с помощью операции '<'
		и нельзя использовать такие массивы, как элементы контейнеров STL, 
		если проверка равенства выполняется с помощью операции ==.
 
		Функции выше демонстрируют простое использование массивов значений.
	*/
}
/*
	Начиная со стандарта С++11, для обработки элементов можно использовать 
	'интервальные циклы' for, 
	потому что массивы значений имеют глобальные функции begin() и end().
 
	// выводим массив значений (начиная со стандарта С++11): 
*/	
template <typename T>
void 	printValarray_CPP11 (const std::valarray<T>& va)	{
	for (const T& elem : va) { 
		cout << elem << ' ';
	}	
	cout << endl;
}
