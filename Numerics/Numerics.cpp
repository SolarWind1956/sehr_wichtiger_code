/*
	**************************************************************************************
	Библиотека Basic Linear Algebra Subprograms (BLAS) 
	содержит основные средства для реализации операций линейной алгебры, 
	таких как умножение матриц, решение треугольных систем и простые векторные операции.
	https://ru.wikipedia.org/wiki/Basic_Linear_Algebra_Subprograms
	**************************************************************************************
	S.2.1. Описание массивов значений std::valarray
	
	Массивы значений — это 'одномерные массивы' с элементами, 
	последовательно пронумерованными начиная с нуля. 
	
	Они реализуют возможность выполнять определенные числовые процедуры 
	над всеми или частью значений в одном или нескольких массивах. 
	
	Oперации над массивами значений выполняются эффективно, 
	потому что классы выполняют определенную оптимизацию, 
	чтобы избежать создания временных объектов при вычислении оператора. 
	
	Кроме того, специальные интерфейсы и вспомогательные классы 
	предоставляют возможность обрабатывать 
	только одно определенное подмножество массивов значений 
	или имитировать работу с многомерными массивами. 
	
	Таким образом, массивы значений представляют собой концепцию, 
	помогающую реализовать векторные и матричные операции, 
	а также реализующие их классы.
	
	Стандарт гарантирует, что массивы значений не имеют псевдонимов. 
	
	Иначе говоря, к любому значению неконстантного массива значений 
	можно обратиться по уникальному пути. 
	
	Таким образом, операции над этими значениями можно оптимизировать, 
	потому что компилятор не учитывает данные, к которым обращаются по другому пути.
*/ 
// print valarray
template <typename T>
void 	printValarray (const std::valarray<T>& va)
{
    for (int i = 0; i < va.size(); i++) {
        cout << va[i] << ' ';
    }
    cout << endl;
}
/*
	 Создание массивов значений
	
	При создании массива значений количество его элементов задается как параметр.
*/
void 	valarray_creation()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	
	std::valarray<int> 	va1_arr_int	{10}; 		// 	массив значений из десяти целых чисел с нулевыми значениями
	
	std::valarray<float> va2_arr_flt	{5.7, 10}; 	// 	массив значений из десяти чисел типа float со значением 5.7
												// 	(обратите внимание на порядок следования аргументов)
	/*											
		При передаче одного аргумента он интерпретируется как размер. 
		
		Элементы инициализируются конструктором типа значений по умолчанию. 
		
		Элементы массива значений, имеющие фундаментальный тип, инициализируются нулем 
		(см. описание процесса инициализации данных фундаментального типа 
		с помощью конструктора по умолчанию). 
		
		При передаче второго параметра первый параметр считается начальным значением элемента, 
		а второй — количеством элементов. 
		
		Отметим, что порядок передачи двух аргументов конструктору 
		отличается от всех других классов в стандартной библиотеке C++. 
		
		Все контейнерные классы STL используют первый числовой аргумент	как количество элементнов,
		второй аргумент - как начальное значение.	

		После принятия стандарта С++11 массив значений можно инициализировать 
		с помощью списка инициализации.											
	*/
	std::valarray<int> 	va3_arr_int 		= 	{ 3, 6, 18, 3, 22 };
	std::valarray<int> 	va31_arr_int  		{ 3, 6, 18, 3, 22 };
	
	//	До принятия стандарта С++11 необходимо было использовать обычный массив из языка С.
	int array[] = { 3, 6, 18, 3, 22 };
	// 	инициализируем массив значений элементам! обычного массива 
	std::valarray<int> 	va32_arr_int		(	array
										,	sizeof(array) / sizeof(array[0])
										);
	// инициализируем второй элемент из четырех 
	std::valarray<int> 	va4_arr_int		(array + 1, 3);
	/*
		Массив значений копирует передаваемое значение. 
		
		Таким образом, для инициализации можно передавать временные данные.
	*/
}	
