/*
	Трансцендентные функции
	 
	Трансцендентные функции (тригонометрические и экспоненциальная) 
	определены как эквиваленты числовых операций. 
	
	Эти операции выполняются над всеми элементами массивов значений. 
	
	В бинарных операциях один из операндов может быть отдельным значением, 
	а вторым операндом — все значения массива значений.
	
	Все эти операции определены как глобальные функции, 
	а не как функции-члены, 
	чтобы обеспечивать автоматическое преобразование типов 
	для подмножеств массивов значений для обоих операндов 
	(подмножества массивов значений описаны в разделе S.2.2).
	
	Рассмотрим второй пример использования массивов значений. 
	
	Он демонстрирует использование трансцендентных операций:
*/
void 	Transcendental_functions_using()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	
	// create and initialize valarray with nine elements
	valarray<double> 	va(9);
    for (int i = 0; i < va.size(); i++) {
        va[i] = i * 1.1;
    }

    // print valarray
    printValarray(va);

    // double values in the valarray
    va *= 2.0;

    // print valarray again
    printValarray(va);

    // create second valarray initialized by the values of the first plus 10
    valarray<double> 	vb	(va + 10.0);

    // print second valarray
    printValarray(vb);

    // create third valarray as a result of processing both existing valarrays
    valarray<double> 	vc	(9);
    vc 	= 	sqrt(va) + vb / 2.0 - 1.0;
    
    // print third valarray
    printValarray(vc);
}	
