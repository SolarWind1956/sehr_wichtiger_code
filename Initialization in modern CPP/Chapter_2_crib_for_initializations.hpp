/*
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.1.2. 	`Агрегатная инициализация` по стандарту C++03 		-	aggregate initialization
	
	`Агрегаты` (aggregates) 	– 	это специальный вид объектов в версии C++03, 
								которые в большинстве случаев не используют конструкторы, 
								но подчиняются другому набору правил инициализации, 
								обычно обозначаемому {фигурными скобками} (braces). 
								
	Существуют два варианта `агрегатов`: 
	
	(1) 	массивы 
	и 
	(2) 	типы класса, определенного пользователем, которые: 
		-	не содержат закрытых или защищенных нестатических членов данных, 
		-	не имеют: 
				-	базовых классов, 
				-	конструкторов, предоставленных пользователем, 
				и 
				-	виртуальных функций. 
				
	`Агрегаты` похожи на `стандартную структуру` языка `C`, 
	но с `потенциальной возможностью` включения в них `дополнительных невиртуальных функций-членов`. 
	
	Следует отметить, что `сами члены агрегата` `не обязаны` быть `агрегатами`:
*/
// 	Массивы являются `агрегатами`.
int a_aggregate_deflt [5];		//	Инициализация `по умолчанию` только для неконстантных массивов

//	Константный массив должен быть инициализирован, но
const int a_aggregate [5] 	= {1, 2, 3, 4, 5};  	
const int a2_aggregate [5] 	= {};
const int a3_aggregate [5]{};			//	Все три варианта универсальной инициализации массива проходят
			
const int b_aggregate [5](1, 2, 3, 4, 5);  		// 	`прямая инициализация` - нормальна

