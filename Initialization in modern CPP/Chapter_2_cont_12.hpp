/*
	-------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.4.8. 	`Составные операторы присваивания`, но не арифметические операторы, 
			принимают `списки в {фигурных скобках}`

	`Инициализаторы в {фигурных скобках}` 
	можно использовать для `передачи аргументов` в `оператор присваивания` 
	и дополнительно для `составных операторов присваивания`, 
	таких как +=, 
	в которых `инициализаторы` интерпретируются 
	как `вызовы перегружаемой функции оператора` 
	для типа класса или как += T{value} для скалярного типа `T`. 
	
	Обратите внимание: `присваивание скалярам` поддерживает `списки в {фигурных скобках}`, 
	содержащие `не более одного` элемента, 
	и `не поддерживает` `составные операторы присваивания` 
	для типов указателей, поскольку `списки в {фигурных скобках}` 
	преобразуются в `тип указателя`, 
	который не должен находиться в `правой части` `составного оператора присваивания`.
	
	Хотя предназначением `составных операторов присваивания`
	является семантическая равнозначность выражению 
	
	a = a + b (или * b, или – b и т. д.), 
	
	`списки в {фигурных скобках}` 
	запрещено использовать в `обычных арифметических выражениях`, 
	поскольку грамматика не поддерживает `списки в {фигурных скобках}` 
	как `произвольные выражения`:
*/
struct S_Compound_assignment
{
    S_Compound_assignment(std::initializer_list<int>) { 
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	}
    S_Compound_assignment& operator+=(const S_Compound_assignment&) { 
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
		return *this; 
	}
};
S_Compound_assignment 	operator+(const S_Compound_assignment&, const S_Compound_assignment&) 
{ 
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	return S_Compound_assignment{}; 
}
