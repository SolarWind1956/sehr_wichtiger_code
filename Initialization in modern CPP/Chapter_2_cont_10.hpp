/*
	------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.2.4. 	`Универсальная инициализация` в `фабричных функциях`
	
	Одна из проблем проектирования для автора `обобщенного кода` – 
	какую `форму синтаксиса` "выбрать" для `инициализации объектов`, 
	`тип` которых `зависит от параметров шаблона`. 
	
	Различные типы `C++` ведут себя по-разному и допускают разнообразные варианты синтаксиса, 
	поэтому предоставление единого согласованного синтаксиса для всех случаев невозможно. 
	
	В этом разделе представлены разнообразные соглашения и компромиссы, 
	которые необходимо принимать во внимание при написании `фабричной функции` (`factory function`), 
	принимающей `произвольный набор типов аргументов`
	для создания `объекта типа, определяемого пользователем`:
*/
#include <utility>   	// 	std::forward
template <typename T, typename... ARGS>
T 	factory1(ARGS&&... args)
{
	return T(std::forward<ARGS>(args)...);   			// 	`Прямая инициализация`.
}
template <typename T, typename... ARGS>
T 	factory2(ARGS&&... args)
{
	return T{std::forward<ARGS>(args)...};   			// 	`Прямая списковая инициализация`.
}
template <typename T, typename... ARGS>
T factory3(ARGS&&... args)
{
	return {std::forward<ARGS>(args)...};   			// 	`Списковая инициализация копированием`.
}
/*
	Все три фабричные функции определяются 
	с использованием `полноценного перенаправления` (perfect forwarding), 
	но `поддерживают разнообразные подмножества типов` `C++` 
	и могут интерпретировать свои аргументы по-разному.
	
	Функция function1() возвращает значение, 
	созданное `прямой инициализацией`, 
	но, поскольку применяются (круглые скобки), 
	не может возвращать `агрегаты`, 
	за исключением особого случая, когда список `args` пуст 
	или содержит `ровно один аргумент` типа `T` или  
	типа, который можно преобразовать в `T`, 
	иначе попытка создания возвращаемого значения приведет к ошибке компиляции.
	
	Функция function2() возвращает объект, 
	созданный при помощи `прямой списковой инициализации`. 
	
	Следовательно, function2() поддерживает те же типы, что и function1(), плюс `агрегаты`. 
	
	Но из-за применения `инициализации с {фигурными скобками}` 
	function2() будет отвергать любые типы в ARGS, 
	для которых требуется `сужающее преобразование` 
	при `передаче в конструктор` (или для `инициализации члена агрегата`) 
	`возвращаемого значения`. 
	
	Кроме того, если передаваемые аргументы можно преобразовать в однотипный список std::initializer_list, 
	соответствующий конструктору для `T`, 
	то именно этот конструктор будет выбран вместо конструктора, 
	лучше всего соответствующего переданному списку аргументов.
 
	Функция function3() ведет себя так же, как function2(), 
	за исключением того, что использует `списковую инициализацию копированием`, 
	следовательно, будет возникать та же ошибка компиляции, 
	если выбранный конструктор или оператор преобразования для возвращаемого значения 
	объявлен как `explicit`.
 
	Не существует единственной верной формы инициализации, 
	работающей наилучшим образом во всех случаях для такой фабричной функции, 
	и разработчики библиотеки обязаны выбрать и задокументировать свой контракт для формы, 
	наилучшим образом удовлетворяющей потребности. 
	
	Следует отметить, что в стандартной библиотеке возникает та же проблема 
	при реализации фабричных функций, подобных std::make_shared(), 
	или функции emplace() для любого контейнера. 
	
	В `стандартной библиотеке` неизменно выбирается `инициализация с применением (круглых скобок)`, 
	как в функции function1() в приведенном выше примере кода, 
	поэтому `такие функции не работают с агрегатами` до версии `C++20`.
	
	----------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.2.5. Универсальная инициализация членов в обобщенном коде
 
	После добавления `обобщенной инициализации с применением {фигурных скобок}` 
	в стандарт `C++11` авторы классов обязаны дать ответ на вопрос, 
	должны ли конструкторы использовать `прямую инициализацию` или `прямую списковую инициализацию` 
	для своих баз и членов. 
	
	Обратите внимание: поскольку варианты `инициализации копированием` и `списковой инициализации копированием` 
	не рассматриваются, никогда не возникает вопроса о том, 
	объявлен ли как `explicit` конструктор для конкретной базы или члена или нет.
	
	До версии `C++11` было абсолютно невозможным написание кода, 
	инициализирующего агрегатные подобъекты, включая массивы, 
	набором данных, содержащимся в списке инициализации членов для конструктора. 
	
	Разрешалась только `инициализация по умолчанию`, 
	`инициализация значением` или `прямая инициализация` 
	из другого агрегата того же типа.
	
	Начиная с версии `C++11` появилась возможность 
	`инициализации агрегатных членов` с помощью `списка значений` 
	с использованием `агрегатной инициализации` 
	вместо `прямой списковой` для членов, которые `сами являются агрегатами`:
*/ 
struct S_aggr
{
	int 			i	=	1;		//	`Инициализация копированием`
    std::string 	str	=	"";		//	`Инициализация копированием`
};

