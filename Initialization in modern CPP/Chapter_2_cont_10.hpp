template <typename T>
bool		test_func(const T& t_param)
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << "; t_param == " << t_param << endl;
	
	return true;
}
#include <initializer_list>   	// 	std::initializer_list
template <typename T, typename U>
bool 	run_Test	(	bool 						(*test)(const T& t_param)
				, 	std::initializer_list<U> 		values
				)
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	for (const auto& val : values)
    {
        T 	obj 	= 	val;   			// 	Инициализация тестовым значением (`инициализация копированием`). 
		
		if (!test(obj))
        {
			return false;
        }
    }
	return true;
}
