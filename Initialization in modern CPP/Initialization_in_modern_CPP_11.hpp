/*
	****************************************************************************************************************
	Инициализация в `C++11`
	------------------------------------------------------------------------------------------------------------------------------------------------------------
	`Универсальная инициализация` (C++11)

	В версии С++11 было много очень важных изменений. 
	
	В частности, была введена `универсальная (uniform) инициализация`, 
	которую я предпочитаю называть «unicorn initialization» («инициализация-единорог»), 
	потому что она `просто волшебная`. 
	
	Давайте разберёмся, зачем она появилась.

	Как вы уже заметили, в С++ 
	`очень много различных синтаксисов инициализации`
	с `разным поведением`. 
	
	Множество неудобств вызывала проблема `досадного разбора` `vexing parse` или `most vexing parse`
	с `круглыми скобками`. 
	
	Ещё разработчикам не нравилось, что `агрегатную инициализацию` 
	можно было использовать `только с массивами`, 
	но не с контейнерами вроде std::vector. 
	
	Вместо неё приходилось выполнять .reserve() и .push_back(), 
	или пользоваться всякими `жуткими библиотеками`:
*/
void vector_before_c11()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	// 	вот так было нельзя, а хотелось:
	std::vector<int> 	vec_f = {0, 1, 2, 3, 4};

	// приходилось писать так:
	std::vector<int> 	vec;

	vec.reserve(5);

	vec.push_back(0);
	vec.push_back(1);
	vec.push_back(2);
	vec.push_back(3);
	vec.push_back(4);
}	
