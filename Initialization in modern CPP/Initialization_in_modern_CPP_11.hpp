#endif	
/*
	Мне кажется, что со стороны комитета С++ `std::initializer_list` 
	был `не самым удачным решением`. 
	
	От него больше вреда, чем пользы.

	Начнём с того, что `std::initializer_list` 	- 	это `вектор фиксированного размера` 
											с `элементами const`. 
	
	То есть `это тип`, 
	у него есть функции begin() и end(), 
	которые возвращают итераторы, 
	есть собственный тип итератора, 
	и `чтобы его использовать`, 
	нужно включать `специальный одноименный заголовок`. 
	
	Поскольку элементы `std::initializer_list` являются `const`, 
	его `нельзя перемещать`, 
	поэтому, если `T` в коде выше является типом `move-only`, 
	код не будет выполняться.

	Далее, `std::initializer_list` является `объектом`. 
	
	Используя его, мы, фактически, `создаём и передаём объекты`. 
	
	Как правило, компилятор может это оптимизировать, 
	но с точки зрения семантики 
	мы всё равно имеем дело с лишними объектами.

	Несколько месяцев назад в твиттере был опрос: 
	если бы можно было отправиться в прошлое и убрать что-либо из C++, что бы вы убрали? 
	
	Больше всего голосов получил именно `initializer_list`.

	Давайе разберёмся, как работает новый синтаксис. 
	
	Он вызывает конструкторы, 
	которые принимают на вход `initializer_list`, 
	и эти `вызовы создают много проблем` 
	по сравнению с `прямой инициализацией` в старом синтаксисе. 
	
	Часто приводят следующий пример:
*/
#if 0	
std::vector<int> 	v(3, 0); 		// 	вектор содержит 0, 0, 0
std::vector<int> 	v{3, 0}; 		// 	вектор содержит 3, 0
#endif	
/*
	Если вызвать `vector` с `двумя аргументами` `int` 
	и использовать `прямую инициализацию`, 
	то выполняется вызов конструктора, 
	который `первым аргументом` принимает `размер вектора`, 
	а `вторым` - `значение элемента`. 
	
	На выходе получается вектор из трёх нулей. 
	
	Если же вместо `круглых скобок` написать `фигурные`, 
	то используется `initializer_list` 
	и на выходе получается вектор из двух элементов, 3 и 0.

	Есть примеры ещё более странного поведения этого синтаксиса:
*/
#if 0	
std::string 		s (48, 'a'); 	// 	"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
std::string 		s {48, 'a'}; 	// 	"0a"
#endif	
/*
	В первой строке создаётся строка из 48 символов «а», 
	а во второй строка «0а». 
	
	Это происходит потому, что во втором случае конструктор `string` 
	принимает на вход `initializer_list` из символов. 
	
	`48` является целочисленным значением, 
	поэтому оно преобразуется в символ. 
	
	В ASCII число `48` - код символа «0». 
	
	Это очень странно, потому что есть конструктор, 
	принимающий именно такие аргументы, `int` и `char`. 
	
	Но вместо вызова этого конструктора 
	происходит `совершенно неочевидное` преобразование. 
	
	В итоге получается код, 
	который чаще всего ведёт себя не так, 
	как мы ожидаем.

	Ещё больше трудностей возникает при `использовании шаблонов`. 
	
	Как вы думаете, что возвращает эта программа? Какой здесь размер вектора?
*/
template <typename T, size_t N>
auto test_template() {
	return std::vector<T>{N};
}

void test_of_test_template () {
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	int result 	= test_template<std::string, 3>().size();
	cout << result << endl;
	result 		= test_template<int, 3>().size();
	cout << result << endl;
}
/*
	Мы получим `вектор с тремя строками`, 
	то есть ответ - `3`. 
	
	Но если `string` заменить на `int`, ответ будет `1`, 
	потому что для std::vector<std::int> будет использован `initializer_list`. 
	
	В зависимости от `шаблонного параметра` 
	вызывается либо конструктор initializer_list, 
	либо другой конструктор. 
	
	А если вместо string или int использовать float, я и вовсе не знаю, что выйдет. Предсказать поведение такого кода очень сложно, и это создаёт множество неудобств. Например, мы не можем написать emplace функцию, которая работала бы для агрегатных типов с синтаксисом фигурных скобок. В общем, агрегатная инициализиация и синтаксис {} не работают с шаблонами.

	Теперь давайте разберёмся, что именно делает `инициализация списком`.

	Для `агрегатных типов` при такой инициализации выполняется `агрегатная инициализация`.

	Для `встроенных типов` - `прямая инициализация` 	({a}) 
	или
	`копирующая инициализация` 						(= {a});

	А `для классов` выполняется такая последовательность:

	Вначале «жадно» `выполняется вызов конструктора`, который принимает `std::initializer_list`.
	
	Если для этого вызова необходимо сделать неочевидные преобразования - они выполняются.

	Если подходящего конструктора нет, 
	выполняется `обычный вызов конструктора` () 
	при помощи `разрешения перегрузки`.

	Для второго шага есть пара исключений.

	Исключение 1: при использовании = {a}, когда в списке один элемент `a`,
	может быть использована `инициализация копированием`.

	Исключение 2: `пустые фигурные скобки`, {}.
	
	Пусть у нас будет тип с `конструктором по умолчанию` и 
	`конструктором, который принимает `initializer_list``.

	Что происходит при вызове Widget<int> 	widget{}?
*/
template <typename T>
struct Widget_with_init_list {
	int m_test = 111;
#if 1	
	Widget_with_init_list	()	= default;
#endif		
#if 1	
	Widget_with_init_list	(T  param)	{
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
		m_test = 10 * param;
	}
	
#endif	
#if 0	
	Widget_with_init_list	(std::initializer_list<T> param)	{
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
		m_test = 100 * (*param.begin());
	}
#endif		
};

void initializer_list_test_1() {
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	// 	какой конструктор будет вызван?
	Widget_with_init_list<int> 	widget_1{11}; 	
	cout << " First case - m_test == " << widget_1.m_test << endl;
	
	Widget_with_init_list<int> 	widget_2{42}; 	
	cout << " Second case - m_test == " << widget_2.m_test << endl;
}
