/*
	*******************************************************************************************************************
	2.4. 	Синтаксис `инициализации с использованием фигурных скобок`: {}	-	 Braced-Initialization Syntax: {}
 
	Инициализация с использованием {фигурных скобок} – 
	`обобщение синтаксиса инициализации` по стандарту C++03 – 
	была спроектирована с намерением обеспечить 
	`безопасное и универсальное` его применение 
	в `любом контексте инициализации`.	
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.1. 	Описание
	
	'Списковая инициализация` (`list initialization`), 
	изначально названная `унифицированной инициализацией` (`uniform initialization`), 
	использует для этой цели {фигурные скобки}, 
	поэтому неформально упоминается как `инициализация с применением фигурных скобок` (`braced-Initialization`)
	и иногда используется в тесном взаимодействии 
	с шаблоном стандартной библиотеки C++ 
	`std::initializer_list`. 
	
	`Инициализация с применением фигурных скобок`  (`braced-Initialization`)
	предназначена для предоставления `универсального синтаксиса инициализации объектов`
	независимо 
	
	(1) 	от контекста, в котором используется этот синтаксис, 
	или 
	(2) 	от типа инициализируемого объекта. 
	-------------------------------------------------------------------------------------------------------------------------------------------------------------------
*/	
/*
	*****************************************************************************************************************
	2.4.3. Потенциальные опасности
	-------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.3.1. 	Непреднамеренный вызов конструкторов списков инициализаторов
	
	Классы с `конструкторами списков std::initializer_list` 
	подчиняются некоторым особым правилам 
	для `устранения неоднозначности` при `разрешении перегрузки`, 
	которые скрывают в себе `малозаметные опасности` для `неопытных программистов`. 
	
	В этом разделе описано, как при `разрешении перегрузки` 
	подобные конструкторы могут быть выбраны или проигнорированы такими способами, 
	которые могут оказаться неожиданными.
	
	Когда объект `инициализируется с применением {фигурных скобок}`, 
	компилятор в первую очередь выполняет поиск конструктора списка std::initializer_list, 
	который можно вызвать, с единственным исключением – 
	если `список в {фигурных скобках}` `пуст`, 
	то `конструктор по умолчанию`, если он доступен, 
	должен `иметь приоритет`:
*/
struct S_3_ctors
{
	explicit 	S_3_ctors() { 
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	}
	explicit 	S_3_ctors(int int_param) { 
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << " int_param == " << int_param << endl;
	}
 
	S_3_ctors(std::initializer_list<int> 	iL) { 
		cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
		if (0 == iL.size()) 
		{ 
			throw 13; 
		} 
		for (auto el_l : iL)
			cout << el_l << "  ";
		cout << endl;
	}
};
void		S_3_ctors_test()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	S_3_ctors 	a{};             	// 	OK: `инициализация значением` -  `конструктор по умолчанию`
	//	S_3_ctors 	b = {};          	// 	Ошибка: `конструктор по умолчанию` объявлен как `explicit`.
	S_3_ctors 	c{1};            	// 	OK: std::initializer_list.
	S_3_ctors 	d = {1};         	// 	OK: std::initializer_list.
	S_3_ctors 	e{1, 2, 3};      	// 	OK: std::initializer_list.
	S_3_ctors 	f = {1, 2, 3};  	// 	OK: std::initializer_list.
}	
/*
	При наличии `конструкторов списка инициализаторов` 
	`разрешение перегрузки` для выбора вызываемого конструктора 
	представляет собой `двухэтапный процесс`. 
	
	Сначала рассматриваются все `конструкторы списка инициализаторов`, 
	и только если не найден подходящий конструктор std::initializer_list, 
	происходит обращение к прочим конструкторам, 
	не создающим список инициализаторов. 
	
	Этот процесс имеет некоторые последствия, 
	возможно неожиданные, 
	поскольку разрешены `неявные преобразования` 
	при поиске `соответствия для перегрузки`. 
	
	Существует вероятность того, что будет выбран конструктор std::initializer_list, 
	`требующий неявного преобразования`, 
	вместо `конструктора, не имеющего отношения к списку инициализации`, 
	который не требует какого-либо преобразования:
*/
struct S_many_ctors
{
	// 	(1)
    S_many_ctors	(std::initializer_list<int>)   	
	{cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}
	
	// 	(2)
    S_many_ctors	(int i, char c)                	
	{cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}
	/*
		Из-за `инициализации с {фигурными скобками} 
		более предпочтительными являются `конструкторы списка инициализации`, 
		поэтому `S_many_ctors` содержит конструктор `initializer_list`, 
		который может соответствовать инициализатору `s1`,
		а конструктор, `в большей степени подходящий в противном случае`, 
		не рассматривается.
		
		Еще одно, возможно, `неожиданное последствие` 
		связано с проверкой на `сужающее преобразование` 
		только `после выбора конкретного конструктора`. 
		
		Таким образом, `конструктор initializer_list`, 
		который подходит для инициализации, 
		но требует `сужающего преобразования`, 
		приведет к ошибке даже при наличии конструктора, 
		не создающего список инициализации, 
		который должен был бы стать более подходящим 
		без обязательного требования `сужающего преобразования`:
	*/
	// 	(3)
	S_many_ctors	(int i, double d)                	
	{cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}
	/*
		Из-за `инициализации с {фигурными скобками}` 
		`сначала выбирается конструктор`, 
		а `затем` выполняется `проверка на сужающее преобразование`.
		
		Конструктор, `не создающий список инициализации` и `не требующий сужающего преобразования`, 
		"не рассматривается".
	*/
};

void		S_many_ctors_test()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;

	S_many_ctors 	s1{1, 'a'};   	// 	Вызывается вариант (1), даже притом что (2) `не требует преобразований`.
	//S_many_ctors 	s2{1, 3.2};   	//	error: narrowing conversion of '3.20000002e+0' from 'double' to 'int' [-Wnarrowing]
	S_many_ctors 	s3(1, 3.2);
	S_many_ctors 	s4(1, 'a');
	/*
		Обе описанные выше проблемы можно решить, 
		используя (круглые скобки) или другие формы инициализации, 
		отличающиеся от `списков в {фигурных скобках}`, 
		поскольку их невозможно интерпретировать как `списки типа initializer_list`:
	*/
	// 	Этот вариант решения часто применяется при работе с std::vector:
	std::vector<char> 	v{std::size_t(3), 'a'};   	// 	Содержит 2 элемента: '\x03' 'a'.
	
	for (auto vec_element : v)
		cout << vec_element << "  ";
	cout << endl;
	
	std::vector<char> 	w(std::size_t(3), 'a');   	// 	Содержит 3 элемента: 'a' 'a' 'a'.
	
	for (auto vec_element : w)
		cout << vec_element << "  ";
	cout << endl;
}
/*
	В приведенном выше фрагменте кода для переменной `v` 
	в результате перегрузки выбирается `конструктор списка std::initializer_list<char>`, 
	даже притом что создается вектор с заданным количеством элементов, 
	например std::size_t(3), содержащий конкретное значение, 
	например 'a', который абсолютно точно соответствует аргументам. 
	
	Напротив, `прямая инициализация` переменной `w` в том же фрагменте кода 
	не рассматривает конструктор std::initializer_list<char>, 
	и в результате `w` содержит три элемента со значением 'a'.
*/
/*
	------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.3.2. 	Неявное перемещение и оптимизация `именованного возвращаемого значения` 
			`могут быть запрещены` в инструкциях `return`
			
	Применение `дополнительных {фигурных скобок}`, 
	окружающих значение в инструкции `return`, 
	может запретить `оптимизацию именованного возвращаемого значения` 
	или `неявное перемещение в возвращаемый объект`. 
	
	`Оптимизация именованного возвращаемого значения` (named return value optimization – NRVO) – 
	это оптимизация, которую разрешено выполнять компиляторам, 
	когда операндом инструкции `return` является только конкретное имя 
	(т.е. id-выражение, выражение-идентификатор) неизменяемой локальной переменной 
	(т.е. объекта с автоматической продолжительностью хранения, 
	который не является параметром функции или конструкции `catch`), 
	а тип ее без учета `cv-квалифицирования` совпадает с `возвращаемым типом` функции. 
	
	В таких случаях компилятору разрешено игнорировать копию, 
	подразумеваемую возвращаемым выражением. 
	
	Как правило, такая оптимизация применяется только к функциям, 
	`возвращающим объекты`, но `не указатели или ссылки`.
 
	Следует отметить, что эта оптимизация допускается для изменения смысла программ, 
	которые могут полагаться на очевидные побочные эффекты в игнорируемых копирующих конструкторах. 
	
	Большинство современных компиляторов способны выполнить такую оптимизацию 
	по крайней мере в простых условиях, как, например, 
	если существует только одно возвращаемое выражение для всей функции в целом.
 
	В приведенном ниже примере можно видеть, 
	что функция notBraced() выполняет возврат, 
	используя имя локальной переменной, 
	созданной в ее теле. 
	
	При вызове notBraced() мы получаем возможность наблюдать при выполнении оптимизации компилятором, 
	что создается только один объект класса `S` с использованием его конструктора по умолчанию. 
	
	Не выполняется копирование, перемещение, не создается другой объект. 
	
	По существу, локальная переменная `a` внутри функции notBraced() 
	создается непосредственно в области памяти переменной `m1` в основной функции main().
	
	В функции braced() мы используем ту же локальную переменную, 
	но в инструкции `return` берем ее имя в {фигурные скобки}, 
	следовательно, операнд этой инструкции уже не является именем (т.е. id-выражением), 
	поэтому правила, разрешающие `NRVO`, здесь не применимы. 
	
	При вызове braced() мы видим, что теперь создаются две копии и два объекта – 
	первым является `a`, локальная переменная, использующая `конструктор по умолчанию`, 
	вторым – переменная `m2`, созданная как `копия` `a`, – 
	это подтверждает, что `NRVO` не действует:
*/
struct S_NRVO
{
    S_NRVO()          		{ cout << "S_NRVO()\n"; }
    S_NRVO(const S_NRVO &) 	{ cout << "S_NRVO(copy)\n"; }
    S_NRVO(S_NRVO &&)      	{ cout << "S_NRVO(move)\n"; }
};
S_NRVO notBraced()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
    S_NRVO 	a;
	return 	a;						// 	НЕ запрещает NRVO.
}
S_NRVO braced()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	S_NRVO 	a;
	return 	{ a };   				// 	Запрещает NRVO
}
S_NRVO moved()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
    S_NRVO 	a;
	return 	std::move(a);			// 	Запрещает NRVO
}
void NRVO_test()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
    S_NRVO 	m1 	= 	notBraced();   	// 	S_NRVO().
    S_NRVO 	m2 	= 	braced();      	// 	S_NRVO(), S_NRVO(copy).
	S_NRVO 	m3 	= 	moved();      	// 	S_NRVO(), S_NRVO(move).
} 
/*
	`Неявное перемещение` в инструкции `return`
	является весьма малозаметной операцией, 
	замаскированной так, что потребовался отчет о дефектах, 
	эта работа выполнялась, как было задумано. 
	
	Мы демонстрируем `неявные перемещения` в инструкции `return` из `локальной переменной`, 
	используя два типа. 
	
	Класс типа `L_for_move` будет использоваться для локальной переменной, 
	а класс типа `R_for_move`, который может быть создан `перемещением` или `копированием из `L_for_move`, 
	применяется как `возвращаемый тип`. 
	
	По существу, мы `принудительно` выполняем `преобразование типов` в `инструкции return`, 
	которая может быть копированием или перемещением:
*/
struct 	L_for_move
{
    L_for_move() { cout << "L_for_move()\n"; }
};
struct R_for_move
{
    R_for_move(const L_for_move &) { cout << "R_for_move(L_for_move		–	copy)\n"; }
    R_for_move(L_for_move &&)      { cout << "R_for_move(L_for_move	–	move)\n"; }
};
R_for_move 	r_notBraced()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	L_for_move 	a;
	return 		a;
}
R_for_move r_braced()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
    L_for_move 	a;
	return 		{ a };   	// 	Запрещает неявное перемещение из `L_for_move`
}
void 	NRVO_test_2()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
    R_for_move 	r1 	= 	r_notBraced();   	// 	L_for_move(), R_for_move(L_for_move–перемещение).
    R_for_move 	r2 	= 	r_braced();      	// 	L_for_move(), R_for_move(L–копия).
}
/*
	Функция r_notBraced() просто создает локальную переменную и возвращает ее. 
	 
	При вызове этой функции мы видим, что создается объект `L_for_move`, 
	который затем перемещается в объект `R_for_move`. 
	
	Обратите внимание: положение стандарта `C++` разрешает такое `неявное перемещение`, 
	только если операнд инструкции `return` является `именем`, т.е. id-выражением.
	
	Функция r_braced() почти идентична функции r_notBraced(), 
	за исключением добавления {фигурных скобок}, 
	окружающих `операнд инструкции return`. 
	
	Вызов этой функции показывает, 
	что перемещаемое из `L_for_move` `возвращаемое выражение` 
	превратилось в `копируемое` из `L_for_move`, 
	потому что инициализатор в {фигурных скобках} 
	не является `именем какого-либо объекта`.
*/ 
