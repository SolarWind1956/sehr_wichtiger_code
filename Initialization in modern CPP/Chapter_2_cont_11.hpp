/*
	---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.3.3. 	Неожиданное поведение агрегатов, содержащих `удаленные конструкторы`
	
	`Инициализация агрегатов` значением разрешена 
	с применением `списка инициализаторов в {фигурных скобках}`, 
	даже если `конструктор по умолчанию` является `удаленным`.
	
	Следует отметить, что стандарт `C++20` окончательно решает проблему, 
	из-за которой `наличие удаленных конструкторов` приводит к тому, 
	что класс `перестает классифицироваться` как `агрегат`.
*/
struct 	S_aggregate
{
	int 		data;
    S_aggregate() = delete;   		// 	Не должен быть "пустым".
	S_aggregate(int data_) : data(data_)
	{}
};
void S_aggregate_test() {
	//S_aggregate 	s{};   				// 	Работает неожиданным образом (до версии C++20), и 0 == s.data.
			//	error: use of deleted function 'S_aggregate::S_aggregate()'
	/*
		Эта неожидаемая опасность возникает по двум причинам:
		
		1) 	`удаленный конструктор` является объявленным, 
			но `не предоставленным пользователем`, 
			поэтому не нарушает требований, согласно которым класс считается `агрегатом`;
			
		2) 	правила утверждают, что `инициализация агрегата`
			определяется не по критериям конструкторов, 
			а `непосредственно по критериям инициализации его членов`.
	*/
	S_aggregate 	s1(11);
	cout << "S_aggregate s1(11); s1.data == " << s1.data << endl; 
	
	S_aggregate 	s2{11};
	cout << "S_aggregate s2{11}; s2.data == " << s2.data << endl; 
}	
