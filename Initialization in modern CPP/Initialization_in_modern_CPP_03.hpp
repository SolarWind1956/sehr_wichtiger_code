/*
	****************************************************************************************************************
	Инициализация в `C++03`
	----------------------------------------------------------------------------------------------------------------------------------------------------
	`Инициализация значением` (C++03)

	Перейдём к следующей версии - С++03. 
	
	Принято считать, что существенных изменений в этой версии не произошло, 
	но это не так. 
	
	В С++03 появилась `инициализация значением` (value initialization), 
	при которой пишутся `пустые круглые скобки`:
*/
#if 0	
int main() {
  return 	int(); 	// 	UB в C++98, 0 начиная с C++03
}
#endif	
/*
	В С++98 здесь возникает `неопределенное поведение`, 
	потому что происходит `инициализация по умолчанию`, 
	а начиная с С++03 эта программа возвращает `нуль`.

	Правило такое: 	если существует `определённый пользователем` `конструктор по умолчанию`, 
					`инициализация значением` вызывает этот конструктор, 
					в противном случае возвращается `нуль`.

	Рассмотрим подробнее ситуацию с пользовательским конструктором:
*/
#if 0	
struct Widget {
	int 	i;
};

Widget 	get_widget() {
	return 	Widget();  	// 	value initialization - `инициализция значением`
}

int main() {
	return get_widget().i;
}
#endif	
/*
	В этой программе функция инициализирует 	`значение` для нового `Widget` и возвращает его. 
	
	Мы вызываем эту функцию и обращаемся к элементу `i` объекта `Widget`. 
	
	Начиная с C++03 `возвращаемое значение` здесь `нуль`, 
	поскольку нет `пользовательского конструктора по умолчанию`. 
	
	А если такой конструктор существует, 
	но `не инициализирует` `i`, 
	то мы получим `неопределённое поведение`:
*/
#if 0	
struct Widget {
	Widget() {}   	// 	пользовательский конструктор
	int 	i;			//	не инициализирует данные-члены
};

Widget 	get_widget() {
  return Widget();  	// 	value initialization
}

int main() {
  return get_widget().i;    	// 	значение `не инициализировано`, происходит `UB`
}
#endif
/*
	Стоит заметить, 
	что «пользовательский» 
	не значит 
	«определённый пользователем». 
	
	Это значит, что `пользователь должен предоставить` `тело конструктора`, 
	т.е. {фигурные скобки}. 
	
	Если же в примере выше `заменить` `тело конструктора` на `= default` 
	(эта возможность была добавлена в С++11), 
	смысл программы изменяется. 
	
	Теперь мы имеем конструктор, `определённый пользователем` (user-defined), 
	но `не предоставленный пользователем` (user-provided), 
	поэтому программа возвращает `нуль`:
*/
#if 0	
struct 	Widget {
	Widget() 	= 	default;   	// 	`user-defined`, но 
								//	не `user-provided`
	int 		i;
};

Widget 	get_widget() {
	return 	Widget();      		// 	value initialization
}

int main() {
	return 	get_widget().i;    	// 	возвращает 0
}
#endif
/*
	Теперь попробуем вынести 	`Widget() = default` 
	за рамки класса. 
	
	Смысл программы снова изменился: 
	`Widget() = default` считается `предоставленным пользователем конструктором`, 
	если он находится `вне класса`. 
	
	Программа снова возвращает `неопределённое поведение`.
*/
#if 0	
struct 	Widget {
	Widget();
	int 	i;
};

Widget::Widget() 	= 	default; 	//  	вне класса, считается `user-provided` - предоставленный пользователем

Widget 	get_widget() {
	return 	Widget();      			// 	value initialization
}

int main() {
	return 	get_widget().i;    		// 	`снова` значение `не инициализировано`, `UB`
}
#endif
/*
	Тут есть `определённая логика`: 
	`конструктор, определённый вне класса`, 
	может быть `внутри другой единицы трансляции`. 
	
	`Компилятор может не увидеть` этот `конструктор`, 
	поскольку он может быть `в другом файле` .cpp. 
	
	Поэтому делать какие-либо выводы о таком конструкторе компилятор не может, 
	и он не может отличить 
	`конструктор с телом` 
	от 
	`конструктора с = default`.

	

*/

