/*
	Для `скалярных типов` `инициализация по умолчанию` в действительности `не инициализирует объект`, 
	а `инициализация значением` `инициализирует объект` якобы `литералом 0`. 
	
	Следует отметить, что представление этого значения не обязательно содержит все нулевые биты, 
	так как некоторые платформы используют различные значения 
	внутренних аппаратных прерываний-ловушек 
	для нулевых значений указателей и объектов «указатель на член».
	
	Для класса, содержащего доступный `предоставленный пользователем` `конструктор по умолчанию`, 
	оба 	`типа инициализации` ведут себя одинаково, вызывая `конструктор по умолчанию`. 
	
	Если такой `конструктор по умолчанию` недоступен, 
	то обе формы являются неправильно сформированными (ill-formed). 
	
	Для объектов типов классов, содержащих `неявно определенный` `конструктор по умолчанию`, 
	каждый `базовый подобъект` и `подобъект-член` 
	будет `инициализирован по умолчанию` или 
	`значением в соответствии с формой инициализации`, 
	указанной для всего объекта в целом. 
	
	Если какая-либо из этих инициализаций приводит к ошибке, 
	то программа является `неправильно сформированной`. 

	Обратите внимание: 
	когда "объединение" (union) с `неявно определенным` `конструктором по умолчанию` 
	инициализируется `значением`, 
	то первый член этого объединения будет инициализирован значением как его активный член:
*/ 
struct B_default_a_value_init	{
	int 		i;
	// 	Предоставленный пользователем конструктор по умолчанию:
    B_default_a_value_init() : i() { cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}   
							//	`i` `инициализируется значением`.
};

struct C_default_a_value_init	{
	int 		i;				// 	`i` `инициализируется по умолчанию`.
	// 	Предоставленный пользователем конструктор по умолчанию:
    C_default_a_value_init() { cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}   
};

// 	Производный класс без конструкторов, предоставленных пользователем. 
struct D_default_a_value_init : B_default_a_value_init 	{ 	
	int 	j; 
};  

