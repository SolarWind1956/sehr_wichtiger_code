/*
	*******************************************************************************************************************
	2.4. 	Синтаксис `инициализации с использованием фигурных скобок`: {}	-	 Braced-Initialization Syntax: {}
 
	Инициализация с использованием {фигурных скобок} – 
	`обобщение синтаксиса инициализации` по стандарту C++03 – 
	была спроектирована с намерением обеспечить 
	`безопасное и универсальное` его применение 
	в `любом контексте инициализации`.	
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.1. 	Описание
	
	'Списковая инициализация` (`list initialization`), 
	изначально названная `унифицированной инициализацией` (`uniform initialization`), 
	использует для этой цели {фигурные скобки}, 
	поэтому неформально упоминается как `инициализация с применением фигурных скобок` (`braced-Initialization`)
	и иногда используется в тесном взаимодействии 
	с шаблоном стандартной библиотеки C++ 
	`std::initializer_list`. 
	
	`Инициализация с применением фигурных скобок`  (`braced-Initialization`)
	предназначена для предоставления `универсального синтаксиса инициализации объектов`
	независимо 
	
	(1) 	от контекста, в котором используется этот синтаксис, 
	или 
	(2) 	от типа инициализируемого объекта. 
	
	Как мы увидим в дальнейшем, эта цель проектирования в общем и в целом была достигнута, 
	хотя и с некоторыми особенностями и недоработками.
 
	-------------------------------------------------------------------------------------------------------------------------------------------------------------------
	2.4.1.1. 	Обзор `синтаксиса инициализации` по стандарту C++03
 
	`Классическая версия` C++ предоставляет `несколько форм инициализации` 
	с `собственным синтаксисом`, 
	и `некоторые из этих форм` `синтаксически взаимозаменяемы`, 
	хотя и с малозаметными тонкими различиями. 
	
	На самом высоком уровне существуют 
	`две парные` `категории инициализации`:
	
	1) 	(инициализация) `копированием` /  `прямая`, когда имеется `как минимум один` инициализатор;
	
	2) 	`по умолчанию` /  `значением`, когда недоступен ни один инициализатор.
	
	---------------------------------------------------------------------------------------------------------------------------------------------------------------
	Первую `парную` категорию составляют 
	`инициализация копированием` (copy initialization) 
	и 
	`прямая инициализация` (direct initialization). 
	
	`Инициализация копированием`	действует, когда `задано значение без круглых скобок`, 
									справа от знака равенства `=`
									как при передаче аргумента в функцию 
									или при возврате значения из функции. 
	
	`Прямая инициализация`  	выполняется при инициализации объекта одним или несколькими аргументами 
							в круглых скобках (), 
							например при инициализации члена данных или базового класса 
							в списке инициализаторов конструктора или в выражении `new`. 
							
	Обе формы можно использовать для инициализации переменной:
*/
void copy_initialization_and_direct_initialization_test_1()
{
	int 	i 	= 	23;   	// 	Инициализация `копированием` 	(copy_initialization)
	int j(23);    		// 	`Прямая` инициализация 			(direct_initialization)
}
/*
	В приведенном примере в обоих случаях инициализируется переменная – 
	`i` или `j` – `литеральным значением` (`literal value`).
	
	---------------------------------------------------------------------------------------
	Для простых `скалярных типов` (`scalar types`) 
	нет каких-либо заметных различий между этими двумя парными формами инициализации в C++03, 
	но для `типов, определенных пользователем` (`user-defined types`), различие существует. 
	
	Во-первых, `прямая инициализация` 
	рассматривает все допустимые 
	`определенные пользователем последовательности преобразования`
	(`user-defined conversion sequences`)
	как часть `набора перегрузки` (` overload set`), 
	тогда как `инициализация копированием` исключает `явные преобразования` (`explicit conversions`):
*/
struct S_copy_a_direct_init
{
	explicit 	S_copy_a_direct_init(int)							// 	Явный конструктор значения (из int)
				{cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}
				
				S_copy_a_direct_init(double)						// 	Неявный конструктор значения (из double)
				{cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;}
				
				S_copy_a_direct_init(const S_copy_a_direct_init&)	// 	Неявный конструктор копирования.
				{cout << "----- COPY CTOR ----- I'm " <<  __PRETTY_FUNCTION__  << endl;}
};
void user_defined_conversion_sequences_test()
{	
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	
	S_copy_a_direct_init 		s1(1);    	// 	`Прямая инициализация` s1: вызывает S(int); 
										//	конструктор копирования не вызывается.
									
	S_copy_a_direct_init 		s2(1.0);  	// 	`Прямая инициализация` s2: вызывает S(double);
										//	конструктор копирования не вызывается.
										
	S_copy_a_direct_init 		s3 = 1;   	// 	`Инициализация копированием` s3: вызывает S(double); 
										//	неявное преобраование `int` в `double`
										//	конструктор копирования может быть вызван
										//	но не был вызван - а почему?
										//	Потому что компилятор имеет право это делать - смотри ниже.
										
	S_copy_a_direct_init 		s4 = 1.0;  	// 	`Инициализация копированием` s4: вызывает S(double); 
										//	конструктор копирования может быть вызван
										//	но не был вызван - а почему?
										//	Потому что компилятор имеет право это делать - смотри ниже.
} 
/*
	В приведенном выше примере `исключение явных преобразований` для `инициализации копированием` 
	проявляется в инициализации `s1`, вызывающей конструктор, отличающийся от инициализации  `s3`. 
	
	Более того, `инициализация копированием` определяется 
	как `создание временного объекта`, 
	компилятору разрешено `исключать это временное значение`, 
	что на практике обычно и происходит. 
	
	Но обратите внимание: `инициализация копированием` не разрешена, 
	если нет `доступного конструктора копирования` или `конструктора перемещения`, 
	даже если временный объект был бы исключен. 
	
				В C++17 `гарантированное исключение копии` (guaranteed copy elision) 
				отбрасывает `операцию создания временного объекта` 
				и избавляется от необходимости в какой-либо 
				`доступной копии` 
				или 
				`конструкторе перемещения`.

	Если `конструктор перемещения` для определяемого пользователем типа объявлен, 
	но недоступен, `инициализация копированием` `сформирована неправильно`. 
	
	Следует отметить, что `аргументы функций` и `возвращаемые значения` 
	инициализируются с использованием `инициализации копированием`.
	
	Для `ссылочных типов` также применяются `инициализация копированием` и `прямая инициализация` 
	со `связыванием` `объявленной ссылки` с `объектом` или `функцией`. 
	
	Для `ссылки lvalue` на тип `без квалификатора const` 
	`ссылочный тип` обязательно должен `точно совпадать` или `являться производным` от `этого типа`.

	Но если ссылка `rvalue` или `lvalue` 
	связывается с типом `с квалификатором const`, 
	то компилятор `инициализирует копию` как `временный объект` `целевого типа исходной ссылки` 
	и `связывает` эту `ссылку` с `созданным временным объектом`. 
	
	В подобных случаях `время жизни такого временного объекта` 
	увеличивается `до конца времени жизни самой ссылки`:
*/ 
void copy_initialization_and_direct_initialization_test_2()
{
	int 			i 	= 	0;           	// 	OK: `инициализация копии` типа `int`.
	int& 		x(i);           		// 	OK: `прямая инициализация` `ссылки`.
	const long& 	y 	= 	x;   			// 	OK: `y` связывается с `временным объектом`, 
										//	время жизни которого увеличивается.
										//	`Временный объект` - это, видимо, `указатель на переменную`
	//long& 		z 	= 	x;         		// 	Ошибка: несовместимые типы.
								//	error: cannot bind non-const lvalue reference of type 'long int&' to a value of type 'int'
	int			j	=	42;
	const long& 	w 	= 	j;				//	ОК: потому что  `const long& 	w`
	
	const int& 	q(j);
	const long& 	v 	= 	q;				//	ОК: потому что  `const long& 	v`
	
	const int	k	=	142;
	const int& 	p(k);
	const long& 	u 	= 	p;				//	ОК: потому что  `const long& 	u`
	
	//	Тут как бы имеет место `константная ссылка` одного типа на `константный объект` другого типа
}
/*
	---------------------------------------------------------------------------------------------------------------------------------------------------------------
	`Вторая` `парная категория` включает 
	`инициализацию по умолчанию` (`default initialization`) 
	и 
	`инициализацию значением` (`value initialization`). 
	
	Оба вида инициализации относятся к ситуациям, 
	в которых `инициализатор не указывается`, 
	и эти `типы инициализации` 
	различаются по `наличию` или `отсутствию`
	`круглых скобок` (`parentheses`), в том числе, `пустых круглых скобок` (`empty parentheses`): 
	
	-	`отсутствие круглых скобок` означает `инициализацию по умолчанию`, 
	а 
	-	`присутствие круглых скобок` – `инициализацию значением`.
	
	В `простых контекстах` `прямой инициализации`, например `при объявлении переменной`, 
	`пустые круглые скобки` также могут означать `объявление функции`, 
	а `не инициализацию`. 
	
	int 	j();
	
	Тогда на помощь приходит знак равенства `=`, и имеет место инициализация `значением`.
	
	int 	j =	int();
*/ 
