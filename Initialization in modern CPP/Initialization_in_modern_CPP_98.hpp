/*
	****************************************************************************************************************
	Инициализация в `С++98`
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	`Прямая` инициализация (С++98)

	Перейдём теперь к `С++98`. 
	
	Пожалуй, наиболее важная возможность, отличающая С++ от `С` - это `конструкторы`. 
	
	Вот пример вызова конструктора:
*/
#if 0	
	Widget 	widget(1, 2);
	int(3);
#endif		
/*
	При помощи этого же синтаксиса можно инициализировать встроенные типы вроде `int` и `float`.

	Этот синтаксис называется `прямой инициализацией`. 
	
	Она выполняется всегда, когда у нас есть `аргумент в (круглых скобках)`.

	Для `встроенных типов` (`int`, `bool`, `float`) 
	`никакого отличия` от `копирующей инициализации`
	здесь нет. 
	
	Если же речь идёт о `пользовательских типах`, 
	то, в отличие от `копирующей инициализации`, 
	при `прямой инициализации` 
	можно передавать `несколько аргументов`. 
	
	Собственно, ради этого прямую инициализацию и придумали.

	Кроме того, при `прямой инициализации` 
	"не выполняется" `последовательность преобразования`. 
	
	Вместо этого происходит `вызов конструктора` при помощи 
	`разрешения перегрузки` (overload resolution). 
	
	У `прямой инициализации` тот же синтаксис, 
	что и у `вызова функции`, 
	и используется та же логика, что и в других функциях С++.

	Поэтому в ситуации с `explicit конструктором` 
	`прямая инициализация` работает нормально, 
	хотя `копирующая инициализация` выдаёт ошибку:
*/
#if 0	
struct Widget {
	explicit 	Widget(int) {}
};

Widget 	w1 	= 	1; 	// 	ошибка
Widget 	w2(1);  	// 	а так можно
#endif
/*
	В ситуации же с `двумя конструкторами`, 
	один из которых `explicit`, 
	а второй `хуже подходит по типу`, 
	при `прямой инициализации` вызывается `первый`, 
	а при `копирующей` - `второй`. 
	
	В такой ситуации `изменение синтаксиса` 
	приведёт к `вызову другого конструктора` - об этом часто забывают:
*/
#if 0	
struct 	Widget {
	explicit 	Widget(int) 		{}
				Widget(double) 	{}
};

Widget 	w1 	= 	1; 		// 	вызывает Widget(double)
Widget 	w2(1);  		// 	вызывает Widget(int)
#endif	
/*
	`Прямая инициализация` применяется всегда, 
	когда используются `круглые скобки`, 
	в том числе когда используется `нотация вызова конструктора для инициализации временного объекта`, 
	а также в выражениях `new` с `инициализатором в скобках` и в выражениях `cast`:
*/
#if 0	
useWidget(Widget(1, 2));                		// 	вызов конструктора
auto * 	widget_ptr 	= 	new 	Widget(2, 3);   	// 	new-expression with (args)
static_cast<Widget>(thingy);            		// 	cast
#endif	
/*
	Этот синтаксис существует столько, сколько существует сам С++, 
	и у него есть `важный недостаток`: 
	the most vexing parse. 
	
	Это значит, что 
	`всё, что компилятор может прочитать как "объявление"(declaration), 
	он читает именно как "объявление".

	Рассмотрим пример, в котором есть класс `Widget` и класс `Thingy`, 
	и конструктор `Thingy`, который получает `Widget`:
*/
#if 0	
struct 	Widget 
{};

struct 	Thingy {
	Thingy(Widget) {}
};

int main () {
	Thingy 	thingy(Widget());	//	`Объявление функции`
}
#endif
/*
	На первый взгляд кажется, что при инициализации `Thingy` 
	ему передаётся `созданный по умолчанию` `Widget`, 
	но на самом деле здесь происходит `объявление функции`. 
	
	Этот код `объявляет функцию`, 
	`которая получает на вход другую функцию`, 
	`которая ничего не получает на вход и возвращает Widget`, 
	а `первая функция` возвращает `Thingy`. 
	
	Код скомпилируется без ошибок, 
	но вряд ли мы добивались именно такого поведения.
*/

