/*
	**********************************************************************************************
	4.1.8.2 Выражения requires
 
	Благодаря выражениям requires 
	вы можете определять концепты с мощными возможностями. 
	
	Выражение requires имеет следующий вид.
 
	Выражение requires
 
	requires (parameter-list(optional)) 	{
			requirement-seq
	}
 
	parameter-list: 	разделенный запятыми список параметров, 
					аналогичный списку в определении функции.
	
	requirement-seq: 	последовательность, состоящая из 
					-	простых, 
					-	составных 
					или 
					-	вложенных 
									требований 
					и 
					-				требований типа.
	
	-----------------------------------------------------------------------------------------------------------	
	4.1.8.2.1 Простые требования
 
	Следующий концепт Addable является примером простого требования.
	Концепт Addable
*/	
template<typename T>
concept Addable = 	requires (T a, T b) {
						a + b;
					};
/*
	Концепт Addable требует, чтобы было возможно сложение a + b двух значений типа 'Т'.
 
	Избегайте 'анонимных требований': 
										requires requires
 
	Вы можете определить анонимный концепт и сразу же его использовать. 
	
	Избегайте этого. 
	
	Это делает ваш код тяжелым для понимания, 
	и  вы больше не сможете снова использовать 
	(переиспользовать) эти концепты.

	 Анонимный концепт для сложения двух концептов
*/	 
template<typename T>
	requires requires (T x) { x + x; }
T 	add1(T a, T b) 	{ 
	return a + b; 
}
/*
	Эта шаблонная функция определяет концепт прямо на месте. 

	Функция add1 ()
	использует выражение requires 
	внутри другого выражения requires. 
	
	Используемый анонимный концепт оказывается эквивалентным ранее введенному концепту Addable, 
	как и шаблонная функция add2, использующая именованный концепт Addable.
	
	Использование концепта Addable
*/	
template<Addable T>
T add2(T a, T b) { 
	return a + b; 
}
