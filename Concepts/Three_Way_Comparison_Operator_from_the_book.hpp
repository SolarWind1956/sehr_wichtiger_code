/*
	***********************************************************************************************
	4.3.4.3 Лексикографическое сравнение
	
	Создаваемый компилятором оператор трехстороннего сравнения выполняет лексикографическое сравнение.

	'Лексикографическое' 	в этом случае значит, 
						что все базовые классы сравниваются слева направо,
						и 
						все нестатические члены класса сравниваются в порядке их объявления. 
	
	Я должен уточнить: 	для быстродействия 
						генерируемые компилятором операторы == и != 
						в С++20 ведут себя иначе. 
						
	Я напишу об этом в разделе «Оптимизированные операторы == и !=».
	
	Публикация «Simplify You Code With Rocket Science: C++ 20's Spaceship operator» 
	в блоге Microsoft Team дает хороший пример лексикографического сравнения. 
	https://devblogs.microsoft.com/cppblog/simplify-your-code-with-rocket-science-c20s-spaceship-operator/
		
	Для улучшения читаемости я добавил несколько комментариев.
	
	-------------------------------------------------------------------------------------------
	Более сложные типы

	Сгенерированный компилятором оператор spaceship 
	не останавливается на отдельных членах классов, 
	он генерирует правильный набор сравнений 
	для всех подобъектов в ваших типах:
*/
struct Basics {
	int 	i;
	char 	c;
	float 	f;
	double 	d;
	auto operator<=>(const Basics&) const = default;
};

struct Arrays {
	int 	ai[1];
	char 	ac[2];
	float 	af[3];
	double 	ad[2][2];
	auto operator<=>(const Arrays&) const = default;
};
 
struct Bases : Basics, Arrays {
	auto operator<=>(const Bases&) const = default;
};
 
void test_7() {
	cout << "-------------- I'm void " << __func__ << "()" << endl;
	/*
		'Агрегированная инициализация' позволяет 
		непосредственно проинициализировать все члены класса (class, struct, union), 
		когда они являются public. 
	*/
	constexpr Bases a = { 	//	Basics
							{ 0, 'c', 1.1f, 1.1 }			
							//	Arrays
						, 	{ { 1 }, { 'a', 'b' }, { 1.1f, 2.2f, 3.3f }, { { 1.1, 2.2 }, { 3.3, 4.4 } } } 
						};
						
	constexpr Bases b = { 	//	Basics
							{ 0, 'c', 1.1f, 1.1 }			
							//	Arrays
						, 	{ { 1 }, { 'a', 'b' }, { 1.1f, 2.2f, 3.3f }, { { 1.1, 2.2 }, { 3.3, 4.4 } } } 
						};

	static_assert(a == b);
	static_assert(!(a != b));
	static_assert(!(a < b));
	static_assert(a <= b);
	static_assert(!(a > b));
	static_assert(a >= b);
}
