/*
	Есть три категории сравнения.
	-------------------------------------------------------------------------------------------------
	4.3.3 Категории сравнения
	
	Три категории сравнения называются: 
	
	-	строгим (strong ordering), 
	
	-	слабым (weak ordering) 
	
	и 
	
	-	частичным упорядочением (partial ordering). 
	
	Для типа 'Т' следующие три свойства разделяют три категории сравнения.
	
	1. Строгое					-  	'Т' поддерживает все шесть операторов сравнения: 
									==, !=, <, <=, > и >= 	
									(операторы сравнения).
	
	2. Слабое						-	Все эквивалентные значения неразличимы (эквивалентность).
	
	3. Частичное упорядочение 		-	Все значения из 'Т' сравнимы между собой: 
									для произвольных значений 'a' и 'b' типа 'T' 
									только одно из следующих трех отношений справедливо: 
		
									a < b, a ==b и a > b (сравнимость).
		
	Когда вы используете в качестве критерия сортировки 
	нечувствительные к регистру представления строк, 
	эквивалентные значения не обязательно должны быть одинаковыми. 
	
	Точно так же два значения с плавающей точкой не обязательно должны быть сравнимыми: 
	для 'a' = 5.5 и 'b' = NaN (Not a Number) 
	ни одно из следующих выражений не возвращает true: a < NaN, a == NaN и a > NaN.
	
	Исходя из этих трех свойств, 'стратегии сравнения' легко различаются.
	
	Строгое, слабое и частичное упорядочение 
	------------------------------------------------------------------------------------------------
	Категория сравнения			Операторы сравнения			 Эквивалентность		Сравнимость
	------------------------------------------------------------------------------------------------
	Строгое упорядочение				Да							Да					Да
 	Слабое упорядочение				Да												Да
	Частичное упорядочение			Да
	------------------------------------------------------------------------------------------------
	
	Тип, поддерживающий строгое упорядочение, также поддерживает и слабое, и частичное. 
	 
	Тип, поддерживающий слабое упорядочение, поддерживает частичное. 
	 
	В обратную сторону это не работает.

	Если объявленный возвращаемый тип – это 'auto', 
	то реальный возвращаемый тип определяется 
	из общей стратегии сравнения подобъектов и элементов массива, 
	которые сравниваются между собой.
	
	Давайте рассмотрим пример к этому правилу.
*/
