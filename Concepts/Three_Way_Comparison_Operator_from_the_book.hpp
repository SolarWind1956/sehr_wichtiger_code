class MyIntUD {
 public:
    constexpr explicit MyIntUD(int val): value{val} { }
	
	// 	Этот оператор по умолчанию constexpr
	/*constexpr */ auto operator<=> (const MyIntUD& rhs) const = default;
		
	/*
		Ни один из этих операторов ниже не может быть constexpr, 
		так как std::cout – это операция времени выполнения.
	*/
	bool operator== (const MyIntUD& rhs) const {                  
		cout << "==  " << '\n';
        return value == rhs.value;
    }
    bool operator< (const MyIntUD& rhs) const {                  
        cout << "<  " << '\n';
        return value < rhs.value;
    }
	bool operator> (const MyIntUD& rhs) const {                  
        cout << ">  " << '\n';
        return value > rhs.value;
    }
	//		Но, если убрать строку вывода на консоль, то, вполне можно объявить оператор constexpr 
	constexpr bool operator>= (const MyIntUD& rhs) const {                  
        return value >= rhs.value;
    }

private:
     int 	value;
};

