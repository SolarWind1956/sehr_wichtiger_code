template<typename T> 
class	simple_vector
{
public:
	using value_type 		= T;
	using reference 		= T&;
	using const_reference 	= const T&;
	using iterator 			= T*;
	using const_iterator 	= const T*;
	using size_type 		= std::size_t;
	
private:
	T 				*arr;
    size_t 			size;
    int 			index;
	
public:
    simple_vector() : size(0), index(), arr(nullptr) {
	}
    simple_vector(size_t size)    {
        simple_vector::size 	= size;
        simple_vector::arr 		= new T[size];
        simple_vector::index 	= 0;
    }
    ~simple_vector()    {
        if(arr)
			delete [] arr;
    }
	iterator	begin(){
		return arr;
	}	
	iterator	end(){
		return arr + size;
	}
	
	T& operator [] (size_t ind)	{
		return arr[ind];
	}
    const T& operator [] (size_t ind) const	{
		return (*this)[index];
	}
	
    int add(T 	value)    {
        if(index == size)
            return 0;
        else 	{
            arr[index] = value;
            index++;
        }
        return 1;
    }
    void show()    {
        if(size == 0)
            cout << "Vector is empty" << endl;
        for(int i = 0; i < index; i++)
            cout << arr[i] << " ";
        cout << endl;
    }
	//template<typename It> 
	void assign	(	iterator begin
				, 	iterator end
				)
	{
		cout << "-------------- I'm template<typename It> void " << __func__ << "(It begin,	It end)" << endl;
	}			
	//template<typename T> 
	void assign	(	size_t 	n
				, 	T 		elem
				)
	{
		cout << "-------------- I'm template<typename T> void " << __func__ << "(size_t n, T elem)" << endl;
		for(int i = 0; i < n; i++)
            add(elem);
	}	

};
//	Рассмотрим ситуацию когда имеем T = size_t
