/*
	****************************************************************************************
	15.6.5. Выражения requires 
	
	В С++ Core Guidelines рекомендуется использовать 'стандартные концепты'.

	Для пользовательских требований, 
	которые не могут быть выражены с помощью 'стандартных концептов' в условии 
	requires (requires clause), 
	вы можете использовать 'выражение requires' (requires expression), 
	имеющее две формы: 
	
requires { 
	определения требобаний 
} 

	или: 
	
requires (список параметроб) { 
	определения требобаний, опционально использующие параметры из списка
} 

	Список параметров похож на список параметров функции, 
	но в нем не может быть аргументов по умолчанию. 
	
	Компилятор использует параметры 'выражения requires'
	только для проверки соответствия типов требованиям, 
	определенным в {фигурных скобках} выражения. 
	
	{Фигурные скобки} могут содержать любую комбинацию из четырех типов требований, 
	описанных ниже: 
	
	-	простые, 
	
	-	типовые (требования к типу),
	
	-	составные 
	
	и 
	
	-	вложенные. 
	
	Каждое требование заканчивается точкой с запятой(;). 
	
	--------------------------------------------------------------------------------------
	Простое требование
	
	Простое требование (simple requirement) проверяет, 
	является ли выражение допустимым. 
	
	Рассмотрим определение концепта range (заголовок <ranges>), 
	который проверяет, 
	является ли объект диапазоном С++20 с начальным итератором и конечным ограничителем:
*/	
template<class T> 
	concept 	my_range = 
				requires	(T& t) { 
										std::ranges::begin(t); 
										std::ranges::end(t); 
				}; 
template<my_range T>				
void 	test_1(T container){
	cout << "\n-------------- I'm inline void " <<  __func__  << "()" << endl;
	std::ostream_iterator<int> 		output	{std::cout, " "};

	cout << "container contains: ";
	std::ranges::copy	(container, output); 			// display container
}
/*
	Требования могут ссылаться 
	на один или несколько параметров выражения 
	и параметров шаблона из заголовка template. 
	
	Концепт my_range определяет параметр 't' с типом 'Т&'. 
	
	В строках выше определяются простые требования, 
	указывающие, что 't' будет считаться диапазоном, 
	если мы можем получить доступ к начальному итератору и ограничителю, 
	передав параметр 't' функциям std::ranges::begin() и std::ranges::епd() соответственно. 
	 
	Если ни одно из этих простых требований не компилируется, 
	параметр 't' не будет считаться диапазоном. 
	
	Простые требования могут применяться к выражениям с операторами. 
	
	Следующий концепт 
	определяет допустимые операции 
	с целыми числами 
	или 
	с числами с плавающей точкой: 
*/
template<class T> 
	concept 	ArithmeticType = 
				requires	(T a, T b) { 
					a + b; 
					a - b; 
					a * b; 
					a / b; 
					a += b;
					a -= b; 
					a *= b; 
					a /= b; 
				}; 
/*
	Мы не указали оператор модуля (%), 
	потому что он совместим только с целочисленными операндами. 
	
	Конечно, стандартные арифметические типы поддерживают больше операций, 
	например неявные преобразования между типами, 
	поэтому «настоящий» концепт ArithmeticType содержал бы больше строк кода. 
	
	Признак типа is_arithmetic проверяет стандартные арифметические типы. 
	
	Для типов пользовательских классов он всегда возвращает false. 
	
	-----------------------------------------------------------------------------
	Требование к типу 
	
	Требование к типу (type requirernent) 
	начинается с ключевого слова typename 
	и последующего имени типа 
	и определяет, 
	является ли указанный тип допустимым. 
	
	Например, если ваш код требует, 
	чтобы аргумент типа имел вложенный тип с именем value_type 
	(в случае с контейнером стандартной библиотеки), 
	вы можете определить концепт с требованием к типу: 
*/	
template<typename T> 
	concept 	HasValueType = 
				requires 	{ 
					typename 	T::value_type; 
				};
/*				
	Тип Т соответствует требованию HasValueType, 
	если Т::value_type является допустимым типом. 
	
	Если тип Т не содержит вложенного value_type, 
	это требование будет оценено как false. 
	
	---------------------------------------------------------------------------------
	Составное требование 

	Составное требование (cornpound requirernent) позволяет указать выражение, 
	к 'результату' которого также предъявляются требования. 
	
	Составное требование имеет следующий вид: 
	
{Выражение}	-> требование-к-результату 

	Например, концепт incrementable из заголовка <iterator> стандартной библиотеки 
	содержит выражение requires, 
	указывающее, 
	что итератор incrementable должен поддерживать оператор постфиксного инкремента ( ++ ): 
*/
template<typename I> 
	concept 	my_Incrementable	=
				requires(I i) { 
					{i++} noexcept -> std::same_as<I>; 
				};
/*
	Обозначение	-> указывает на требование к результату выражения i++. 
	
	В этом случае результат должен иметь тот же тип (I), 
	что и тип объекта i. 
	
	После правой фигурной скобки в составном требовании можно добавить ключевое слово noexcept, 
	указывающее, что выражение не должно генерировать исключения. 
	
	Когда мы использовали std::same_as<>, 
	мы оперировали двумя аргументами шаблона, 
	но здесь используем только один. 
	
	Когда вы накладываете ограничение на результат выражения, 
	компилятор вставляет тип этого выражения в ограничение 
	в качестве первого параметра-типа. 
	
	Поэтому в нашем ограничении на самом деле присутствуют два параметра-типа - 
	в данном случае оба являются типом.
	
	Объект incrementable 
	также должен поддерживать концепт weakly_incrementable, 
	который, помимо других требований, 
	содержит следующее составное требование: 

{++i} -> same_as<I&>; 

	Таким образом, объект incrementable должен поддерживать оператор префиксного инкремента, 
	а результат выражения должен иметь тот же тип, что и ссылка на параметр-тип I. 
	
	----------------------------------------------------------------------------------------------------
	Вложенное требование 
	
	Вложенное требование (nested requirement) 	- 	это условие requires, вложенное в выражение requires.

	Вложенные требования используются для применения существующих концептов и признаков типов 
	к параметрам выражения requires. 
	
	-------------------------------------------------------------------------------------------------------
	'Разовое ограничение' "requires requires" 

	Выражение requires, помещенное непосредственно в условие requires, - 
	это 'ра3овое ограничение' (ad-hoc constraint), 
	также называемое 'специальным ограничением'. 
	
	В следующем шаблоне функции printRange() 
	мы скопировали выражение requires концепта std::ranges::range 
	и поместили его непосредственно в условие requires: 
*/	
template<typename Т> 
	requires 							//	первое требование является условием requires; 
		requires	(const Т& t) { 		//	второе требование является выражением requires. 
			std::ranges::begin(t); 
			std::ranges::end(t); 
		}
void 	printRange	(const Т& 	range) { 
	cout << "-------------- I'm void " <<  __func__  << "()" << endl;
	
	for (const auto& item: range) { 
		std::cout << item <<	" "; 
	} 
	std::cout << std::endl;
} 
/*
	Обозначение 'requires requires' допустимо, 
	если: 
	
	♦ 	первое требование является условием requires; 
	
	♦ 	второе требование является выражением requires. 
	
	Преимущество разового ограничения заключается в том, 
	что его можно определить прямо в том месте кода, 
	где оно используется, если оно нужно вам только один раз. 
	
	Именованные концепты предпочтительнее. 
*/
template<my_range T>				
void 	test_2(T container){
	cout << "\n-------------- I'm inline void " <<  __func__  << "()" << endl;
	printRange(container);
}
