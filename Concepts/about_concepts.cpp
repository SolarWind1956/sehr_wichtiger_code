/*	
	***************************************************************************************************
	-------------------------------------------------------------------------------------------------------
	Концепт или концепция
	https://ru.wikipedia.org/wiki/%D0%9A%D0%BE%D0%BD%D1%86%D0%B5%D0%BF%D1%86%D0%B8%D1%8F_(C%2B%2B)
	
	Концепция — интерфейсное расширение шаблонов языка C++, 
	опубликованное в технической спецификации ИСО/МЭК ISO TS 19217:2015[1]. 
	
	По своей сути концепция является набором логических предикатов, 
	размещённых за списком параметров шаблона, 
	которые оцениваются во время компиляции исходного кода 
	с целью установления ограничений на свойства аргументов, 
	которые принимаются в качестве параметров шаблона.

	Введение концепций связывают с дальнейшим развитием в языке C++ инструментария, 
	основанного на парадигме обобщённого программирования. 
	
	Концепция может быть объявлена с шаблоном любого вида 
	(класс-шаблон, шаблон-функция, или функция-член класса-шаблона), 
	eё назначением является выявление логических несоответствий 
	между свойствами типов данных, 
	которые используются внутри тела шаблона 
	и свойствами типов данных, 
	которые поступают в шаблон в качестве входных параметров.

	До введения в стандарт языка понятие концепции 
	было реализовано в библиотеке общего назначения Boost 
	в виде библиотечных классов проверки концепций BCCL 
	(англ. Boost Concept Checking Library).
	
	*****************************************************************************************************
	Синтаксис текущего предложения (из Си++20)
	------------------------------------------------------------------------------------------------------
	Определение концепции.
*/
template <typename T>
concept InterfaceCheck = 
	requires(T 	m) {  	// любая переменная `m` типа, удовлетворяющего концепту InterfaceCheck,
			m.start();  // должна иметь метод `m.start()` 
			m.stop();   // и метод `m.stop()`
			m.init();   // и метод `m.init()`
	};  
template <class T>					//	T 							-	параметр концепта
concept EqualityComparable =  		//	EqualityComparable 			-	имя концепта
    requires(T a, T b) {			//								-	предикат концепта
		// Концепция, означающая тип, преобразуемый в bool
        {a == b} -> std::convertible_to<bool>;  			
        {a != b} -> std::convertible_to<bool>;
    };
/*
	Шаблон, использующий концепцию (обратите внимание, нет ключевого слова template).
*/
void f_with_concept(const EqualityComparable auto& param)
{
	cout << "-------------- I'm void " << __func__ << "(const EqualityComparable auto& param)" << endl;
	if (param == 10)
		cout << "------- param == 10 -> " << param << endl;
	else
		cout << "------- param != 10 -> " << param << endl;
};
/*
	Концепции будут участвовать в выборе, 
	какую функцию из набора перегруженных применять, 
	наряду с SFINAE. 
	
	Компилятор предпочтёт самую «жёсткую» концепцию.

	Если использовать концепцию в инициализаторе, 
	это будет аналог auto, 
	однако код будет компилироваться, если концепция поддерживается.

	Sortable auto x = f(y); 	// аналог auto x = f(y), 
	
	компилируется, если результат — тип, подходящий под Sortable
	
	------------------------------------------------------------------------------------------
	Предпосылки

	В обобщённом программировании концепция 	— 	это такой набор требований к типу, 
													чтобы шаблон обобщённого программирования 
													имел смысл. 
	
	Например, шаблон 
	
	It2 	std::copy(It1, It1, It2) 
	
	предполагает такие соотношения между типами-итераторами It1 и It2.

	-	It1 и It2 	— однонаправленные итераторы.
	
	-	Между типами *It2 и *It1 возможно присваивание.
	
	Эти концепции описаны в документации по Си++, 
	и они — словесное описание условий, 
	когда код компилируется. 
	
	Так, при попытке специализировать шаблон с параметрами 
	
	It1 = int*, It2 = int** 
	
	компилятор сообщит, что невозможно присваивание int* ← int. 
	
	При этом есть недостатки.

	Ошибка выпадет в глубине заголовочного файла STL — 
	в сложном заведомо правильном коде.
	
	Зачастую тексты ошибок крайне многословны, 
	и сложно выяснить, 
	чего именно не хватает, 
	чтобы шаблон специализировался.

	Когда программист пишет шаблон, 
	он может случайно выйти из концепции 
	и не заметить это. 
	
	Это никак нельзя проверить, 
	кроме как попытавшись специализировать шаблон. 
	
	На сложных шаблонах «проверка специализацией» не так проста, как кажется — 
	большинство простейших типов поддерживают много лишних функций. 
	
	Так, недостаточно проверить std::vector<T> на типе int: 
	помимо операций 
	«конструктор без параметров», 
	«конструктор перемещения» 
	и 
	«присвоить с перемещением», 
	минимально требуемых для вектора, 
	у целого типа есть 
	конструктор копирования, операция присваивания, математические операции и многое другое, 
	и нет гарантий, что они не используются.
	
	Кроме того, приходится делать функции, 
	которые появляются или исчезают 
	в зависимости от некоторых условий 
	(соответствия или несоответствия концепции). 
	
	В Си++17 шаблоны для этого сложны.

	По сей день синтаксически описать концепции получилось только ограниченно — 
	так, в Java роль концепций 
	играют утверждения наподобие 
	class Test <T extends Testable>.
*/
