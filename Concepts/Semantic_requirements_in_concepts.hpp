/*	
	------------------------------------------------------------------------------------------------------
	У нас есть концепция и ограниченная ею Addable общая функция. sum
	
	Ряд читателей заметили, что вместо того, чтобы расширять концепцию, 
	было бы лучше предоставить две перегрузки для шаблона функции sum: 
	
	одну, которая работает для каждого Addable-типа, 
	а другую, более эффективную, если мы знаем тип. 
	есть дополнительно totally_ordered. 
	
	Таким образом, мы имеем следующий набор объявлений:
*/	
template <typename T>
concept AddableAgain = 
					std::regular<T> && 	requires(T x, T y) {
											{ x += y } -> std::same_as<T&>;
											{ x +  y } -> std::convertible_to<T>;
										};
template <AddableAgain T>
	T sumAgain(T a, T b);
	
template <AddableAgain T>
	requires std::totally_ordered<T>
	T sumAgain(T a, T b);
/*
	Реализации двух алгоритмов:
*/
// generic version 
template <AddableAgain T>
T 	sumAgain(T a, T b){
	return a + b;
}
 
// specialized version
template <typename T>
T sum_impl_Again(T a, T b){
	assert (a >= b);
	a += b;          
	return a;
}
template <AddableAgain T>
	requires std::totally_ordered<T>
T 	sumAgain(T a, T b){
	if (b > a) 
		return sum_impl_Again(b, a);
	else
		return sum_impl_Again(a, b);
}
/*
	Теперь у нас есть новый пользователь нашей библиотеки. 
	
	У него есть идея. 
	
	Он будет использовать её для объединения строк. 
	
	Это разрешено? 
	
	Давай проверим:
*/
static_assert(AddableAgain<std::string>);
void test_4() {
	cout << "-------------- I'm void " << __func__ << "()" << endl;
	
	std::string 	air = "air";
	std::string 	bus = "bus";
	cout << sumAgain(air, bus) << endl;
}
/*
	Что случилось? 
	
	Специализированная перегрузка изменила порядок аргументов так, 
	что «больший» оказался слева. 
	
	Было ли автору библиотеки разрешено изменять порядок аргументов?
	
	Заметим, что ранее не было необходимости отвечать на этот вопрос. 
	
	Мы протестировали 
	-	int, 
	-	boost::rational<int>, 
	-	boost::multiprecision::cpp_int 
	и 
	-	std::complex<double>, 
	и такой проблемы не возникло, 
	поскольку для всех этих типов сложение коммутативно . 
	
	Или, может быть, нам следует сказать, 
	что для этих типов operator+()
	представляет собой операцию сложения, 
	которая по определению является коммутативной.
	
	operator+()
	
	Возможно, использование конкатенации строк представляет собой злоупотребление std::string. 
	
	Конкатенация имеет некоторое сходство со сложением (например, ассоциативность), 
	но не обладает всеми его свойствами. 
	
	Мы могли бы винить std::string в этом решении, 
	но это не имеет значения. 
	
	Дело в том, что автор библиотеки function fun сделал предположение: 
	для типов, которые моделируют Addable, operator+() - это коммутативная операция: 
	должна быть возможность передавать аргументы в обратном порядке,
	и результат не должен меняться. 
	
	Проблема в том, что это предположение не было доведено до сведения пользователя.

	Ассоциативность operator+() является примером 
	'семантической потребности понятия'. 
	
	Это нормально, 
	и даже необходимо предъявлять такие семантические требования. 
	
	На самом деле в нашей концепции их больше. 
	
	Например, мы предполагаем, что

(a + b) == (T{a} += b)

	Мы также делегируем std::regular, 
	у которого есть свой набор семантических требований; 
	назвать только одно:

T{a} == a 			// copy is equal to the original

	В одной перегрузке упоминается std::totally_ordered, 
	которая делает ряд предположений о семантических свойствах реляционных операторов.

	Таким образом, 
	"понятие" представляет собой 
	набор синтаксических, а также семантических требований, 
	даже если нет способа выразить эти семантические требования. 
	
	Что мы делаем, так это объявляем требования, которые можем, 
	и надеемся, что пользователи каким-то образом выяснят, 
	каковы оставшиеся (семантические) ограничения. 
	
	Один из способов передать семантические требования — 
	описать их человеческим языком в документации. 
	
	Другой, несколько похожий способ — 
	поместить их в виде комментариев внутри деклараций концепций:
*/
template <typename T>
concept AddableSemantics = 
		  std::regular<T> && requires(T x, T y) {
									{ x += y } -> std::same_as<T&>;
									{ x +  y } -> std::convertible_to<T>;
								 
									// semantics { 
									//  (x + y) == (y + x);
									//  (x + y) == (x += y); 
									// }
							 }; 
/*
	Или применить какой-нибудь хитрый трюк, 
	чтобы заставить компилятор проверять синтаксис этих выражений:
*/	
template <typename T>
concept AddableWithTrick = 
					std::regular<T> && requires(T x, T y) {
											{ x += y } -> std::same_as<T&>;
											{ x +  y } -> std::convertible_to<T>;
										 
											requires requires {
												(x + y) == (y + x);
												// (x + y) == (x += y);
												(x + y) == [](T x, T y){ return x += y; }(x, y);
											};
										}; 						 
/*
	Реализации двух алгоритмов:
*/
static_assert(AddableWithTrick<std::string>);	// Вроде как не должно???????

// generic version 
template <AddableWithTrick T>
T 	sumAgain(T a, T b){
	return a + b;
}
 
// specialized version
template <typename T>
T sum_impl_WithTrick(T a, T b){
	assert (a >= b);
	a += b;          
	return a;
}
template <AddableWithTrick 	T>
	requires std::totally_ordered<T>
T 	sumWithTrick(T a, T b){
	if (b > a) 
		return sum_impl_WithTrick(b, a);
	else
		return sum_impl_WithTrick(a, b);
}

/*
	Вложенные требования, 'requires requires', 
	очевидно, 
	всегда будут успешными (они представляют собой композицию того, что нам уже требуется); 
	но они дают нам гарантию, 
	что программа не сможет скомпилироваться, 
	если мы неправильно воспользуемся выражением. 
	
	Я знаю, что второе уравнение немного сбивает с толку, 
	и его, вероятно, следует переписать так:

(x + y) == [](T x, T y){ return x += y; }(x, y)

	но суть вы поняли.
*/
void test_5() {
	cout << "-------------- I'm void " << __func__ << "()" << endl;
	int x, y;
	x 	= 	21;
	y	=	32;
	
	auto z = [](int x, int y){ return x += y; }(x, y);
	cout << x << "  " << z << endl;
	
	auto zz = [&](){ return x += y; }();
	cout << x << "  " << zz << endl;
	
	cout << sumWithTrick(1, 2) << endl;
	
	std::string 	air = "air";
	std::string 	bus = "bus";
	cout << sumWithTrick(air, bus) << endl;
}
/*
	Интересно, что предыдущий дизайн концептов (для C++11) 
	в какой-то момент имел возможность выражения таких семантических ограничений, 
	как описано в этом посте . 
	
	Но люди этого не оценили, 
	да и все возможные смысловые требования оно выразить не могло. 
	
	Требование, чтобы операция .empty() над контейнером 
	имела временную сложность O(1), 
	также является семантическим требованием 
	но не может быть выражено выражением на C++.

	Подведем итоги того, что у нас есть на данный момент. 
	
	Концепт – это набор требований. 
	
	Пользователи должны удовлетворять всем требованиям концепции, 
	чтобы правильно использовать алгоритмы, ограниченные концепциями. 
	
	Компилятор может только проверить, 
	удовлетворяется ли (синтаксическое) подмножество концептуальных ограничений 
	предоставленным пользователем типом. 
	
	Ответственность за обеспечение того, 
	чтобы все ограничения семантических концепций 
	удовлетворялись типом при его передаче в шаблон, 
	ограниченный этим понятием, 
	в конечном итоге ложится на пользователя.

*/
