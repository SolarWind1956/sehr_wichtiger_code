/*
	********************************************************************************************************
	Нормальное распределение		-		The Normal Distribution
	
	Сигналы, формируемые случайными процессами, 
	обычно имеют 'колоколообразную форму' 'функции плотности вероятности'. 
	
	Это называется 'нормальным распределением', 'Гауссовым распределением' или 'Гауссианом', 
	в честь великого немецкого математика Карла Фридриха Гаусса (1777-1855). 
	
	Signals formed from random processes usually have a 'bell shaped' 'pdf'.  
	
	This is called a 'normal distribution', a 'Gauss distribution', or a 'Gaussian', 
	after the great German mathematician, Karl Friedrich Gauss (1777-1855). 
 
	Причина, почему эта кривая встречается в природе так часто, 
	будет кратко обсуждена в связи с генерированием 'цифрового шума'. 
	
	Основная форма кривой образуется из экспоненты с отрицательным квадратом степени:
	
	y(x)		=	e⁻ˣ²
	
	Эта сырая кривая может быть преобразована в полный Гауссиан, 
	добавлением выверенного 'среднего значения' 'µ' 
	и стандартного отклонения 'σ'. 
	
	Кроме того, уравнение должно быть нормализовано так, 
	чтобы вся площадь, ограниченная кривой, была равна единице, 
	это требование всех функций распределения вероятности. 
	
	Это приводит к общей форме нормального распределения, 
	одного из наиболее важных соотношений 
	в статистике и теории вероятности:
	
	P(x)		=	(1 / σ√2π) e ⁻⁽ˣ⁻ᶬ⁾²/²ᵟ²
	
	Среднее значение 'µ' центрует кривую вокруг конкретного значения, 
	в то время как 
	стандартное отклонение 'σ' регулирует ширину колоколообразной формы. 
	
	Интересной характеристикой Гауссиана является то, 
	что его хвосты очень быстро приближаются к нулю, 
	намного быстрее, чем у других обычных функций, 
	таких как экспоненциального радиоактивного распада или 1/x. 
	
	Как было показано ранее, 
	интеграл функции плотности вероятности 
	используется для нахождения вероятности того, 
	что сигнал будет в пределах некоторого диапазона значений. 
	
	Это делает интеграл функции плотности вероятности достаточно важным, 
	чтобы дать ему свое собственное название: 
	'интегральная функция распределения' (cumulative distribution function - cdf). 
	
	Особенно неприятной проблемой с Гауссианом является то, 
	что он не может быть проинтегрирован при помощи элементарных функций. 
	
	Обойти это, можно подсчитав интеграл Гауссиана численным интегрированием. 
	
	Это потребует очень частой дискретизации непрерывной Гауссовой кривой, 
	скажем несколько миллионов точек между -10σ и +10σ. 
	
	Затем, для моделирования интегрирования, 
	отсчеты в этом дискретном сигнале суммируются. 
	
	Дискретная кривая, являющаяся результатом этого смоделированного интегрирования, 
	сохраняется затем в таблице для использования при вычислении вероятностей. 
	
	Поскольку эта кривая так часто используется в теории вероятности, 
	ей присвоен свой собственный символ: 
	Ф(x) (греческая заглавная буква фи). 
	
	Для вычисления вероятности того, 
	что сигнал будет между двумя значениями, 
	необходимо вычесть соответствующие числа, 
	найденные в таблице Ф(x). 
*/
static 	void		Calculate_normal_distribution()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	
	const	int			N				{10'000};		//	Количество виртуальных отсчетов
	const	int			MAX_INTENSITY	{255};			//	Максимально возможная величина отсчета
	double 				signals_array[N];				//	Массив отсчетов сигнала
	#if 1	
	// 	1.
	//std::random_device 	rd; 								// 	Класс предварительной генерации случайных битов 
	// 	2.
	std::mt19937 		gen_mt{std::random_device{}()};	// 	Класс генерации случайных битов криптозащищенных
	// 	3.												// 	Класс генерации случайных битов равномерно распределенных
	std::uniform_real_distribution<double> 	uniform_distribution(0.00, (double)MAX_INTENSITY); 
	
	for (int i = 0;	i < N; ++i) {
		//	оператор вызова функции .operator()() каждым вызовом даст новое случайное число
		signals_array[i] = uniform_distribution(gen_mt);		
	}
	//	Покажем для примера, чем мы нафоршировали массив
	for (int i = 0;	i < 10; ++i) {
		cout		<<	signals_array[i] << ",  ";
	}
	cout		<<	endl;
	//	Определим среднее значение и стандартное отклонение полученного сигнала
	double 	meen_value		=	mean	(	signals_array	//	Массив значений отсчетов сигнала
									,	N				//	Количество отсчетов в массиве
									);
	cout 	<< "Среднее значение предварительных отсчетов == " << 	meen_value << endl;
	//	Определим стандартное отклонение сигнала
	double 	std_dev_value	=	standard_deviation	(variance	(	signals_array	//	Массив значений отсчетов сигнала
																,	N				//	Количество отсчетов  в массиве
																)
													);
	cout 	<< "Стандартное отклонение предварительных отсчетов == " << std_dev_value << endl;
	#endif	
	// 	Нормальное распределение на базе случайных величин полученных с использованием равномерного распределения
	// 	1.
	//std::random_device 	rd2; 							// 	Класс предварительной генерации случайных битов 
	// 	2.	Класс генерации случайных битов криптозащищенных
	std::mt19937 					gen_mt2		{std::random_device{}()};	
	// 	3.	Класс генерации случайных битов нормально распределенных
    std::normal_distribution<double> 	norm_dist	{meen_value, std_dev_value};	// {160.0, 40.0}; //
		
	std::vector<double> 				signals_vector;	
	
	// 	Fill a vector with samples, распределенных с использованием Гауссиана
	
    for (int i = 0; i < N; ++i) {
        signals_vector.push_back(norm_dist(gen_mt2));
    }
	//	Покажем для примера, чем мы нафоршировали вектор с использованием Гауссиана
	for (int i = 0;	i < 20; ++i) {
		cout		<<	signals_vector[i] << ",  ";
	}
	cout		<<	endl;
	//	Теперь займемся гистограммой
	const int	histogramm_binns					{25};	//	Количество бинн в гистограмме (групп отсчетов)
	int			histogramm[histogramm_binns] = 	{};		//	Определяем массив гистограммы с инициализацией нулями
	//	Формируем гистограмму минимальными значениями каждого бина
	int			binns_index	=	(MAX_INTENSITY) / histogramm_binns;
	cout 	<< "Индекс биннов == " << binns_index << endl;
	
	for (int i = 0;	i < N; ++i) {
		if	(signals_vector[i] > (MAX_INTENSITY)) {
			cout << "Проблемы с индексацией i == " << i << " signals_vector[i] == " << signals_vector[i] << endl;
			signals_vector[i] = MAX_INTENSITY;
		}	
		if	(signals_vector[i] < 0.0) {
			cout << "Проблемы с индексацией i == " << i << " signals_vector[i] == " << signals_vector[i] << endl;
			signals_vector[i] = 0.0;
		}
		++histogramm[(int)(signals_vector[i] / binns_index)];
	}
	cout << "Смотрим значения гистограммы" << endl;
	
	for (int i = 0;	i < histogramm_binns; ++i) {
		cout		<<	histogramm[i] << ",  ";
	}
	cout		<<	endl;
	//	Прорисуем гистограмму
	for (int i = 0;	i < histogramm_binns; ++i) {
		cout << std::setw(2) << i << ' ' <<  std::string((int)(std::sqrt(histogramm[i])), '*')  <<  endl; 
	}
}	
