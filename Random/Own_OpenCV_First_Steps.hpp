/*
	Результаты показывают идентичность формул определения 'дисперсий' и 'стандартных отклонений'.
	
	Итак, 
	'диспрерсия' - это средняя сумма квадратов отклонений отсчетов от математического ожидания,
	'стандартное отклонение' - корень квадратный из 'дисперсии' отсчетов.
	
	Осталось выяснить, почему деление происходит на (N -1) а не на 'N' при вычислении 'дисперсии'.
	
	По мере продвижения по сигналу сохраняются бегущие дубликаты трех параметров: 
	
	(1) 	количество уже обработанных отсчетов, 
	(2) 	сумма этих отсчетов 
	и 
	(3) 	сумма квадратов отсчетов 
		(то есть, возведение в квадрат значение каждого отсчета и 
		добавление результата к аккумулированному значению). 
		
	Используя только текущие значения трех параметров, 
	'среднее значение' и 'стандартное отклонение'
	могут быть эффективно вычислены 
	после любого обработанного отсчета. 
	
	Тогда среднее значение и стандартное отклонение 
	могут быть найдены в любой желаемый момент 
	без необходимости пересчета всей последовательности.
	
	--------------------------------------------------------------------------------------------------------------------------------------------
	Прежде чем закончить дискуссию о среднем значении и стандартном отклонении, 
	необходимо упомянуть о двух других терминах. 
	
	В некоторых случаях среднее значение описывает то, что было измерено, 
	в то время как стандартное отклонение представляет шум и другие помехи. 
	
	В этих случаях стандартное отклонение важно не само по себе, 
	а только в сравнении со средним значением. 
	
	Это придает значимость термину 'отношение сигнал-шум', 
	который равен среднему значению, деленному на стандартное отклонение. 

	Другой также используемый термин – 'коэффициент вариации'. 
	
	Он определяется как стандартное отклонение, 
	деленное на среднее значение, 
	умноженное на 100 процентов. 
	
	Например, сигнал (или другая группа измеренных значений) 
	с 'коэффициентом вариации' 2% имеет 'отношение сигнал-шум' 50. 
	
	Более хорошие данные означают 'более высокое' значение 'отношения сигнал-шум' 
	и 'более низкое' значение 'коэффициента вариации'.
*/
