/*
	----------------------------------------------------------------------------------------------------------------------------------------------------------------
	Не используйте генераторы без распределений	-	 Don’t Use Engines without Distributions
 
	Наивный программист может спросить: 
	почему просто не использовать значения, созданные генератором, 
	в качестве случайных чисел, 
	а если интервал не совпадет с требуемым, 
	просто использовать деление по модулю %?
	
	Использование 'стандартного генератора случайных чисел' "rand ()" из языка 'С' 
	порождает проблемы. 
	
	Существо дела состоит в следующем (точные цитаты выделены курсивам).
	
	Вычисление случайных чисел с помощью операции 
	
	rand () % n 
	
	на практике является ошибочным по двум причинам.
	
	1. 	Если 'n' - небольшое целое число, 
		то многие реализации генераторов случайных чисел 
		выдают остатки, которые не являются в достаточной степени случайными.
 
		Например, довольно часто последовательные результаты функции rand () 
		состоят из чередующихся 'четных' и 'нечетных' чисел. 
		
		В этом случае, если 'n' равно 2, последовательные результаты операции 
		
		rand() % n 
		
		будут принимать чередующиеся значения 0 и 1.
 
	2.	С другой стороны, если число 'n' велико, 
		а максимальное генерируемое значение не делится на 'n' нацело, 
		то некоторые остатки будут появляться чаще других. 
		
		Например, если максимум равен 32767, а 'n' равно 2000, 
		то 17 сгенерированных значений (500, 2500,..., 30500, 32500) 
		будут преобразованы в 500,
		и только 16 сгенерированных значений (1500, 3500,..., 31500) будут отображены в 1500. 
		
		Причем, чем больше 'n', тем хуже становится ситуация.
		
	Хорошие линейные генераторы учитывают эти ситуации 
	при отображении сгенерированных значений 
	в целевой интервал случайных чисел. 
	
	Таким образом, для того чтобы получить случайные числа хорошего качества, 
	'генераторы' и 'распределения' 
	всегда следует использовать "совместно"!!!!!!!!!!!.
*/
