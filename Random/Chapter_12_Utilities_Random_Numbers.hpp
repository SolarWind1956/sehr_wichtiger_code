/*
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	Механизм случайных чисел
	
	Механизм случайных чисел генерируют случайные биты. 
	
	В Boost и stdlib существует огромное множество примеров. 
	
	Вот общее правило: если нужны повторяемые псевдослучайные числа, 
	рассмотрите возможность использования механизма вихря Мерсенна std::mtt19937_64. 
	
	Если нужны криптографически безопасные случайные числа, 
	рассмотрите возможность использования std::random_device.
	
	Вихрь Мерсенна обладает некоторыми желательными статистическими свойствами для моделирования. 
	
	Его конструктору предоставляется целочисленное начальное значение, 
	которое полностью определяет последовательность случайных чисел. 
	
	Все 'механизмы случайных чисел' являются 'функциональными объектами'; 
	чтобы получить случайное число, 
	используйте вызов функции operator(). 
	
	В листинге ниже показано, как создать механизм вихря Мерсенна с начальным числом 91586 и за
	пустить полученный механизм трижды.
*/
