/*
	*******************************************************************************************************************
	Распределение случайных чисел		-	 Random Number Distributions
	
	'Распределение случайных чисел' 	- 	это математическая функция, 
										которая отображает число 
										в 'плотности вероятности'.

	Идея заключается в том, что при взятии выборки из случайных чисел, 
	которые имеют конкретное распределение, 
	и при построении графиков относительных частот значений выборок 
	этот график будет выглядеть как распределение.
	
	Распределения делятся на две большие категории: 
	
	-	дискретные 
	
	и 
	
	-	непрерывные. 
	
	Простая аналогия состоит в том, что 'дискретные распределения' 
	отображают интегральные (то есть, целочисленные) значения, 
	а 'непрерывные распределения' отображают значения с 'плавающей точкой'.
	
	Большинство дистрибутивов принимают параметры настройки. 
	
	Например, 'нормальное распределение' - это непрерывное распределение, 
	которое принимает два  параметра: 
	
	'среднее значение' 
	
	и 
	
	'дисперсию'. 
	
	Его плотность имеет знакомую форму колокола с центром вокруг среднего значения. 
	
	Дискретное 'равномерное распределение' является распределением случайных чисел, 
	которое присваивает равные вероятности числам 
	между некоторым минимумом и максимумом. 
	
	Его плотность выглядит идеально плоской в диапазоне от минимального до максимального.
	
	Можно легко генерировать случайные числа из общих статистических распределений, 
	таких как равномерное и нормальное, используя одну и ту же библиотеку <random> в stdlib. 
	
	Каждое распределение принимает некоторые параметры в конструкторе, 
	соответствующие 'параметрам базового распределения'. 
	
	Чтобы вывести случайную переменную из распределения, 
	используется вызов функции operator()(generator) 
	и передается 'экземпляр механизма случайных чисел' 'generator', 
	такой как вихрь Мерсенна, например.
	
	std::uniform_int_distribution - это шаблон класса, 
	доступный в заголовке <random>, который принимает один 'параметр шаблона', 
	соответствующий типу, который нужно получить при выведении из распределения, 
	например 'int'.
 
	Определяется 'минимум' и 'максимум' равномерного распределения, 
	передавая их в качестве 'параметров конструктора'. 
	
	Каждое число в диапазоне имеет равную вероятность. 
	
	Это, пожалуй, самое распространенное распределение, 
	возникающее в общем контексте разработки программного обеспечения.
*/
static	void		Random_Number_Distributions() {
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	//	Установим режим разделения групп десятичных разрядов (по три разряда в группе по умолчанию)
	separate_number_with_apostrophe snwa;	snwa.set_separator();
	
	/*
		В коде ниже показано, 
		как взять миллион чисел из равномерного распределения 
		с минимумом 1 и максимумом 10 
		и вычислить среднее значение выборки.
	*/
	cout		<<	'\n' << "-------------------- std::uniform_int_distribution produces uniform ints"	<< endl;

	std::mt19937_64 						mt_engine	{102'787};
	
	std::uniform_int_distribution<int> 	int_d		{0, 10};
	const size_t 						n			{1'000'000};
	int 									sum			{};
	for(size_t i{}; i < n; i++)
		sum += int_d(mt_engine);
	
	const long	double					sample_mean 	= (long double){sum} / (long double){n};
	cout		<< "sample_mean == " << sample_mean << endl;
	/*
		Создается вихрь Мерсенна с начальным значением 102'787,
		а затем создается std::uniform_int_distribution 
		с минимальным значением 0 и максимальным значением 10. 
		
		Затем инициализируется переменная 'n '
		для хранения числа итераций 
		и переменная 'sum' для хранения суммы всех равномерных случайных величин. 
		
		В цикле отрисовываются случайные величины из равномерного распределения 
		с помощью operator()(mt_engine), 
		передавая экземпляр вихря Мерсенна.
 
		Среднее дискретное равномерное распределение - 
		это минимум плюс максимум, деленный на 2. 
		
		Здесь 'int_d' имеет 'среднее значение' 5. 
		
		Можно вычислить среднее значение выборки, 
		разделив сумму на количество выборок 'n'. 
		
		С высокой достоверностью можно утверждать, 
		что этот 'sample_mean' равен приблизительно 5.
	*/
	cout 	<< "std::numeric_limits<double>::epsilon == " << std::numeric_limits<double>::epsilon()
			<< ", DBL_EPSILON == "  << DBL_EPSILON << endl; 
	//	https://en.cppreference.com/w/cpp/types/climits
	//	https://en.cppreference.com/w/cpp/types/climits
	#if 0		//	Погрешность оказалась-таки больше 	
	assert	(	(	(5.00 - sample_mean) 
				<= 	
					std::numeric_limits<double>::epsilon()
				)	
			&& 
				"Погрешность оказалась больше epsilon() :("
			);
	#endif			
	//	Восстановим локаль в отношении разделения десятичных разрядов на группы
	snwa.locale_restore();
}	

