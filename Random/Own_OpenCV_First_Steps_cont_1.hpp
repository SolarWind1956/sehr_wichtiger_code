/*
	Вычисление гистограммы происходит очень быстро, 
	поскольку оно требует только индексирования и инкрементирования. 
	
	Для сравнения, вычисление среднего значения и стандартного отклонения 
	требует более длительных операций сложения и умножения. 
	
	Стратегия этого  алгоритма 
	применять такие медленные операции 
	не ко многим отсчетам в сигнале, 
	а только к нескольким числам в гистограмме. 
	
	Это делает алгоритм значительно быстрее, чем ранее описанные методы. 
	
	Для очень длительных сигналов, думается, быстрее раз в десять, 
	при условии выполнения вычислений на компьютерах общего назначения. 
	
	Понимание того, 
	что полученный 'сигнал является' "зашумленной версией" основного процесса, 
	очень важно; 
	настолько важно, что некоторым из понятий даются отличные друг от друга названия. 
	
	Гистограмма это то, что формируется из полученного сигнала. 
	
	Соответствующая кривая для основного процесса 
	называется 'функцией массы вероятности'. 
	
	Гистограмма всегда вычисляется при использовании конечного числа отсчетов, 
	в то время как 'функция массы вероятности' это то, 
	что может быть получено при использовании бесконечного числа отсчетов. 
	
	'Функция массы вероятности' 
	может быть оценена (выведена) из гистограммы 
	или 
	может быть получена с помощью нескольких математических методов таких, 
	как в примере с подбрасыванием монеты. 
	
	Как объяснялось ранее, вертикальная ось гистограммы 	
	-	это число раз, которое конкретное значение встречается в сигнале. 
	
	Вертикальная ось 'функции массы вероятности'  - 	'probability mass function' (pmf).
	содержит такую же информацию, 
	кроме 'выраженного через дробь' основания. 
	
	Другими словами, чтобы аппроксимировать 'функцию массы вероятности', 
	каждое значение в гистограмме 
	делится на общее число отсчетов. 
	
	Это означает, что 
	каждое значение в 'функции массы вероятности'
	должно лежать между нулем и единицей, 
	и что 'сумма всех значений в функции массы вероятности'
	будет 'равна единице'.

	'Функция массы вероятности' важна, 
	поскольку она 'описывает вероятность', 
	с 'которой будет генерироваться конкретное значение'.

	'Гистограмма' и 'функция массы вероятности' 
	могут быть использованы 'только с "дискретными" данными', 
	такими как оцифрованный сигнал, проживающий в компьютере. 
	
	Подобные понятия применимы и к непрерывным сигналам, 
	таким как напряжение, 
	возникающее в аналоговой электронике. 
	
	'Функция плотности вероятности' (ФПВ) 
			'probability density function' (PDF) - https://en.wikipedia.org/wiki/Probability_density_function
			also called the 'probability distribution function'
	для 'непрерывных' сигналов то же, 
	что и 'функция массы вероятности' для 'дискретных' сигналов. 
	
	Для вычисления 'вероятности', 
	'плотность вероятности' умножается на 'диапазон значений'.
	
	'Гистограмма', 'функция массы вероятности' и 'функция плотности вероятности' 
	являются очень близкими понятиями. 
	
	Математики всегда используют их строго и непосредственно, 
	однако частенько, Вы будете обнаруживать, 
	что многие ученые и инженеры используют их друг вместо друга 
	(и, следовательно, некорректно).
	
	При вычислении гистограмм, когда число уровней, 
	которые может принимать каждый отсчет, 
	значительно превышает число отсчетов в сигнале, 
	можно столкнуться с проблемой. 
	
	Это также относится к сигналам, 
	представленным в виде чисел с плавающей запятой, 
	где каждый отсчет хранится как дробная величина. 
	
	Решением этой проблемы является метод носящий название 'бункерование' (binning). 
	https://en.wikipedia.org/wiki/Data_binning
	
	'Биннинг данных' , также называемый 'дискретным биннингом данных' или 'сегментированием данных', 
	представляет собой метод предварительной обработки данных, 
	используемый для снижения влияния незначительных ошибок наблюдения. 
	
	Исходные значения данных, которые попадают в заданный небольшой интервал, 'бин', 
	заменяются значением, представляющим этот интервал, 
	часто центральным значением (средним или медианным).
	
	Это связано с 'квантованием': биннинг данных работает на оси абсцисс, 
	в то время как квантование работает на оси ординат. 
	
	'Биннинг' является 'обобщением округления'.
	
	Оно выполняется следующим образом, 
	произвольно выбирается длина гистограммы, 
	так чтобы она была некоторым удобным числом, скажем 1000 точек, 
	так называемых 'бункеров' (групп сигналов) или 'бинов' (binns).
	
	Величина каждого 'бункера' представляет общее количество отсчетов в сигнале, 
	которые имеют значение в пределах некоторого диапазона. 
	
	Представьте, например, сигнал с плавающей запятой, 
	содержащий значения между 0,0 и 10,0 
	и гистограмму с 1000 бункеров. 
	
	Бункер 0 на гистограмме - это число отсчетов в сигнале со значением между 0 и 0,01, 
	бункер 1 - это число отсчетов со значением между 0,01 и 0,02 
	и т.д. до бункера 999, 
	содержащего число отсчетов со значением между 9,99 и 10,0. 
	
	'Статистическое биннинг данных' - 
	это способ 'группировки чисел' более или менее непрерывных значений 
	в меньшее количество «бинов». 
	
	Например, если у вас есть данные о группе людей, 
	вы можете захотеть организовать их возраст 
	в меньшее количество 'возрастных интервалов' 
	(например, группируя каждые пять лет вместе). 
	
	Его также можно использовать в многомерной статистике , 
	бинируя в нескольких измерениях одновременно.

	В цифровой 'обработке изображений' «биннинг» имеет совершенно иное значение. 
	
	'Биннинг пикселей' - это процесс объединения блоков 'соседних пикселей' 
	по всему изображению 
	путем суммирования или усреднения их значений 
	во время или после считывания. 
	
	Это уменьшает объем данных; 
	также относительный уровень шума в результате ниже.
	
	Calculation of binned histogram 
*/
static	void Calculation_of_binned_histogram() {
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	const	int			N				{10'000};	//	Количество виртуальных отсчетов
	const	int			MAX_INTENSITY	{255};		//	Максимально возможная величина отсчета
	int 					signals_array[N];			//	Массив отсчетов сигнала
	// 	1.
	std::random_device 	rd; 						// 	Класс предварительной генерации случайных битов 
	// 	2.
	std::mt19937 		gen_mt{rd()};				// 	Класс генерации случайных битов криптозащищенных
	// 	3.											// 	Класс генерации случайных битов равномерно распределенных
	std::uniform_int_distribution<int> 	uniform_distribution(0, MAX_INTENSITY); 
	
	for (int i = 0;	i < N; ++i) {
		//	оператор вызова функции .operator()() каждым вызовом даст новое случайное число
		signals_array[i] = uniform_distribution(gen_mt);		
	}
	//	Покажем для примера, чем мы нафоршировали массив
	for (int i = 0;	i < 10; ++i) {
		cout		<<	signals_array[i] << ",  ";
	}
	cout		<<	endl;
	const int	histogramm_binns					{20};	//	Количество бинн в гистограмме (групп отсчетов)
	int			histogramm[histogramm_binns] = 	{};		//	Определяем массив гистограммы с инициализацией нулями
	//	Формируем гистограмму минимальными значениями каждого бина
	int			binns_index	=	MAX_INTENSITY / histogramm_binns + 1;
	for (int i = 0;	i < N; ++i) {
		++histogramm[signals_array[i] / binns_index];
	}
	//	Смотрим значения гистограммы
	for (int i = 0;	i < histogramm_binns; ++i) {
		cout		<<	histogramm[i] << ",  ";
	}
		cout		<<	endl;
	//	Прорисуем гистограмму
	for (int i = 0;	i < histogramm_binns; ++i) {
		cout << std::setw(2) << i << ' ' <<  std::string((int)(std::sqrt(histogramm[i])), '*')  <<  endl; 
	}
}

