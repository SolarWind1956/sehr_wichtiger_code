/*
	********************************************************************************************************
	Сигнал против процесса лежащего в его основе 
	
	Статистика это наука об интерпретации численных данных, 
	таких как полученные сигналы. 
	
	Для сравнения, 
	теория вероятности используется в ЦОС для понимания процессов, 
	генерирующих сигналы. 
	
	Различие между полученным сигналом 
	и 
	процессом, лежащим в его основе, 
	хотя они и тесно связаны, 
	является ключом к большому количеству методов ЦОС. 
	
	Например, представьте себе создание сигнала, 
	содержащего 1000 точек, 
	тысячекратным подбрасыванием монеты. 
	
	Если монета падает орлом, соответствующий отсчет принимает значение единицы. 
	
	Решка и соответствующий отсчет устанавливается в ноль. 
	
	Процесс, создающий этот сигнал, имеет среднее значение 0,5, 
	заданное относительной вероятностью каждого возможного исхода: 
	50% орел, 50% решка. 
	
	Однако вряд ли фактический 1000 точечный сигнал 
	будет иметь среднее значение точно 0,5. 
	
	Каждый раз, когда генерируется сигнал, 
	случайные события будут делать число единиц и нулей слегка разнящимися. 
	
	Вероятности основного процесса постоянны, 
	но статистика полученного сигнала при повторении эксперимента всякий раз меняется. 
	
	Эта произвольная нерегулярность, обнаруживаемая в фактических данных, 
	имеет такие названия как: 
	'статистическая вариация', 
	'статистическая флюктуация' и 
	'статистический шум'.
	
	Обсудим здесь небольшую дилемму. 
	
	Как Вы определяете, 
	обращается ли автор к статистике фактического сигнала 
	или 
	к вероятности основного процесса, 
	создающего сигнал, 
	когда Вы видите термины “среднее значение” и “стандартное отклонение”? 
	
	К сожалению, контекст является единственным способом, 
	которым Вы можете сообщить об этом 
	(для случайной величины вместо 'среднего значения' используют термин 'математическое ожидание', 
	а при описании 'стандартного отклонения' часто пользуются таким приемом: 
	'детерминированная величина' – 'среднеквадратичная величина', 
	а 'стохастическая' – ;среднеквадратическая' – прим. перев.). 
	
	Дело не обстоит так для всех терминов статистики и теории вероятности. 
	
	Например, 'гистограмма' и 'функция массы вероятности' 
	(обсуждаемые в следующем разделе) соответствуют концепции разных названий. 
	
	---------------------------------------------------------------------------------------------------------------------------------------------------------------
	Гистограмма, функция массы вероятности и функция плотности вероятности 
	
	Предположим, что мы подключили 8 битовый аналого-цифровой преобразователь к компьютеру 
	и получили 256000 отсчетов некоторого сигнала изображения. 
	
	Каждый отсчет может принимать одно из 256 значений уровня яркости (интенсивности) от 0 до 255. 
	
	'Гистограмма' показывает 'число отсчетов' сигнала, 
	принимающих 'каждое из этих возможных значений'. 
	
	Так же, как и в случае среднего значения, 
	'статистический шум' (шероховатость) гистограммы 
	'обратно пропорционален' 
	'квадратному корню числа используемых отсчетов'.

	В соответствии со способом задания определения гистограммы, 
	сумма всех значений в гистограмме 
	должна быть равна числу точек в сигнале.
	
	Гистограмма может использоваться для эффективного вычисления 
	'среднего значения' и 'стандартного отклонения' 
	очень больших наборов данных. 
	
	Это особенно важно для изображений, которые могут содержать миллионы отсчетов. 
	
	Гистограмма группирует отсчеты имеющие одинаковые значения вместе. 
	
	Это позволяет вычислять статистику, 
	обрабатывая несколько групп вместо огромного числа индивидуальных отсчетов. 
*/
static void histogramm_building_1()	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	
	const	int	N				{100};		//	массив яркостей
	const 	int 	hist_arr_dim		{N / 10};	//	массив гистограммы
	const 	int 	max_intensity	{255};		//	Максимальный уровень яркости (интенсивности)
	const 	int group_boundary	{max_intensity / hist_arr_dim};	//	Индекс групп отсчетов сигнала изображения
	
	int 	intensity_array[N];
	
	std::random_device 	rd{};
	std::mt19937 		generator{rd()};
	
	#if 0	
	std::mt19937 		generator			{static_cast<unsigned int>(clock())};
	generator.seed		= unsigned(std::time(nullptr));
	//	Это все работает, но уже категорически не рекомендовано к использованию
	//	начиная с С++11	!!!!!!!!!!!
	#endif	
 
    // Values near the mean are the most likely. Standard deviation affects the dispersion of generated values from the mean.
    std::uniform_int_distribution<int> unif_distr{0, max_intensity};
 
    // Draw a sample from the normal distribution and round it to an integer.
    auto random_int = [&unif_distr, &generator]{ return std::lround(unif_distr(generator)); };

	for (int i = 0;	i < N; ++i) {
		intensity_array[i] = random_int();	//	Generating a random number in a semi-open range [0, 255)
		cout << intensity_array[i] << ",   ";
	}
	cout << endl;
	//	Массив гистограммы яркостей
	
	int	hist_arr[hist_arr_dim];
	for (int i = 0;	i < hist_arr_dim; ++i) 
		hist_arr[i]	= 0;
	
	cout << "Формирование массива гистограммы" << endl;	
	for (int i = 0;	i < N; ++i) 		{
		int 	group_index 	= intensity_array[i] / group_boundary;
		cout << group_index << ",   ";
		++hist_arr[group_index]; 
	}	
	cout << endl;
	cout << endl;
	cout << "Массив гистограммы" << endl;
	for (int i = 0;	i < hist_arr_dim; ++i) 
		cout << hist_arr[i] << ",   ";
	cout << endl;
	
	// Построение гистограммы
	for (int i = 0;	i < hist_arr_dim; ++i) {
		for (int j = 0;	j < hist_arr[i]; ++j) 
			cout << "*";
		cout << endl;
	}	
}	
