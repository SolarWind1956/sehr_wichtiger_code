/*
	Конструктор по умолчанию для std::mt19937 инициализирует внутреннее состояние известным стандартным значением. 
	
	Это гарантирует, что 'выходная последовательность', генерируемая объектом mt19937, 
созданным конструктором по умолчанию, будет идентична на всех платформах – в отличие от rand(), 
которая на разных платформах часто генерирует разные последовательности.
	Чтобы получить другую выходную последовательность, нужно передать начальное значение конструктору std::mt19937.

	Сделать это в C++17 можно двумя способами – утомительным и простым. 
	
	Утомительный способ состоит в конструировании истинно случайного 19937-битного начального значения 
и его копировании в объект std::mt19937 в виде начальной последовательности, 
как показано ниже:
*/
void test() {
	cout << "I'm TEST 6 of Examples 11" << endl;
	
    std::random_device 	rd;		// Формирует случайную последовательность с помощью внешнего устройства

    uint32_t 	numbers[624];
	
	// Сгенерировать начальное состояние.
    std::generate	(	  numbers
						, std::end(numbers)
						, std::ref(rd)
					);
					// Generate initial state.

	// Скопировать созданное состояние в "начальную последовательность"
	using SeedSeq_	=	std::seed_seq; 		// Хранит вектор беззнаковых целых значений, 
											// которые можно использовать 
											// как начальное значения для механизма получения случайных чисел.
    SeedSeq_	sseq	(	  numbers
							, std::end(numbers)
						);
						// Copy our state into a heap-allocated "seed sequence".
						
	// Инициализировать генератор mt19937 скопированным состоянием
    std::mt19937 g(sseq);
        // Initialize a mt19937 generator with our state.

}
/*
	Здесь тип SeedSeq может быть std::seed_seq (в действительности std::vector, использует память в куче) 
или вручную написанным классом «начальной последовательности», как в следующем примере:
*/
template<class It>
class SeedSeq 
{
    It begin_;
    It end_;
public:
	// types
	typedef unsigned int 	result_type;

	// constructors
	SeedSeq();
	
    SeedSeq(It begin, It end) : begin_(begin), end_(end) 
	{
		cout << "I'm CTOR of template<class It> struct SeedSeq " << endl;
	}
	
	template <class T>
    SeedSeq(initializer_list<T> initlist);
	
	template <class InputIterator>
    SeedSeq(InputIterator begin, InputIterator end);
	  
	// no copy functions: copy constructor and copy assign operator
	SeedSeq(const SeedSeq&) 			= delete;
	void operator=(const SeedSeq&) 		= delete;

	// generating functions
	template <class RandomAccessIterator>
    void generate(RandomAccessIterator begin, RandomAccessIterator end)
	{
        assert((end - begin) <= (end_ - begin_));
        std::copy	(	  begin_
						, begin_ + (end - begin)
						, begin
					);
    }
	size_t size() const
	{
		return end_ - begin_;
	};
};

