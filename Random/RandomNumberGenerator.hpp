	template<class T>
	class SimplePRNG {
		unsigned long long 	state = 1;
	  public:
		static constexpr T min() { return 0; } 
		static constexpr T max() { return 0x7FFF; }
		// Оператор "вызова функции" ("вызываемой фунции") 
		T operator()() {
			cout << "Я оператор вызываемой функции T operator()() класса template<class T> class SimplePRNG" << endl;
			cout << state << endl;
			state = state * 1'103'515'245 + 12'345; //	
			unsigned  long long res = state / 32; // ();
			unsigned  long long result =  (state >> 16) & 0x7FFF;	//	(state >> 16)
														// 	0x7FFF == 32'767; 	Сдвиг вправо на 16 бит - >> 16  === 
														//	это то же самое, что разделить на 65536
			
			cout << state << "   " << res << "  " << result << endl;
			cout << state << "   " << integ_to_bin_str((int)res) << "  " << integ_to_bin_str((int)result) << endl;
						
			return result;			
		}
	};

