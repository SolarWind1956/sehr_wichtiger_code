/*
	--------------------------------------------------------------------------------------------------------------------
	Как это делается
 
	В этом примере мы реализуем процедуру, 
	которая выводит на экран гистограмму, 
	содержащую числа, создаваемые генератором случайных чисел. 
	
	Затем запустим все генераторы случайных чисел, 
	доступные в STL, 
	и воспользуемся нашей процедурой, чтобы исследовать результаты. 
	
	Данная программа содержит множество повторяющихся фрагментов, 
	поэтому может быть полезным просто скопировать 
	исходный код из репозитория, дополняющего эту книгу, 
	а не писать повторяющийся код вручную.
	
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------
	Реализуем вспомогательную функцию, 
	которая позволит сопровождать и выводить на экран 
	статистику для каждого типа генераторов случайных чисел. 
	
	Она принимает два параметра - количество сегментов и количество образцов. 
	
	Мы сразу увидим, для чего они нужны. 
	
	Тип генератора случайных чисел определяется с помощью шаблонного параметра RD. 
	
	Первое, что мы сделаем в этой функции, - 
	определим псевдоним типа для полученного численного типа чисел, 
	возвращаемых генератором. 
	
	Кроме того, убедимся, что у нас есть как минимум десять сегментов:
*/
template <typename RD>
void histogram 	( 	size_t 	partitions
				, 	size_t 	samples 
				)	{
	cout << "-------------- I'm " << __PRETTY_FUNCTION__ << endl;				
	// 	Убедимся, что у нас есть  как минимум десять сегментов, иначе, исправим ситуацию: 
	partitions = max<size_t>(partitions, 10);

	/*
		Далее создадим экземпляр генератора типа 'RD'. 
		
		Затем определим переменную-делитель с именем 'div'. 
		
		Все генераторы случайных чисел создают случайные числа 
		в диапазоне от 0 до RD::max(). 
		
		Аргумент функции 'partitions' позволяет вызывающей стороне выбирать, 
		на сколько сегментов мы разделим каждый диапазон случайных чисел. 
		
		Разделив 'наибольшее возможное значение' на 'количество сегментов', 
		мы узнаем, насколько большим является каждый из них:
	*/
	// Определим псевдоним типа для полученного численного  типа чисел, возвращаемых генератором.
	using 	rand_t 	= 	typename 	RD::result_type;

	/*
		Создадим экземпляр 'генератора случайных чисел' типа RD. 
		
		Можно передать конструктору любого генератора случайных чисел 
		'реальное  случайное число', 
		полученное от std::random_device (или, например, текущее  время на системных часах), 
		чтобы заставить его создавать разные случайные числа при каждом обращении.
		
		Это называется 'посевом'.
	*/
	RD 		rd;

	/*
		Все генераторы случайных чисел создают случайные числа 
		в диапазоне от 0 до RD::max().
	
		div - переменная - делитель
	
		Аргумент функции 'partitions' позволяет  вызывающей стороне выбирать, 
		на сколько 'сегментов' мы разделим каждый 'диапазон случайных чисел'. 
	
		Разделив 'наибольшее возможное значение' на 'количество сегментов', 
		мы узнаем, насколько большим является каждый из них: 
	*/	
	rand_t 	div {	(rand_t)	(	((double)RD::max() + 1.0 ) 
							/ 	(double)partitions
							)
				};

	/*
		Создадим вектор переменных-счетчиков. 
		
		Он будет иметь размер, равный количеству сегментов:
	*/	
	std::vector<size_t> 	v (partitions);

	/* 
		Получим случайные значения от генератора в количестве, 
		равном значению переменной 'samples'. 
		
		Выражение rd() получает случайное число от генератора 
		и изменяет его внутреннее состояние так, 
		чтобы  подготовить его к выдаче следующего случайного числа. 
		
		Разделив каждое  случайное число на 'div', мы получим номер сегмента, 
		в который оно попадает,  
		и можем увеличить соответствующий счетчик в векторе: 
	*/	
	for (size_t i{0}; i < samples; ++i ) 	{
		++v[rd() / div];
	}
	/*
		Теперь у нас есть «аккуратная» гистограмма, содержащая значения-примеры. 
		
		Чтобы вывести ее на экран, 
		нужно получить более подробную информацию о ее реальных значениях счетчика. 
		
		Извлечем самое большое значение с помощью алгоритма std::max_element. 
		
		Затем разделим это значение на 100. 
		
		Таким образом можно разделить все значения счетчика на 'max_div' 
		и вывести множество звездочек на консоль, 
		не выходя за значение ширины, равное 100. 
		
		Если самое крупное значение меньше 100 
		(это может произойти в случае применения небольшого количества образцов), 
		то воспользуемся 'max' для получения минимального делителя 1:
	*/
	/*	
	 	Построение гистограммы на консоли с максимальной длиной строки в 100 звездочек '*'
	*/
	
	// 	Извлечем самое большое значение с помощью алгоритма max_element.
	rand_t		max_elm	(	*std::max_element	( 	begin(v)
												, 	end(v) 
												) 	
						);
	
	/* 
		Вычислим максимальный делитель пропорциональности 
		величины счетчиков в диапазоне
		для определения длины строки гистограммы для каждого диапазона (сегмента)
	*/	
	rand_t		max_div		(	max	(	max_elm / 100
									, 	rand_t{1} 
									) 
							);
	/*
		Выведем для каждого сегмента (диапазона) строку гистрограммы, 
		постоив таким образом гистограмму распределения генерации случайных чисел.
	
		Очевидно, что идеальным вариантом является прямоугольная гистограмма.
	*/
	for (size_t i{0}; i < partitions; ++i) 	{
		cout << std::setw(2) << i << ": " << std::string(v[i] / max_div, '*') << '\n';
	}
	cout << endl;
}
