static	void 	our_random_generator ()
{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;
	cout << '\n';
	cout << "Работает <our_random_generator ()>  " << endl;
	cout << '\n';

	size_t	partitions	{20};			//	Количество сегментов
	size_t	samples		{1'000'000};		//	Количество отсчетов

	/*
		std::random_device. 
		
		Это устройство пытается распределить случайность поровну между всеми возможными значениями. 
		
		Кроме того, этот генератор недетерминированный: 
	*/	
	cout << "std::random_device" << '\n';
	histogram<std::random_device>(partitions, samples);
	/*
		http://www.cyberguru.ru/programming/cpp/pseudo-number-generators-with-applied-crypto.html?start=1
		
		Генераторы случайных чисел относятся к одному из двух классов: 
		-	детерминированные 
		и 
		-	недетерминированные. 
		
		Детерминированный RNG (генератор случайных чисел) состоит из алгоритма, 
		генерирующего последовательность битов исходя из начального значения. 
		
		Недетерминированный RNG дает вывод, 
		зависящий от некоторого непредсказуемого физического источника, 
		не контролируемого человеком.

		Неспециалисты обычно называют 'недетерминированный' генератор 
		«генератором истинно случайных чисел».
	*/
	/*  
		std::default_random_engine. 
		
		Тип генератора, на который ссылается данный тип, 
		зависит от конкретной реализации.  
		
		Он может оказаться одним из следующих генераторов:
	*/	
	cout << "\nstd::default_random_engine" << '\n';
	histogram<std::default_random_engine>(partitions, samples);

	cout << "\nstd::minstd_rand0" << '\n';
	histogram<std::minstd_rand0>(partitions, samples);
	
	cout << "\nstd::minstd_rand" << '\n';
	histogram<std::minstd_rand>(partitions, samples);

	cout << "\nstd::mt19937" << '\n';
	histogram<std::mt19937>(partitions, samples);
	
	cout << "\nstd::mt19937_64" << '\n';
	histogram<std::mt19937_64>(partitions, samples);

	cout << "\nstd::ranlux24_base" << '\n';
	histogram<std::ranlux24_base>(partitions, samples);
	
	cout << "\nstd::ranlux48_base" << '\n';
	histogram<std::ranlux48_base>(partitions, samples);

	cout << "\nstd::ranlux24" << '\n';
	histogram<std::ranlux24>(partitions, samples);
	
	cout << "\nstd::ranlux48" << '\n';
	histogram<std::ranlux48>(partitions, samples);

	cout << "\nstd::knuth_b" << '\n';
	histogram<std::knuth_b>(partitions, samples);
}
/*
	Как это работает
 
	Как правило, перед использованием генератора случайных чисел 
	нужно создать 'объект этого класса'. 
	
	Полученный объект может быть вызван как функция без параметров, 
	поскольку он перегружает operator()(). 
	
	Тогда каждый вызов 
	будет приводить к получению нового случайного числа. 
	
	Все очень просто. 
	
	В этом разделе мы написали довольно сложную программу, 
	чтобы чуть больше узнать о генераторах случайных чисел. 
	
	Поработайте с получившейся программой, 
	запуская ее с разными величинами количества отсчетов, и проверьте следующее:
	
	-	чем больше образцов мы возьмем, тем больше будут равны наши счетчики разделов;

	-	неравенство счетчиков разделов значительно отличается между отдельными генераторами;
	
	-	для большого числа образцов становится понятно, что производительность отдельных генераторов различается;

	Шаблоны распределения будут выглядеть одинаково: 
	генераторы постоянно создают одни и те же последовательности; 
	
	это говорит о том, что они совсем не случайны. 
	
	Такие генераторы называются 'детерминированными', 
	поскольку можно предсказать получаемые значения. 
	
	Единственным исключением являет ся std::random_device.
 
	Как видите, необходимо рассмотреть несколько характеристик. 
	
	Для большинства стандартных приложений достаточно применить std::default_random_engine. 
	
	Эксперты в области криптографии или в других областях, 
	чувствительных к безопасности, будут тщательно выбирать один из доступных генераторов, но для нас, 
	типичных программистов, это не так важно.
 
	Из данного примера следует сделать три вывода.
	
	1. 	Как правило, std::default_random_engine - это хороший вариант по умолчанию для типичного приложения.
	
	2. 	Если действительно нужно получить недетерминированные случайные числа, 
		то поможет std::random_device.
 
	3. 	Можно передать конструктору любого генератора случайных чисел реальное случайное число, 
		полученное от std::random_device (или, например, текущее время на системных часах), 
		чтобы заставить его создавать разные случайные числа при каждом обращении. 
		
		Это называется 'посевом'.
	
	Обратите внимание: std::random_device может откатиться к одному из детерминированных генераторов, 
	если библиотека не поддерживает недетерминированные генераторы.	
*/

