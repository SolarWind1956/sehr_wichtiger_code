// 	Простейшая реализация 'std::uniform_int_distribution' выглядит примерно так:
template<class Int>
class 	uniform_int_distribution {
    using 	UInt 	= 	std::make_unsigned_t<Int>;
    UInt 	m_min
		, 	m_max
		;
public:
    uniform_int_distribution(Int a, Int b) : m_min(a), m_max(b) 
	{}

    template<class Gen>
    Int operator()(Gen& g) {
        UInt 	range = (m_max - m_min);
        assert(g.max() - g.min() >= range);
        while (true) {
            UInt 	r = g() - g.min();
            if (r <= range) {
                return Int(m_min + r);
            }
        }
    }
};
//	-----------------------------------------------------------------------------------------------------------------------------------------------------------------
void test() {
	cout << "I'm TEST 13 of Examples 11" << endl;

    std::mt19937 						g;
    std::uniform_int_distribution<short> 	d(576, 4979);
	
    for (int i = 0; i < 100; ++i) {
        assert(576 <= d(g) && d(g) <= 4979);
    }
}
