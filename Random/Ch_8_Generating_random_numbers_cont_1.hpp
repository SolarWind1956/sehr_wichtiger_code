/*
	*************************************************************************************************************************
	Распределения		-	Distributions
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	Генерируем случайные числа  и создаем конкретные распределения с помощью STL
	
	Как это делается
 
	В этом примере мы будем генерировать случайные числа, 
	придавать им форму и выводить на экран шаблоны распределения. 
	
	Таким образом, рассмотрим их все и разберем их самые важные свойства, 
	которые могут оказаться полезными, если потребуется смоделировать что-то конкретное.
	
	Для каждого распределения, предоставляемого STL, выведем гистограмму, 
	чтобы увидеть его характеристики, поскольку каждое из них выглядит особенным образом. 
	
	Гистограмма принимает в качестве аргумента распределение и количество образцов, 
	которые будут взяты из него. 
	
	Затем создадим генератор случайных чисел по умолчанию и ассоциативный массив. 
	
	В последнем будут соотнесены значения, 
	полученные из распределения, со счетчиками, 
	показывающими, как часто встречается то или иное значение. 
	
	Мы всегда создаем экземпляр генератора случайных чисел, 
	потому что все распределения 
	используются только в качестве функции для формирования случайных чисел, 
	которые все еще должны быть сгенерированы.
*/
template <typename T>
void 	print_distro 	( 	T 		distro
						, 	size_t 	samples 
						)	{
	cout << "-------------- I'm " <<  __PRETTY_FUNCTION__  << endl;						
	/*
	  	Cоздадим 'генератор случайных чисел' 'по умолчанию' 
		и 'ассоциативный массив'. 
	  
		В последнем будут  соотнесены значения, полученные из распределения, 
	  	со счетчиками, показывающими, как часто встречается то или иное значение.
	*/
	std::default_random_engine		d_r_e;
	std::map<int, size_t>			m;

	/*
		Возьмем столько образцов, сколько указано в переменной samples, 
		и заполним ими ассоциативный массив счетчиков. 
	
		Таким образом получим  очередную гистограмму.
	*/
	for (size_t i{0}; i < samples; ++i ) 	{
		/*
			Простой вызов d_r_e() даст необработанное простое  число, 
			distro(d_r_e) придает случайным числам форму с помощью объекта распределения: 
		*/	
		m[distro(d_r_e)] += 1;
		/*
			Метод индексации ассоциативного массива (таблицы) гистограммы std::map
			создаст новую строку с std::pair(distro(d_r_e), m[distro(d_r_e)])
			если этой строки еще не было, 
			или сделает инкремент для значения m[distro(d_r_e)], 
			если такой образец (отсчет) уже учтен в таблице.
		*/
	}

	/* 
		Чтобы получить выходные данные, которые помещаются в окно консоли,  
		нужно узнать самое большое значение счетчика. 
		
		Функция из стандартной библиотекм std::max_element 
		определит такое значение путем сравнения всех связанных счетчиков  в массиве 
		и возвратит итератор, 
		указывающий на узел, содержащий данное максимальное значение из множества отсчетов (образцов).
	*/	
	size_t 	max_elm { 	std::max_element		( 	begin	(m)
											, 	end		(m)
											,	[] (const auto& a, const auto& b) { 
													return a.second < b.second;	// 	Счетчики храняся в second
												}
											)->second 
					};
	/*
		Зная это значение std::max_element, можем определить, 
		на какое число следует разделить все значения счетчиков, 
		чтобы уместить полученный результат  в окно консоли.
	*/	
	size_t 	max_div (std::max	( 	max_elm / 100
								, 	size_t{1} 
								) 
					);
	/*
		Теперь пройдем по массиву в цикле и выведем полоски из символов '*' 
		для  всех счетчиков большого размера. 	
	*/
	for (const auto [randval, count] : m) 
	{
		/*
			Остальные значения, совсем маленькие, отбросим, 
			поскольку  некоторые генераторы случайных чисел 
			распределяют числа так широко, 
			что  это переполнит наши окна консоли.
		*/	
		if (count < max_elm / 200) { 
			continue; 
		}

		cout	<< setw(3) << randval 
				<< " : "
				<< string (count / max_div, '*') 
				<< '\n';
	}
}
/*
  *	**********************************************************************************
  *	Основная  подпрограмма
  *	**********************************************************************************
  */
static 	void 	random_distro ()
{
	cout << '\n';
	cout << "Работает < random_distro () >  " << endl;
	cout << '\n';
	/*	
		Зададим количество взятых образцов случайных чисел,
	*/
	size_t	samples		{1'000'000};	//	Количество отсчетов

	/* 
		Сначала попробуем распределения 
		std::uniform_int_distribution и std::normal_ distribution. 
	
		Они используются в большинстве случаев, когда нужно применить генератор случайных чисел.
	
		Равномерное распределение принимает два  значения, 
		указывая нижнюю и верхнюю границы диапазона, 
		в котором будут  распределены случайные значения. 
		
		Выбрав 0 и 9, мы получим одинаково часто  встречающиеся значения между 0 и 9 (включительно).
	*/	
	cout << "uniform_int_distribution\n";
	print_distro (std::uniform_int_distribution<int>{0, 9}, samples);
	
	/*
		Нормальное распределение принимает в качестве аргументов 
		математическое ожидание и среднеквадратическое отклонение. 
	*/	
	cout << "normal_distribution\n";
	print_distro (std::normal_distribution<double>{0.0, 2.0}, samples);

	/*
		std::piecewise_constant_ distribution. 
		
		Оно принимает в качестве аргументов два входных диапазона.  
	
		Первый диапазон содержит числа, которые указывают 'границы интервалов'.  
	
		Определив их как 0, 5, 10, 30, 
		получим три интервала, 
		простирающиеся от 0 до 4,  от 5 до 9 и от 10 до 29. 
	
		Еще один входной диапазон определяет 'веса входных' диапазонов. 
		
		Установив значения этих весов равными 0.2, 0.3, 0.5, мы укажем,  
		что из соответствующих интервалов 
		случайные числа будут получены с вероятностями 20, 30 и 50 %.
	
		Внутри каждого из интервалов значения будут иметь  одинаковую вероятность выпадения. 
	*/	
	std::initializer_list<double> 	intervals	{ 0, 5, 10, 30 };
	std::initializer_list<double> 	weights		{ 0.2, 0.3, 0.5 };
	
	cout << "piecewise_constant_distribution\n";
	
	print_distro	( 	std::piecewise_constant_distribution<double>	{ 	begin(intervals)
																, 	end(intervals)
																, 	begin(weights)}
				, 	samples 
				);
	/*
		Распределение std::piecewise_linear_distribution создается аналогично, 
		но веса  работают совершенно по-другому. 
	
		Для каждой граничной точки интервала  существует одно значение веса.
	
		При переходе от одной границы к другой вероятность интерполируется линейно. 
		
		Воспользуемся теми же интервалами, но  передадим другой список весов:
	*/	
	cout << "piecewise_linear_distribution\n";
	
	std::initializer_list<double> 	weights2	{ 0, 1, 1, 0 };
	
	print_distro	(	std::piecewise_linear_distribution<double>	{	begin(intervals)
															, 	end(intervals)
															, 	begin(weights2)}
				, 	samples
				);
	/*
		Распределение Бернулли - это еще одно важное распределение, 
		поскольку распределяет лишь значения «да/нет», 
		«попадание/промах» или «орел/решка» 
		с конкретной вероятностью. 
		
		Его выходными значениями будут только 0 и 1.  
	*/	
	cout << "bernoulli_distribution\n";
	
	print_distro	(	std::bernoulli_distribution{ 0.75 }
				, 	samples
				);
	/*
		std::discrete_distribution. 
		
		В нашем случае инициализируем его дискретными  значениями 1, 2, 4, 8. 
	
		Они интерпретируются как веса для возможных выходных  значений от 0 до 3. 
	*/	
	cout << "discrete_distribution\n";
	
	print_distro	(	std::discrete_distribution<int>{ {1, 2, 4, 8} }
				, 	samples
				);
	/*
		Существует множество других генераторов распределений. 
	
		Они полезны только  в очень специфических ситуациях.
	*/	
	cout << "binomial_distribution\n";
	print_distro	(	std::binomial_distribution<int>{10, 0.3}
				, 	samples
				);
	
	cout << "negative_binomial_distribution\n";
	print_distro	(	std::negative_binomial_distribution<int>{10, 0.8}
				, 	samples
				);

	cout << "geometric_distribution\n";
	print_distro	(	std::geometric_distribution<int>{0.4}
				, 	samples
				);
	
	cout << "exponential_distribution\n";
	print_distro	(	std::exponential_distribution<double>{0.4}
				, 	samples
				);
	
	cout << "gamma_distribution\n";
	print_distro	(	std::gamma_distribution<double>{1.5, 1.0}
				, 	samples
				);
	
	cout << "weibull_distribution\n";
	print_distro	(	std::weibull_distribution<double>{1.5, 1.0}
				, 	samples
				);
	
	cout << "extreme_value_distribution\n";
	print_distro	(	std::extreme_value_distribution<double>{0.0, 1.0}
				, 	samples
				);
	
	cout << "lognormal_distribution\n";
	print_distro	(	std::lognormal_distribution<double>{0.5, 0.5}
				, 	samples
				);
	
	cout << "chi_squared_distribution\n";
	print_distro	(	std::chi_squared_distribution<double>{1.0}
				, 	samples
				);
	
	cout << "cauchy_distribution\n";
	print_distro	(	std::cauchy_distribution<double>{0.0, 0.1}
				, 	samples
				);
	
	cout << "fisher_f_distribution\n";
	print_distro	(	std::fisher_f_distribution<double>{1.0, 1.0}
				, 	samples
				);
				
	cout << "student_t_distribution\n";
	print_distro	(	std::student_t_distribution<double>{1.0}
				, 	samples
				);
}
/*
	*********************************************************************************************************************
	Как это работает
 
	Хотя генераторы случайных чисел нас не интересуют до тех пор, 
	пока работают быстро и создают числа максимально случайным образом, 
	следует 'тщательно выбирать' "распределение" в зависимости от решаемой задачи.
	
	Чтобы использовать любое распределение, 
	сначала нужно 'создать' для него 'соответствующий объект'. 
	
	Мы видели, что разные распределения принимают разные аргументы конструктора. 
	
	В описании примера мы кратко остановились на некоторых видах распределения, 
	поскольку большинство из них слишком специфичны и/или сложны, 
	чтобы рассматривать их здесь. 
	
	Не волнуйтесь, все они подробно описаны в документации к C++ STL.
	
	Однако как только появляется экземпляр распределения, 
	можно вызвать его как функцию, 
	которая принимает в качестве единственного параметра 
	объект генератора случайных чисел. 
	
	Классы распределение - это функторы, они имеют функции вызова operator()().
	
	Далее объект распределения получает случайное число, 
	придает ему некую форму 
	(которая полностью зависит от выбранного распределения), 
	а затем возвращает его нам. 
	
	Это приводит к появлению совершенно разных гистограмм, 
	что мы видели после запуска программы.
	
	Программа, которую мы только что написали, 
	позволит нам получить наиболее полную информацию о разных распределениях. 
	
	В дополнение к этому рассмотрим самые важные виды распределения (табл. 8.2). 
	
	Для всех остальных видов распределения вы можете обратиться к документации C++ STL.	
	
	Таблица 8.2
	---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	Распределение					Описание
	---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	std::uniform_int_distribution 		Это распределение принимает в качестве аргументов конструктора 
									нижнюю и верхнюю границы. 
									
									Вероятность генерации каждого значения, 
									лежащего в пределах этих границ (включительно), 
									будет одинаковой, что делает гистограмму плоской. 
									
									Данное распределение может представлять собой, 
									например, бросок кубика, 
									поскольку каждая грань может выпасть с одинаковой вероятностью
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	std::normal_distribution			Нормальное, или гауссово, распределение встречается в природе практически везде. 
	
									Его версия из STL принимает в качестве аргументов конструктора 
									математическое ожидание и среднеквадратическое отклонение 
									и формирует гистограмму в виде крыши. 
									
									Если мы сравним размеры тела, либо IQ людей или других животных, 
									или оценки учеников, то увидим, что эти числа тоже имеют нормальное распределение
	-----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	std::bernoulli_distribution			Распределение Бернулли идеально подходит в том случае, 
									если мы хотим подбросить монетку или получить ответ «да/нет». 
									
									Оно генерирует только значения 0 и 1, 
									единственным параметром конструктора является значение 1
	---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	std::discrete_distribution			Дискретное распределение будет интересно только в том случае, 
									если нужно получить ограниченный набор значений, 
									для каждого из которых мы хотим определить свою вероятность. 
									
									Его конструктор принимает список весов, 
									и оно будет генерировать случайные числа с вероятностью, зависящей от их веса. 
									
									Если мы хотим смоделировать случайно распределенные группы крови, 
									когда каждое из четырех значений имеет конкретную вероятность появления, 
									то данное распределение идеально подойдет
	---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
	
*/
