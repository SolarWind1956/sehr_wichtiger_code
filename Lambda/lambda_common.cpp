/*
Возможные варианты синтаксиса лямбда функций

[ capture ] ( params ) mutable exception attribute -> ret { body }
[ capture ] ( params ) -> ret { body }
[ capture ] ( params ) { body }
[ capture ] { body }

Первый вариант является полным, но не запрещается использовать сокращённые вариации записи функций.

capture         (Предложение capture - также известное как предложение фиксации, 
                        элемент объявления лямбда-выражения в C++ спецификации) 
                        - список  внешних захватываемых объектов, 
                        они могут захватываться как по ссылке, так и по значению - копированием.

params          (Также называется лямбда-объявлением) - список параметров, передаваемых в лямбда функции, 
                        данная часть будет аналогична записи аргументов для обычных функций. 
                        (Optional - и даже скобки круглые можно опустить, если нет параметров).

mutable         Спецификация - использование mutable позволяет модифицировать копии объектов, 
                         которые были захвачены копированием. В обычном варианте они не будут модифицироваться.
                          (Optional).

exception     (throw() - спецификация)  - обеспечивает спецификацию исключения, 
                        то есть лямбда функции также как и обычные функции могут выкидывать исключения.
                         (Optional).

attribute       - обеспечивает спецификацию атрибута, 
                        таких атрибутов в спецификации C++ определено всего два:
                        ([[noreturn]], [[carries_dependency]])
                         (Optional).

-> ret           - возвращаемое значение лямбда-выражения (функции).
                         (Optional).

body            - тело лямбда-функции в фигурных скобках.

Хотя лямбда-выражения чаще всего объявляются в теле функции, можно объявлять их в любом месте, 
где можно инициализировать переменные.

*/

