#include "my_std_library.h"
using namespace std;
/*
Возможные варианты синтаксиса лямбда функций

[ capture ] ( params ) mutable exception attribute -> ret { body }
[ capture ] ( params ) -> ret { body }
[ capture ] ( params ) { body }
[ capture ] { body }

params          (Также называется лямбда-объявлением) - список параметров, передаваемых в лямбда функции,
                        данная часть будет аналогична записи аргументов для обычных функций.
                        (Optional - и даже скобки круглые можно опустить, если нет параметров).

                        В дополнение к возможности фиксации переменных, 
                        лямбда-выражения могут принимать входные параметры. 
                        Список параметров (лямбда-декларатор в стандартном синтаксисе) является необязательным 
                        и в большинстве аспектов напоминает список параметров для функции.

                        Общая лямбда, представленная в C ++ 14,  может захватывать параметры с auto спецификатором.
                        const auto l = [](auto a, auto b, auto c) {};

                        // is equivalent to
                        struct anonymous
                        {
                                    template <class T0, class T1, class T2>
                                    auto operator()(T0 a, T1 b, T2 c) const
                                    {
                                    }
                        }
};
*/

/*
  *     ********************************************************************
  *     Основная функция
  *     ********************************************************************
  */
void  params_of_lambda()
{
        cout << '\n' << "Работает <params_of_lambda()>  " << '\n' << endl;

        int my_par = rand();                                // Готовим параметр для лямда-выражения
        cout << my_par << endl;
        // Когда ламбда-выражению в определении передаются параметры,
        // его вызов осуществляется как обычной функции: аргумент указываетя  также в круглых скобках
        // Именно в этом месте и осуществляеся привязка лямбда-выражения к захватываемым переменным
        int timestwo = []( int x ) -> int
                                        {
                                                return x * 2;
                                        } 
                                        ( my_par / 5 );                                 // Передача аргументов в функцию из вызывающего объекта

        my_par = 12;            // Это изменение уже никак не отразится на результате лямбда

        // Print the result. Результат будет расчитан по значениям переменных, которые были
        // захвачены на момент объявления лямбда выражения
        cout << timestwo << endl;

}

