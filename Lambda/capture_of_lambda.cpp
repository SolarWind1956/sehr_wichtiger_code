void  capture_of_lambda() 
{
        cout << '\n' << "Работает <capture_of_lambda()>  " << '\n' << endl;

        //      Захват ВСЕХ по ссылке 
        int x = 100, y = 200;
        auto print = [&] ()
                                { // Capturing object by reference
                                        std::cout << "x and y " << " : " << x++ << " , " << y++ << std::endl;
                                };
        //print();
        //std::cout << "x and y after lambda " << " : " << x << " , " << y << std::endl;
}

