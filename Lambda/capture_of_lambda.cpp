/*
Возможные варианты синтаксиса лямбда функций

[ capture ] ( params ) mutable exception attribute -> ret { body }
[ capture ] ( params ) -> ret { body }
[ capture ] ( params ) { body }
[ capture ] { body }

capture         (Предложение capture - также известное как предложение фиксации,
                        элемент объявления лямбда-выражения в C++ спецификации)
                        - список  внешних захватываемых объектов,
                        они могут захватываться как по ссылке, так и по значению - копированием.

Лямбда-выражение может добавлять новые переменные в тексте, 
а также получать доступ к переменным из окружающей области  (внешней  области видимости) – 
в терминах лямбда - захватывать их.

Лямбда-выражение начинается с предложения capture (лямбда - знаком в стандартном синтаксисе),
который указывает, какие переменные захватываются и является ли захват значением или ссылкой. 
Доступ к переменным с префиксом с амперсандом (&) осуществляется по ссылке, 
а к переменным без префикса - по значению. 
Пустое предложение фиксации capture ([ ]) показывает, что тело лямбда-выражения 
не осуществляет доступ к переменным во внешней области видимости.

Режим записи по умолчанию (захват - по умолчанию в стандартном синтаксисе) 
можно использовать для указания способа записи ВСЕХ внешних переменных, 
на которые имеются ссылки в лямбда-выражении: 
[&] означает, что все переменные, на которые вы ссылаетесь, записываются по ссылке, и 
[=] означает, что они записываются по значению. 
Можно сначала использовать режим фиксации по умолчанию, 
а затем применить для определенных переменных другой режим.

Например, если тело лямбда-выражения осуществляет доступ к внешней переменной total по ссылке, 
а к внешней переменной factor по значению, следующие предложения фиксации попарно эквивалентны:
[&total, factor]                        - к total по ссылке, а к factor - по значению
[factor, &total]

[&, factor]                             - к всем по ссылке, а к factor - по значению
[factor, &]

[&total, =]                             - к total по ссылке, а ко всем - по значению
[=, &total]

Если в предложении capture стоит знак захвата ВСЕХ переменных по ссылкам (по значениям), 
то не допускается одновременная запись отдельнх переменных,
также как захватываемых по ссылке (по значению)
[&, &i]{};                              // Ошибка - код не компилируется
[=, =i]{};                              // Ошибка - код не компилируется


При этом, компилятор следит за тем, чтобы захватываемые по значению переменные
не были модифицированы ошибочно в теле лямбда-выражения - ошибочная модификация не компилируется

[args...]                               Захват, за которым следует многоточие, - это расширение пакета

[this]                                      Захват указателя на объект класса используется лямбда-выражениями
                                                в теле метода класса, чтобы предоставить доступ к методам и членам данных 
                                                this указатель также может быть захвачен с помощью [=] или [&], 
                                                В любом из этих случаев члены данных класса (включая private) будут доступны,
                                                как и в обычном методе.

[=, this]{};                            // ERROR: код не компилируется
[=, *this]{};                          // OK: captures this by value. 

Глобальные переменные, как и статические, нет необходимости (и не разрешается) захватывать.
Их можно использовать в лямбдах без захвата.

Если очень хочется иметь в лямбде копию глобальной переменной (например если лямбда - mutable, 
и эту копию хочется изменять), то можно использовать захват с инициализацией:
[offset_copy = offset, scale_copy = scale](int b) {}
Инициализировать можно и функцией
[ptr = move(pNums)]() {}

*/
