#include "my_std_library.h"
using namespace std;
/*
        Тип лямбда-выражения

        nesting lambda expresion - вложенные лямбда-выражения 

        Можно вложить одно лямбда-выражение в другое. 
        Внутреннее (вложенное) лямбда-выражение обрабатывает свои параметры, 
        как аргументы внешнего лямбда и возвращает результат. 
        Кроме того, вложенное лямбда-выражение может захватить параметры внешнего лямбда.
        Внешнее лямбда-выражение вызывает внутреннее лямбда-выражение 
        с использованием своих параметров.

        При использовании вложеннных лямбда-выражений имеет место два этапа:
        - построение функтора, и тогда параметры передаются внешнему лямбда выражению;
        - инициация (вызов) построенного функтора, и тогда параметры передаются
                                                                                                                внутреннему (вложенному) лямбда выражению;

*/

/*
  *     ********************************************************************
  *     Основная функция
  *     ********************************************************************
  */
void nesting_lambda()
{
        cout << '\n' << "Работает <nesting_lambda()>  " << '\n' << endl;

        /*
          *     Можно вложить одно лямбда-выражение в другое, как показано в следующем примере. 
          *     Внутреннее лямбда-выражение умножает своего аргумент на 2 и возвращает результат. 
          *     Внешнее лямбда-выражение вызывает внутреннее лямбда-выражение 
          *     с использованием своего параметра уже как аргумента и добавляет к результату 3.
          */
        // The following lambda expression contains a nested lambda  expression.
        int timestwoplusthree = [](int x) 
                                                                { 
                                                                        return [](int y) 
                                                                                        { 
                                                                                                return y * 2; 
                                                                                        } (x)   // Аргумент вложенной лямбда - параметр внешней
                                                                                     + 3; 
                                                                 } (5);                         // Передача аргумента из вызывающего объекта

        // Print the result.
        cout << timestwoplusthree << endl;

        // Здесь параметр внешней лямбда захватывается по значению вложенной лямбдой
        const auto less_than = [](auto x) 
                                                        {
                                                                cout << "Параметр внешней лямбда " << x << endl;
                                                                return [x](auto y) 
                                                                                {
                                                                                        cout << "Параметр вложенной лямбда " << y << endl;
                                                                                        return y < x;
                                                                                };
                                                        };
        cout << "При построении функтора аргумент передается внешней лямбда" << endl;
        auto less_than_five = less_than(5);
        cout << "При вызове функтора аргумент передается уже вложенной лямбда" << endl;
        cout << boolalpha << less_than_five(3)        << endl;
        cout << boolalpha << less_than_five(10)      << endl;

}
