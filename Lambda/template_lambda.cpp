	auto iter_of_neg = findNegative(any_int_vect.begin(), any_int_vect.end());
	cout << "The first negativ number is: " << *iter_of_neg << endl;

	vector<double> any_int_vect2{ 11.45, 45.14, -21.21, 23.44, -41.76, 77.22 };
	auto iter_of_neg2 = findNegative(any_int_vect2.begin(), any_int_vect2.end());
	cout << "The first negativ number is: " << *iter_of_neg2 << endl;

	auto iter_of_neg3 = findPositive(any_int_vect2.begin(), any_int_vect2.end());
	cout << "The first negativ number is: " << *iter_of_neg3 << endl;

