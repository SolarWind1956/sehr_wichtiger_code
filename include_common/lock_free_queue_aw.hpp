	/*
	*************************************************************************************************
	Глава 7. Проектирование параллельных структур данных без блокировок
	Chapter 7. Designing lock-free concurrent data structures
	*************************************************************************************************
	Cтруктуры данных, с которыми можно было бы безопасно работать, не прибегая к блокировкам,
называются 'структурами данных без блокировок', или 'свободными от блокировок'.
	*************************************************************************************************
	Раздел 7.1. Определения и следствия из них
	*************************************************************************************************
	Алгоритмы и структуры данных, в которых для синхронизации доступа
используются 'мьютексы', 'условные переменные' и 'будущие результаты', называются 'блокирующими'.
	Библиотечные функции, которые приостанавливают выполнение потока до тех пор,
пока другой поток не завершит некоторое действие, называются также 'блокирующими',
потому что поток не может продвинуться дальше некоторой точки, пока не будет 'снята блокировка'.
	Структуры данных и алгоритмы, в которые 'блокирующие библиотечные функции' не используются,
называются 'неблокирующими'.
	Но не все такие структуры данных 'свободны от блокировок'; рассмотрим различные типы 'неблокирующих структур'.

	*************************************************************************************************
	Параграф 7.1.1. Типы неблокирующих структур данных
	*************************************************************************************************

/*
	************************************************************************************************************
	Листинг 7.16. Реализация push() для очереди без блокировок с подсчетом ссылок на tail
*/
	template<typename T>
	class lock_free_queue_aw
	{
	private:
		// На 21.12.20 в Visual Studio 2019 функция std::atomic_is_lock_free(&some_shared_ptr) возвращает false, 
		// поэтому управлять подсчетом ссылок придется самостоятельно.
		// Объявление структуры узла, чтобы можно было сослаться, определение будет ниже
		struct node;
		// Указатель на узлы очереди с 'внешним' счетчиком - счетчик увеличивается при каждом чтении этого указателя
		struct counted_node_ptr
		{
			int								external_count;		// 'Внешний' счетчик
			node*							ptr;
		};
		// Поскольку counted_node_ptr определена как struct, 
		// то ее можно использовать в шаблоне std::atomic<> для представления головы и хвоста списка head и tail
		std::atomic<counted_node_ptr>		head_a_cn_ptr;
		std::atomic<counted_node_ptr>		tail_a_cn_ptr;

		// Используем два счетчика ссылок – 'внутренний' (internal_count) и 'внешний' (external_count).
		// Их сумма равна общему количеству ссылок на узел.
		// 'Внешний' счетчик хранится вместе с указателем на узел и увеличивается при каждом чтении этого указателя.

		// Для обновления разделяемых данных по-прежнему необходимо применять 'атомарные операции'.

		struct node_counter
		{
			unsigned internal_count		: 30;		// Внутренний счетчик
			unsigned external_counters	: 2;		// Количество внешних счетчиков в структуре node
		};
		// Под поле external_counters отведено только 2 бита, потому что 'внешних' счетчиков может быть не более двух.
		// Воспользовавшись битовыми полями и отведя под internal_count - 30 бит, 
		// мы ограничили длину поля счетчика 32 битами.
		// В результате мы убиваем сразу двух зайцев : и значение 'внутреннего' счетчика может быть достаточно велико, 
		// и вся структура помещается в машинное слово на 32 - и 64 - разрядных машинах.
		// Очень важно изменять счетчики как единое целое, чтобы избежать гонки.

		// Узел очереди
		struct node
		{
			std::atomic<T*>					data_a_ptr;		// Атомарный указатель на элемент данных
			std::atomic<node_counter>		count_a;			// Атомарный Cчетчик 'внутренний' + счетчик 'внешних' счетчиков
			counted_node_ptr				next_cn_ptr;		// Указатель с 'внешним' счетчиком
			// Конструктор узла очереди по умолчанию
			node()
			{
				node_counter				new_count;		// HE Атомарный Cчетчик 'внутренний' + счетчик 'внешних' счетчиков
				// При инициализации структуры node в поле internal_count записывается 0, 
				// а в поле external_counters – 2, потому что сразу после добавления нового узла в конец очереди 
				// на него есть две ссылки : из tail и из указателя next в предыдущем узле (два 'внешних' счетчика).
				new_count.internal_count = 0;
				new_count.external_counters = 2;	// 'внешний' счетчик ссылок из tail и 'внешний' счетчик из next 

				count_a.store(new_count);				// Сохраним его в Атомарный Cчетчик 'внутренний' + счетчик 'внешних' счетчиков
				next_cn_ptr.ptr = nullptr;
				next_cn_ptr.external_count = 0;
			}
			//	Листинг 7.18. Освобождение ссылки на узел в очереди без блокировок
			void release_ref()
			{
				// Загрузим Атомарный Cчетчик 'внутренний' + счетчик 'внешних' счетчиков
				node_counter	old_counter = count_a.load(std::memory_order_relaxed);
				// Создадим такой же но HE Атомарный Cчетчик 'внутренний' + счетчик 'внешних' счетчиков
				node_counter	new_counter;

				do
				{
					new_counter = old_counter;		// 'желаемое значение' == 'ожидаемое значение' ==  count_a ?????????
					--new_counter.internal_count;		// Уменьшим на единичку 'внутренний' счетчик
					// Хорошо бы другие потоки не исказили картину - тогда и цикла не будет
				} while (!count_a.compare_exchange_strong(old_counter, new_counter,
					std::memory_order_acquire, std::memory_order_relaxed));

				// Если внутренний счетчик равен нулю и количество внешних счетчиков также нулевое
				if (!new_counter.internal_count && !new_counter.external_counters)
				{
					// Уничтожаем узел, вытолкнутый из очереди
					delete this;
				}
			}
		};
		// 	Листинг 7.19. Получение новой ссылки на узел в очереди без блокировок
		// Функция принимает подлежащий обновлению внешний счетчик извне
		static
			void increase_external_count(std::atomic<counted_node_ptr>& counter_a_cn_ptr,
				counted_node_ptr& old_counter_cn_ptr)
		{
			counted_node_ptr	new_counter_cn_ptr;		// Создадим новый указатель с 'внешним' счетчиком external_count

			do
			{
				new_counter_cn_ptr = old_counter_cn_ptr;	// 'желаемое значение' == 'ожидаемое значение' 
				++new_counter_cn_ptr.external_count;		// increase_external_count - Увеличим 'внешний' счетчик на единичку

			} while (!counter_a_cn_ptr.compare_exchange_strong(old_counter_cn_ptr, new_counter_cn_ptr,
				std::memory_order_acquire, std::memory_order_relaxed));

			old_counter_cn_ptr.external_count = new_counter_cn_ptr.external_count;
		}
		// Листинг 7.20. Освобождение счетчика внешних ссылок на узел в очереди без блокировок
		static
		void free_external_counter(counted_node_ptr& old_node_cn_ptr)
		{
			// Создаем указатель на узел, и запоминаем, на какой указывал указатель из параметра
			node* const		ptr = old_node_cn_ptr.ptr;
			// Запомним также значение 'внешнего' счетчика, уменьшенного на 2
			int const			count_increase = old_node_cn_ptr.external_count - 2;

			node_counter	old_counter = ptr->count_a.load(std::memory_order_relaxed);

			node_counter	new_counter;

			do
			{
				new_counter = old_counter;	// 'желаемое значение' == 'ожидаемое значение'
				--new_counter.external_counters;			// Уменьшаем на единичку счетчик  'внешних' счетчиков 
				// К 'внутреннему' счетчику прибавляем 'внешний' счетчик -2
				new_counter.internal_count += count_increase;

			} while (!ptr->count_a.compare_exchange_strong(
				old_counter, new_counter,
				std::memory_order_acquire, std::memory_order_relaxed));
			// Если 'внутренний' счетчик равен нулю и количество 'внешних' счетчиков также нулевое
			if (!new_counter.internal_count && !new_counter.external_counters)
			{
				// Уничтожаем узел, вытолкнутый из очереди
				delete ptr;
			}
		}
	public:
		// *************** Конструкторы и операторы присваивания или перемещения ******************

		// Kонструктор по умолчанию сразу создает фиктивный узел, и инициализирует
		// уникальный указатель на голову			head_u_ptr
		// и простой указатель на хвост очереди		tail_ptr
		lock_free_queue_aw()
		{
			// Создаем указатель с 'внешним' счетчиком также для нового узла
			counted_node_ptr	new_cn_ptr;
			// Создадим в куче новый узел для вставки в очередь
			new_cn_ptr.ptr	= new node;

			head_a_cn_ptr	= new_cn_ptr;
			tail_a_cn_ptr		= head_a_cn_ptr.load();
		}
		// Деструктор проходит с головы очереди до хвоста и удаляет все элементы
		~lock_free_queue_aw()
		{
			std::cout << "~lock_free_queue_aw()" << std::endl;
			counted_node_ptr head_cn_ptr = head_a_cn_ptr.load();

			while (node* const ptr  = head_cn_ptr.ptr)
			{
				head_cn_ptr.ptr = ptr->next_cn_ptr.ptr;
				delete	ptr;
			}
		}
		
		// Конструктор копирования и оператор копирующего присваивания запрещаем, так как имеются 
		// уникальные указатели
		lock_free_queue_aw(const lock_free_queue_aw& other)				= delete;
		lock_free_queue_aw& operator=(const lock_free_queue_aw& other)	= delete;


		void push(T new_value)
		{
			// Создаем разделяемый указатель на переданные данные для вставки в очередь нового узла
			std::unique_ptr<T>	new_data_u_ptr( new T( std::move(new_value) ) );
			// Создаем указатель с 'внешним' счетчиком также для нового узла
			counted_node_ptr	new_next_cn_ptr;
			// Создадим в куче новый узел для вставки в очередь
			new_next_cn_ptr.ptr = new node;
			// При этом в струтуре node_count cозданного узла конструктором инициализируются два счетчика:
			//		new_count.internal_count			= 0;		// 'Внутренний' счетчик
			//		new_count.external_counters		= 2;		// Счетчик счетчиков 'внешних' ccылок
			// Одна ссылка на этот узел уже как бы есть - наращиваем счетчик 'внешних' ссылок
			new_next_cn_ptr.external_count = 1;
			// Запомним указатель на хвост очереди
			counted_node_ptr	old_tail_cn_ptr = tail_a_cn_ptr.load();										// (1)
			for (;;)
			{
				// Запустим функцию инкремента 'внешнего' счетчика для хвоста
				increase_external_count(tail_a_cn_ptr, old_tail_cn_ptr);

				T* old_data_ptr = nullptr;
				// Если указатель на данные равен nullptr, значит мы работаем с фиктивным узлом
				if (old_tail_cn_ptr.ptr->data_a_ptr.compare_exchange_strong(old_data_ptr, new_data_u_ptr.get()))	// (2)
				// и мы одновременно присваиваем пустому указателю указатель на добавляемые данные,
				// делая фиктивный узел не фиктивными
				{
					// Указатель next теперь уже не фиктивного узла будет указывать на новый созданный узел,
					// который станет тепрь фиктивным
					old_tail_cn_ptr.ptr->next_cn_ptr = new_next_cn_ptr;
					// Хвост очереди tail теперь будет указывать на новый фиктивный узел
					// у старое значение указателя хвоста очереди мы запомним
					old_tail_cn_ptr = tail_a_cn_ptr.exchange(new_next_cn_ptr);
					// Освободим внешние счетчики для старого хвоста
					free_external_counter(old_tail_cn_ptr);
					// Освобождает владение возвращаемым сохраненным указателем на вызывающий объект 
					// по  сути мы уничтожаем созданный уникальный указатель на данные для вставки за ненадбностью
					new_data_u_ptr.release();
					break;
				}
				// Если между (1) и (2) какой-то другой поток уже вставил свой новый узел,
				// то ???????????
				old_tail_cn_ptr.ptr->release_ref();
			}
		}
		// Листинг 7.17. Извлечение узла из очереди без блокировок с подсчетом ссылок на tail
		std::unique_ptr<T> pop()
		{
			// Загрузим указатель на голову очереди
			counted_node_ptr old_head_cn_ptr = head_a_cn_ptr.load(std::memory_order_relaxed);
			for (;;)
			{
				// Запустим функцию инкремента 'внешнего' счетчика для головы очереди
				increase_external_count(head_a_cn_ptr, old_head_cn_ptr);
				// Запомним указатель на элемент, следующий за выталкиваемым
				node* const		ptr = old_head_cn_ptr.ptr;

				// Если узел head совпадает с tail, то можно освободить ссылку и вернуть нулевой указатель, 
				// потому что очередь пуста.)
				if (ptr == tail_a_cn_ptr.load().ptr) // Если он указывает на фиктивный узел, очерeдь нефиктивных узлов пуста
				{
					// Сбрасываем счетчик ссылок
					ptr->release_ref();
					// Возвращаем нулевой указатель - очередь пуста
					return std::unique_ptr<T>();
				}
				// Если же в очереди есть данные, то мы пытаемся заявить на них свои права 
				// с помощью compare_exchange_strong()
				// Mы при этом сравниваем 'внешний' счетчик и указатель как единое целое; 
				// если хотя бы один из них изменился, то мы должны вернуться в начало цикла, 
				// освободив предварительно ссылку (6). 
				// Если обмен завершился удачно, то мы получили в свое распоряжение данные в узле, 
				// поэтому можем вернуть их вызывающей программе, 
				// освободив предварительно 'внешний' счетчик ссылок на извлеченный узел - функция free_external_counter
				// B этой функции после того как оба 'внешних' счетчика освобождены, 
				// а 'внутренний'	счетчик обратился в нуль, сам узел можно удалять .
				if (head_a_cn_ptr.compare_exchange_strong(old_head_cn_ptr, ptr->next_cn_ptr))
				// B указатель на голову очереди запишется указатель на узел, следующий за вытолкнутым
				{
					// Сохраним указатель на данные вытолкнутого узла
					T* const		result_ptr = ptr->data_a_ptr.exchange(nullptr);
					// Освободим 'внешние' счетчики вытолкнутого элемента
					free_external_counter(old_head_cn_ptr);
					// Возвратим читателю указатель на данные вытолкнутого узла
					return std::unique_ptr<T>(result_ptr);
				}
				// (6) - oсвобождаем ссылку
				ptr->release_ref();
			}
		}
		bool empty()
		{
			return (head_a_cn_ptr.load().ptr == tail_a_cn_ptr.load().ptr);
		}
	};
