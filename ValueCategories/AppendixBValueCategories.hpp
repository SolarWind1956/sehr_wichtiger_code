/*
	У значений l-value имеются идентификаторы, но это верно и для значений x-value
	(только l-value не могут быть перемещены, а  x-value могут быть перемещены). 
	
	Существует категория значений gl-value, от "generalized l-value" (универсальное значение l-value) - 
значение имеют идентификаторы. 
	
	Расширенный набор значений gl-value содержит и значения l-value 
	(также известные как классические значения l-value), 
и значения x-value. 
	Поэтому, хотя утверждение, что у l-value есть идентификатор, и верно, 
полный набор значений с идентификатором — это набор значений gl-value.

		gl-value		=	l-value		U	x-value

	идентификаторы имеют оба подмножества.

	R-значения являются чисто математическими значениями (например, 7 или символ 'а' ), 
которые не обязательно имеют связанное с ними постоянное место хранения;
они существуют только для вычислений, но после того, как они были использованы, на них нельзя ссылаться. 
	Это "временные значения".

	В частности, любые литеральные значения, за исключением строковых литералов (например, 7, 'а', true, nullptr), 
являются r-значениями, 
как и результаты многих встроенных арифметических вычислений (например, z + 5 для z целочисленного типа) 
и вызовов функций, возвращающих результат по значению. 
	То есть все "временные значения" являются r-значениями.

	Хотя это не относится к именованным ссылкам, которые ссылаются на них.

Значение r-value является перемещаемым, а l-value — нет

	Существуют значения, для которых невозможно получить адрес памяти (либо не гарантируется, что он будет действительным). 
	
	Мы видели несколько таких значений в приведенном выше примере кода. Это может показаться недостатком. 
	
	Но на самом деле преимущество такого значения заключается в том, что вы можете переместить данные из него 
(что, как правило, не требует больших затрат), а не копировать их (что, как правило, требует несколько больших затрат).
	Перемещение значения означает, что оно не остается там, где было до этого, в том же самом виде. 
	
	Поэтому следует избегать попыток обращения к переменным там, откуда они уже были перемещены. 
	
	Значение, которое может быть перемещено, называется r-value (или классическое значение r-value).

	Буква "r" в r-value представляет собой сокращение от "right" (справа) (то есть правая сторона присвоения). 
	
	Но значения r-value, а также ссылки на r-value, можно использовать и за пределами присвоений. 
	
	Значит, на "r" в имени r-value можно не обращать особого внимания. 
	
	Необходимо только понимать, что r-value — это значение, которое можно перемещать.

	Перемещенное значение l-value противоречило бы определению l-value, и возникла бы непредвиденная проблема для кода, 
который вполне обоснованно по-прежнему должен иметь доступ к l-value.

	Невозможно переместить значение l-value. 
	
	Но есть еще значение типа gl-value (набор значений с идентификатором), 
которое можно переместить — если, конечно, вы знаете, что делаете 
(в то числе достаточно внимательны, чтобы не обращаться к нему после перемещения) — это значение x-value. 
	Мы вернемся к этой идее позже, когда рассмотрим полную картину категорий значений.

Б.1.1. Преобразования l-значений в r-значения

	В силу своей эфемерной природы 
r-значения, как правило, ограничены присутствием только с правой стороны (“простых”) присваиваний: 
присваивание 7 = 8 не имеет смысла, потому что математическое значение 7 не может быть переопределено.
	С другой стороны, l-значения подобного ограничения не имеют: 
безусловно можно вычислить присваивание z = у, когда и 'z', и 'у' являются переменными совместимого типа, 
даже если оба выражения 'z' и 'у' являются l-значениями.
	Присваивание z = у работает благодаря тому, что выражение справа, 'у', 
подвергается 'неявному преобразованию', 
которое называется "преобразованием l-значения в r-значение" (l-value-to-r-value conversion). 
	Как предполагает название, 
это преобразование принимает l-значение и выполняет чтение из памяти или регистра, связанных с l-значением, 
r-значения того же типа. 

	Таким образом, это преобразование выполняет два действия: 
	
	-	во-первых, оно гарантирует, что l-значения могут использоваться везде, 
		где ожидается r-значение 
		(например, в правой части присваивания или в математическом выражении наподобие х + у). 
		
	-	Во-вторых, оно определяет, 
		где в программе компилятор может включать (до оптимизации) инструкцию “загрузка” для чтения значения из памяти.

Б.2. Категории значений, начиная с С++11

	Когда в C++11 для поддержки семантики перемещения были введены ссылки на r-значение, 
традиционного деления выражений на l-значения и r-значения стало недостаточно, чтобы описать все поведение C++11. 
	Поэтому комитет по стандартизации C++ изменил систему категорий значений, 
основав ее на трех основных и двух составных категориях. 

						    ВЫРАЖЕНИЯ

				gl-значения		     r-значения

			l-значения	   x-значения	  pr-значения


	Основными категориями являются: 
	
	-	l-значение, 
	
	-	pr-значение (pure r-value — чистое r-значение) и 
	
	-	х-значение.

	Составными категориями являются:

	-	gl-значение (generalized l-value — обобщенное l-значение, 
						которое является объединением l-значения и х-значения) и 
	
	-	r-значение (объединение х-значения и рr-значения).

gl-value
	У gl-value (универсальное значение l-value) имеется идентификатор.

r-value
	Значение r-value допускает перемещение.

l-value
	У l-value (относится к типу gl-value) имеется идентификатор, но его невозможно перемещать.

pr-value
	Значение pr-value ("чистое значение rv-alue", относится к типу r-value) не имеет идентификатора, но может быть перемещено.

x-value
	Значение x-value (относящееся к типу gl-value потому, что имеет идентификатор, 
	но также являющееся разновидностью r-value потому, что может быть перемещено)
	имеет идентификатор и может быть перемещено.

	Эта категоризация С++11 остается в силе, 
но в С++17 характеристики категорий были пересмотрены следующим образом.

	•	gl-значение представляет собой выражение,	вычисление которого определяет идентичность объекта, 
													битового поля или функции, передающей результат по ссылке, 
													(сущности, имеющей место хранения и имеющей идентификатор).

	•	pr-значение представляет собой выражение,	вычисление которого инициализирует объект или битовое поле, 
													или вычисляет значение операнда оператора, или функции, 
													возвращающей результат по значению (не по ссылке),
													но не имеет идентификатора.

	•	х-значение представляет собой gl-значение,	обозначающее объект или битовое поле, 
													ресурсы которого не могут быть повторно использованы 
													(обычно из-за того, что вскоре истечет его время жизни — 
													так что “x” в x-value означает “eXpiring value” — 
													завершающееся значение);
													x-value имеет идентификатор.
	
	•	l-значение представляет собой gl-значение,	не являющееся х-значением; 
													оно имеет идентификатор, и не может быть перемещено.

	•	r-значение представляетсобой выражение,		являющееся либо рr-значением, либо х-значением;
													оно может быть перемещено, а идентификатор может иметь или не иметь.

	B С++17 (и в некоторой степени в С++11 и С++14) разделение gl-значений и pr-значений, 
возможно, более фундаментальное, чем традиционное отличие l-значений от r-значений.
	Хотя это описание характеристик введено в C++17, оно применимо и в C++11 и C++14 
(более ранние описания эквивалентны по смыслу, но с ними трудно работать).

	За исключением битовых полей, gl-значения производят сущности с адресами. 
	
	Этот адрес может быть адресом подобъектов большего охватывающего объекта. 
	
	В случае подобъекта базового класса тип gl-значения (выражения) называется "статическим типом", 
а тип наиболее производного объекта, частью которого является базовый класс, 
называется "динамическим типом" gl-значения. 
	Если gl-значение не производит подобъект базового класса, 
статические и динамические типы являются идентичными (типами выражения).

	Примеры l-значений таковы (имеют идентификатор и не могут быть перемещены).

	•	Выражения, обозначающие переменные или функции.

	•	Применения встроенного унарного оператора * (разыменование указателя).
	
	•	Выражение, являющееся простым строковым литералом.

	•	Вызов функции с возвращаемым типом, являющимся "ссылкой" на l-значение.

	Примеры pr-значений таковы (могут быть перемещены, но не имеют идентификатора).

	•	Выражения, которые состоят из литерала, 
		не являющегося строковым литералом или литералом, определяемым пользователем.
		
		Пользовательские литералы могут давать l-значения или r-значения, 
		в зависимости от возвращаемого типа соответствующего литерального оператора. 
		К сожалению, это означает, что используемые термины являются неподходящими.

	•	Применения встроенного унарного оператора & (взятие адреса выражения).

	•	Применение встроенных арифметических операторов.

	•	Вызов функции с возвращаемым типом, который не является ссылочным типом.

	•	Лямбда-выражения.

	Примеры х-значений таковы (имеют идентификаторы и могут быть перемещены):

	•	Вызов функции с возвращаемым типом, 
		который представляет собой ссылку на r-значение на тип объекта (например, std::move()).

	•	Приведение к r-значению ссылки на тип объекта (static_cast<A&&>(a);).

	Ссылки r-value на типы функций производят l-значения, а не х-значения.

	Note that r-value references to function types produce l-values, not x-values.

	gl-значения, pr-значения, х-значения и так далее являются "категориями выражений", а не значениями или сущностями. 
	
	(К сожалению, это означает, что используемые термины являются неподходящими.)
	
	Например, переменная не является l-значением, несмотря на то, что выражение, описывающее переменную, является таковым:

	int z = 3;		// Здесь z — переменная - сущность, но не l-значение как "категория значения". 
					// 3 является pr-значением, инициализирующим переменную z.

	int у = z;		// Здесь z — l-значение. 
					// Вычисление этого выражения l-значения не дает значения 3, 
					// но обозначает объект, содержащий значение 3. 
					// Такое l-значение затем преобразуется в рr-значение, которое инициализирует у.

	В терминах имеет место масса нюансов, и всегда следует следить за контекстом, в которых употребляются
те или иные термины. Особенны с учетом некачественного перевода.

Б.2.1. Временная материализация

	Ранее мы упоминали, что l-значения часто проходят преобразования l-значения в r-значение, 
потому что pr-значения представляют собой разновидность выражений, 
которые инициализируют объекты (или предоставляют операнды для большинства встроенных операторов).

	В мире категорий значений C++11 более точной будет фраза "преобразование gl-значения в pr-значение", 
но традиционный термин остается более распространенным.
	В C++17 существует дуальное преобразование к данному, известное как "временная материализация"
(но его можно было бы также назвать "преобразованием pr-значения в х-значение"): 
	в любой момент, когда pr-значение корректно появляется там, 
	где ожидается gl-значение (которое включает х-значение), 
	создается временный объект, который инициализируется рr-значением 
	(pr-значения являются главным образом инициализирующими значениями),
	и pr-значение заменяется временным х-значением. 
	
	Например:

	int f(int const&);
	
	int r = f(3);

	Поскольку f() в этом примере имеет ссылочный параметр, 
ожидается аргумент, являющийся gl-значением. 
	Однако выражение <3> является рr-значением.

	Поэтому вступает в дело правило временной материализации, 
и выражение <3> “преобразуется” в х-значение, 
обозначающее временный объект, инициализированный значением <3>.
	В целом, временное значение материализуется с инициализацией рr-значением в следующих ситуациях.

	•	pr-значение связано со ссылкой (например, как в вызове f(3) выше).

	•	Доступ к члену pr-значения классового типа.
	
	•	Индексация массива рr-значений.

	•	Массив рr-значений преобразуется в указатель на его первый элемент (низведение массива).

	•	pr-значение находится в списке инициализации в фигурных скобках, 
		который для некоторого типа X инициализирует объект типа std::initializer_list<X>.

	•	Применение операторов sizeof или typeid к рr-значению.

	•	pr-значение представляет собой выражение верхнего уровня в инструкции вида “ехрr; ” 
		или выражение, приводимое к void.

	Таким образом, в C++17 объект, инициализированный рr-значением, всегда определяется контекстом, 
и в результате временные значения создаются только тогда, когда они действительно необходимы. 

	До С++17 pr-значения (в частности, классового типа) всегда подразумевали временные объекты. 
	
	Копии этих временных объектов позже могли (необязательно) быть устранены, 
но компилятор попрежнему должен был обеспечивать большинство семантических ограничений операции копирования 
(например, мог требоваться вызываемый копирующий конструктор). 

В следующем примере показано следствие пересмотра правил в С++17:
*/
