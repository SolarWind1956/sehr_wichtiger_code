/*
Appendix B		Value Categories
Приложение Б	“Категории значений”

	Выражения являются краеугольным камнем языка C++, предоставляя основной механизм, 
позволяющий выразить необходимые вычисления. 
	Каждое выражение имеет тип, который описывает статический тип значения - результата, 
производимого при вычислении.
	Таким образом, любое выражение имеет определенный тип и после вычисления возвращает некоторое значение. 

	Простейшими выражениями являются переменные и константы.
	
	Это объекты, куда помещаются значения, вычисленные выражениями.

	Каждое выражение имеет также "категорию значения" (value category), 
которая описывает то, как было сформировано значение, и влияет на поведение выражения.

Б.1. Традиционные l- и r-значения

	Исторически изначально имелись только две категории значений: l-значения и r-значения. 
	
	L-значениями являются выражения, ссылающиеся на фактические значения, 
хранящиеся в памяти или в регистре компьютера, такие как выражение z, где z — имя переменной (идентификатор!!!). 
	Эти выражения могут быть изменяемыми, позволяя обновлять сохраненное значение,
или не изменяемыми, не позволяюзщими изменять значения (константами). 
	
	Например, если z является переменной типа int, то следующее присваивание заменит значение z на 7:

	z = 7;

	Термин l-значение (l-value) является производным от роли, которую это выражение могло бы играть в рамках присваивания: 
	буква l означала left - “левый” 
потому что (исторически в языке программирования С) слева от знака присваивания могли находиться только l-значения. 
	И наоборот, r-значения (r-values, где r означает right - “правый”) 
могло находиться только в правой части выражения присваивания.
	
	После стандартизации языка С в 1989 году все изменилось: 
хотя попрежнему значение int const хранится в памяти, оно не может находиться в левой части присваивания:
	
	int const z;					// z - неизменяемое значение
	z = 7;							// Ошибка: слева должно быть изменяемое значение

	Изменения в C++ пошли еще дальше: класс r-значений может находиться слева в присваиваниях. 
	
	Такие присваивания на самом деле являются вызовами функций операторов присваивания соответствующих классов, 
а не “простыми” присваиваниями скалярных типов, так что они управляются (отдельными) правилами вызовов функций-членов.
	Учитывая все эти изменения, термин "l-значение" теперь иногда трактуется как "локализуемое значение". 
	
	Выражения, которые ссылаются на переменную, являются не единственными выражениями l-значений. 
	
	Еще один класс выражений, которые являются l-значениями, 
включает операцию разыменования указателя (например, *рtr), 
и ссылается на значения, хранящиеся по адресу, на который указывает указатель, 
а также выражения, которые ссылаются на члены объектов классов (например, ptr->data). 
	Даже вызовы функций, возвращающих значения “традиционных” ссылочных на l-значения типов, 
объявленных с использованием &, являются l-значениями. 

	Например:

	int		int_var;					// l-значение, так как имеет идентификатор
	int*	int_var_ptr	=	&int_var;	// l-значение, так как возвращаемый тип является указателем на l-значение

	std::vector<int> v;
	v.front()							// l-значение, так как возвращаемый тип является ссылкой на l-значение
	// Вот так объявлены эти методы 
	reference		std::vector::front();
	const_reference std::vector::front() const;

	Возможно, это покажется удивительным, но строковые литералы также являются (неизменяемыми) l-значениями.
	Правда, строковые литералы не имеют идентификаторов - исключение, подтверждающее правило.

	Итак, l-значения указывают на объекты, занимающие место в памяти, и имеющие идентификаторы,
но не все l-значения могут находиться в левой части выражений. 
	В то же время, l-значения могут находиться в правой части выражений.

У l-value есть идентификатор

	Что означает, что у значения есть идентификатор? 
	
	Если у вас есть (или его можно выделить) адрес памяти значения и вы можете его безопасно использовать, 
то у значения есть идентификатор. 

	Таким образом вы не просто сравниваете содержимое значений: 
вы можете сравнивать или различать их по идентификатору.

	У l-value есть идентификатор. 
	
	Сейчас этот вопрос представляет лишь исторический интерес, 
но "l" в имени l-value представляет собой сокращение от "left" (слева) (то есть левая сторона присваивания). 
	
	В C++ в настоящее время l-value может отображаться как в левой, так и в правой части присваивания. 
	
	То есть "l" в имени l-value уже не помогает понять, что это за значения. 

	Необходимо только понимать, что l-value — это значение, которое имеет идентификатор.

	Примеры выражений с l-value: 
	
	-	именованная переменная или константа; 
	
	-	результат применения оператора разыменования (*);
	
	-	результат применения к именованным переменным операторов доступа к членам (., ->) и индексатора;
	
	-	строковый литерал; 
	
	-	функция, возвращающая "ссылку", именно ссылку, а не значение. 
	
	Примеры выражений, которые не содержат l-value: 
	
	-	Результат применения оператора получение адреса (&);
	
	-	Результат применения других операторов (за исключением l-value операторов (*) и (., ->));
	
	-	Простой литерал (42, ’X’, etc.);
	
	-	Член перечисления;
	
	-	Вызов функции, которая возвращает не-ссылку;
	
	-	Вызов функции, которая возвращает r-value-ссылку.
	
	-	Вызов функции, возвращающей результат по значению;
	
	-	Временное значение.
*/
// Возврат по ссылке обычно используется для возврата аргументов, переданных в функцию также по ссылке.
