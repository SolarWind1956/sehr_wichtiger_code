/*
	****************************************************************************************************
	CRTP (Curiously Recurring Template Pattern) 	- 	это идиома проектирования на C++, 
												где класс наследуется от `шаблонного класса`, 
												используя при этом `себя` 
												в качестве `параметра шаблона`. 
												
	Этот паттерн позволяет `базовому` классу "знать" о `производном` классе, 
	что дает возможность реализовать `статический полиморфизм`, 
	избавляясь от накладных расходов `виртуальных функций`, 
	а также добавлять `общую функциональность` в `производные` классы. 
	
	----------------------------------------------------------------------------------------------------
	https://en.wikipedia.org/wiki/Curiously_recurring_template_pattern
	https://en.cppreference.com/w/cpp/language/crtp.html
	
	Преимущества
	
	Статический полиморфизм: 	Позволяет достичь полиморфизма во время компиляции, 
								что устраняет затраты на производительность, 
								связанные с виртуальными функциями 
								и динамическим полиморфизмом. 
								
	Общая функциональность: 	Позволяет создавать общую функциональность в базовом классе, 
								которая работает с методами производного класса. 
								
								Это полезно для реализации паттернов, 
								таких как «Шаблонный метод». 
								
	Переиспользование кода: 		Снижает дублирование кода между производными классами, 
								помещая общую логику в базовый класс. 

	Применение
	-	Реализация `статического полиморфизма` и устранение накладных расходов. 
	-	Создание интерфейсов, где базовый класс может вызывать методы реализаций, 
		переданных как шаблонный аргумент. 
	-	Добавление общей функциональности к классу, 
		например, поддержка подсчета объектов или сравнения. 

*/
