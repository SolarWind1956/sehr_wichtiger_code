/*
	Пробелы вставляются для лучшей читаемости кода, 
	правила их расстановки определяются сложившимися традициями, 
	правилами кодирования или просто личным вкусом программиста.

	1.4. Имя переменной

	Имя переменной (идентификатор) должен отвечать правилам, предусмотренным для идентификаторов.

	1.5. Fa-спецификаторы

	Fa-спецификаторы (function-array) подразделяются на две группы: 
	
	-	спецификаторы функций 
	и 
	-	спецификаторы массивов.

	1.5.1. Спецификаторы функций

	Спецификатор функции имеет вид:

	(params)

	В этом описании params — список параметров (параметры функции подробнее рассмотрены в разделе 3.1). 
	
	Список параметров может быть пустым. 
	
	Остальная часть объявления описывает тип возвращаемого значения функции. 
	
	Возвращаемое значение может иметь тип void, это означает, что функция ничего не возвращает.

	Спецификатор функции может быть только один, 
	и он не может комбинироваться со спецификатором массива, 
	так как в этом случае формально мы получим функцию, 
	возвращающую либо функцию, либо массив, 
	а такой тип является в C++ неразрешенным 
	(см. алгоритм разбора объявлений с несколькими fa-спецификаторами в разделе 2.3).
*/
int 	Foo1	(int x); 				// функция, принимающая int и возвращающая int
void 	Foo2	(double y, int x); 		// функция, принимающая double и int
										// и ничего не возвращающая
int *	Foo3	(); 					// функция, ничего не принимающая и возвращающая
										// указатель на int
//int 	Foo4	(int x)(char y); 		// ошибка, функция, принимающая int
										// и возвращающая функцию, принимающую char и возвращающую int
/*
	1.5.2. Спецификаторы массивов

	Спецификатор массива может иметь две формы:
[N];
[].

	В первом случае N 	— 	это целочисленное выражение, вычисляемое при компиляции, 
							его значение называется 'размером массива', 
							размер должен быть больше нуля. 
	
	Во втором случае компилятор определяет размер массива на основе списка инициализации, 
	но и в этом случае он должен быть больше нуля. 
	
	Остальная часть объявления описывает тип элементов массива. 
	
	Типом элементов массива не может быть void или ссылочный тип. 
	
	Размер массива является составной частью типа массива, 
	два массива с элементами одного и того же типа, 
	но с разными размерами являются разными типами.

	Спецификатор массива не может комбинироваться со спецификатором функции, 
	так как в этом случае мы формально получим массив функций, 
	а такой тип является в C++ неразрешенным 
	(см. алгоритм разбора объявлений с несколькими fa-спецификаторами в разделе 2.3).
*/
void 	test_5()
{
	cout << "-------------- I'm void " <<  __func__  << "()" << endl;

	int 	x1	[4];  					// массив размера 4 с элементами типа int
	int 	x2	[] = {1, 2, 3, 4}; 		// массив размера 4 с элементами типа int
	int *	x3	[4]; 					// массив размера 4 с элементами типа указатель на int
	//int &	x	[4]; 					// ошибка, массив ссылок
	//void 	x	[4]; 					// ошибка, массив void
	//int 	x	[4]	(int); 				// ошибка, массив функций, принимающих int и возвращающих int
}
