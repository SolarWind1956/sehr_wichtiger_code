/*
	*****************************************************************************************************
	*
	*	std::invoke and std::apply
	*
	*****************************************************************************************************
	
	std::invoke - 	это функция стандартной библиотеки C++, 
				добавленная в C++17, 
				которая предоставляет универсальный синтаксис 
				для вызова `любого вызываемого (Callable) объекта` 
				с `произвольным набором аргументов`. 
				
				Она определена в заголовочном файле <functional>.
	
	
	Зачем нужен std::invoke?

	В C++ существует множество сущностей, 
	которые можно «вызвать», 
	но синтаксис их вызова существенно отличается. 
	
	Например:
	
	• 	Обычная функция или лямбда: f(args...).
	
	• 	Указатель на метод класса: (obj.*method)(args...) или (ptr->*method)(args...).
	
	• 	Указатель на член-данное класса (для чтения/записи): obj.*member.
	
	Если вы пишете обобщенный (шаблонный) код, 
	который принимает `стороннюю функцию` или `объект`, 
	вам пришлось бы писать несколько перегрузок 
	под каждый из этих синтаксисов. 
	
	std::invoke решает эту проблему, 
	сводя все вызовы к единой форме.	
	
	Основные возможности

	• 	`Обычные функции` и `лямбды`: 
	
		вызываются напрямую, как если бы вы написали f(args...).
	
	• 	`Функциональные объекты` (`функторы`): 
		
		экземпляры классов с перегруженным оператором operator().
		
	• 	`Указатели на `методы классов`: 
		
		автоматически разыменовывает указатель на объект или ссылку на объект и вызывает метод.
		
	• 	`Указатели на `члены-данные классов`: 
	
		позволяет получить доступ к переменной члена класса по указателю на неё.
		
	Как это выглядит на практике	
*/	
struct Foo 
{
    int 	num;
	
    void print_add(int i_param) const { 
		cout << num + i_param << '\n'; 
	}
};
void print_num(int i_param) { 
	cout << i_param << '\n'; 
}
void first_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';

	Foo 		foo{10};

    // 	1. 	Вызов обычной функции
    std::invoke(print_num, -9); 						// 	Выведет: -9

    // 	2. 	Вызов лямбда-выражения
    std::invoke	(	[](int x_param) -> auto { cout << x_param * 2 << '\n'; }
				, 	21	//	Параметр для `лямбды`
				); 									// 	Выведет: 42

    // 	3. 	Вызов метода класса (первым аргументом передается объект или указатель)
    std::invoke(&Foo::print_add, foo, 5); 		// 	Выведет: 15
    std::invoke(&Foo::print_add, &foo, 5); 	// 	Тоже работает через указатель

    // 	4. 	Доступ к члену-данному класса
    cout << std::invoke(&Foo::num, foo) << '\n'; // Выведет: 10		
}
/*
	Развитие в более новых стандартах

	• 	C++20 (constexpr): 
		
		std::invoke получила спецификатор `constexpr`, 
		что позволяет использовать её для вычислений на этапе компиляции.
		
	• 	C++23 (std::invoke_r): 
		
		Добавлена версия std::invoke_r<R>, 
		которая не просто вызывает объект, 
		но и явно приводит возвращаемое значение к типу `R` (или к `void`).

	Связанные инструменты (<type_traits>)

	Для метапрограммирования вместе с std::invoke 
	часто используют специальные типажные трейты из <type_traits>, 
	позволяющие проверять возможность вызова на этапе компиляции:
	
	• 	std::is_invocable_v<F, Args...> - `проверяет`, можно ли вызвать `F` с аргументами Args....
	
	• 	std::invoke_result_t<F, Args...> - `определяет тип`, который `вернет` такой `вызов`.
*/
/*
	Главное отличие между std::invoke() и std::apply() 
	заключается в `форме передачи аргументов` вызываемому объекту. 
	
	Обе функции появились в C++17, 
	чтобы упростить написание обобщенного (шаблонного) кода, 
	но они решают разные задачи.
	
	Суть разницы одной фразой: 
	
	std::invoke() `принимает `аргументы `напрямую` «россыпью» 
	(как обычный вызов функции), 
	
	а 
	
	std::apply() `распаковывает` их `из` одного `контейнера-кортежа` 
	(например, std::tuple, std::pair или std::array).
	
	Сравнительная таблица
-----------------------------------------------------------------------------------------------------------------------------------------------------------------
Характеристика			std::invoke							std::apply
-----------------------------------------------------------------------------------------------------------------------------------------------------------------
Заголовочный файл		<functional>							<tuple>

Формат аргументов		Перечисляются через запятую (args...)	Передаются внутри кортежа (tuple)

Типичный сценарий		Универсальный вызов 					Передача параметров,
						(функция, метод класса, лямбда)		которые были  
						в обобщенном коде.	 				сохранены «на потом» 
															или переданы пакетом.
-----------------------------------------------------------------------------------------------------------------------------------------------------------------
	
	Подробный разбор с примерами


	1. 	std::invoke: 	Передача аргументов по отдельности

		Вы передаете саму функцию и аргументы для неё 
		прямо в параметры std::invoke. 
		
		Количество аргументов может быть любым.
*/
void print_sum(int a_param, int b_param) {
    cout << (a_param + b_param) << '\n';
}
void second_example() 
{
	// 	Аргументы передаются просто через запятую
    std::invoke(print_sum, 10, 20); 				// 	Выведет 30
	/*
	2. 	std::apply: 	Распаковка из кортежа

		Представьте, что `аргументы для функции` 
		не доступны вам прямо сейчас по отдельности, 
		а лежат внутри std::tuple 
		(например, они пришли из другой части программы или очереди задач). 
		
		Напрямую передать std::tuple в print_sum() нельзя, 
		так как `функция `ждет `два `int`, а `не один кортеж`.

		std::apply() автоматически «распаковывает» этот кортеж 
		и подставляет его элементы как отдельные аргументы.
	*/
	std::tuple<int, int> 		params{10, 20};

    // 	Напрямую вызвать print_sum(params) нельзя — будет ошибка компиляции.
    // 	std::apply распакует params и вызовет print_sum(10, 20).
    std::apply(print_sum, params); 							// 	Выведет 30
}
