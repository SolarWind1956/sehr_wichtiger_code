/*
	*****************************************************************************************************
	*
	*	std::bind
	*
	*****************************************************************************************************
	std::bind 	- 	это функция стандартной библиотеки C++ (начиная с C++11), 
				определенная в заголовочном файле <functional>, 
				которая позволяет `генерировать` 
				новые `вызываемые объекты` (функторы) 
				путем «привязывания» определенных `аргументов` 
				к `исходной функции` или `методу класса`.
				
	Оставшиеся `непривязанными` 
	`аргументы` заменяются `специальными маркерами` - `плейсхолдерами` 
	(std::placeholders::_1, _2 и т.д.), 
	которые `заполняются `непосредственно в `момент вызова` нового `функтора`.

	В современном C++ (C++14 и новее) std::bind() 
	`практически полностью` вытеснен `лямбда-выражениями`, 
	так как они работают быстрее, лучше оптимизируются компилятором 
	и гораздо проще читаются. 
	
	Тем не менее, std::bind() остается важной частью стандарта.
	
	
	🛠️ 	Базовый синтаксис и `плейсхолдеры`

	`Плейсхолдеры` указывают, 
	`какой по счету аргумент` 
	`нового вызова` 
	подставится на `место данного параметра` 
	в `оригинальную функцию`.
*/
void print_sum(int a_param, int b_param) {
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
	cout << "a_param = " << a_param << '\n';
	cout << "b_param = " << b_param << '\n';
    cout << "a_param + b_param = " << (a_param + b_param) << '\n';
}

void first_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';

    using 	namespace 	std::placeholders; 	// 	Для доступа к _1, _2

    // 	1. 	Фиксация одного аргумента (Каррирование)
    // 	Передаем 10 как первый аргумент, а второй аргумент (_1) будет передан при вызове `add_ten`
    auto add_ten = std::bind(print_sum, 10, _1);	// NOLINT(modernize-avoid-bind)
	
    add_ten(5); 	// 	Выведет: a_param + b_param = 15 (10 пошло в `a_param`, 5 пошло в `b_param`)
	
	//	Лямбда вместо std::bind
	[](auto && PH1) -> auto { 
		print_sum(10, std::forward<decltype(PH1)>(PH1)); 
	}(5);

    // 	2. 	Изменение порядка аргументов
    // 	(_2) пойдет на место первого параметра (a_param), а (_1) - на место второго (b_param)
    auto swapped = std::bind(print_sum, _2, _1);	// NOLINT(modernize-avoid-bind)
	
    swapped(201, 202); 	// 	202 пойдет в 'a_param', 201 пойдет в 'b_param'
	
	//	Лямбда вместо std::bind
	[](auto && PH1, auto && PH2) -> auto  { 
		print_sum	(	std::forward<decltype(PH2)>(PH2)
					, 	std::forward<decltype(PH1)>(PH1)
					); 
	}(201, 202);
}
/*
	==================================================================
	🎯 	Главный сценарий использования: 
	
		Привязка к методам класса

		Исторически std::bind() 
		чаще всего применялся для создания `колбэков` 
		из `методов классов`. 
		
		`Обычный указатель` на `метод класса` 
		нельзя вызвать `без указания `конкретного объекта` (this). 
		
		std::bind позволяет «пришить» объект к методу
*/
struct Button {
    std::string 	title;
    void click(const std::string& user) const {
        cout << user << " clicked " << title << '\n';
    }
};
void second_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
	
    using namespace std::placeholders;
	
    Button 	btn{"Submit"};

    // 	Важно: `Первым аргументом` после метода 
	//	передается `указатель на объект` (или сам объект)
    auto click_event = std::bind(&Button::click, &btn, _1);	// NOLINT(modernize-avoid-bind)
	click_event("Alex"); // Выведет: Alex clicked Submit
	
	[ObjectPtr = &btn](auto && PH1) -> auto  { 
		// NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-array-to-pointer-decay)
		ObjectPtr->click(std::forward<decltype(PH1)>(PH1)); 
	}("Alex");
}
/*
	===================================================================
	
	⚠️ 	Важные подводные камни std::bind

		1. 	Копирование по умолчанию: 	Аргументы, передаваемые в std::bind, 
										по умолчанию копируются (или перемещаются) 
										внутрь создаваемого функтора, 
										даже если сама функция принимает аргументы по ссылке.
										
			• 	Решение: 		Если нужно передать переменную по ссылке, 
								её необходимо принудительно обернуть в std::ref или std::cref.
							
		2.	Игнорирование лишних аргументов: 	Если передать в созданный функтор 
												больше аргументов, чем описано `плейсхолдерами`,
												std::bind `просто `молча `проигнорирует лишние`, 
												что может скрыть логическую ошибку в коде.
*/
void 	increment(int& x_param) { x_param++; }

void third_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
		
	int 		int_n 	= 	5;
	// NOLINTNEXTLINE(modernize-avoid-bind)
    auto 	func 	= 	std::bind(increment, int_n); 	// 	Передаст копию `int_n`	!!!!
    func(); 	// 	`int_n` всё еще равен 5

	// NOLINTNEXTLINE(modernize-avoid-bind)
    auto f_ref = std::bind(increment, std::ref(int_n)); 	// 	Передаст реальную `ссылку`
    f_ref(); // 	`int_n` теперь равен 6	
}
