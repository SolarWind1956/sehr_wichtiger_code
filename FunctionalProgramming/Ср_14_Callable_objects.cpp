/*
	14.8.3. Вызываемые объекты и тип function

	В языке С++ есть несколько видов вызываемых объектов: 
	
	-	функции, 
	
	-	указатели на функции, 
	
	-	лямбда-выражения, 
	
	-	объекты, созданные функцией bind(), 
	
	-	объекты, созданные классом std::function<>, 
	
	и 
	
	-	классы с перегруженным оператором вызова функции operator().
	
	Подобно любому другому объекту, у вызываемого объекта есть тип.
	
	Например, у каждого лямбда-выражения есть собственный уникальный (безымянный) тип класса. 
	
	Типы функций и указателей на функции зависят от типа возвращаемого значения, типа аргумента и т.д.

	Однако два вызываемых объекта с разными типами могут иметь ту же сигнатуру вызова (call signature). 
	
	'Сигнатура вызова' определяет тип возвращаемого значения вызываемого объекта и тип (типы) аргумента,
	которые следует передать при вызове. 
	
	Сигнатура вызова соответствует типу функции. 
	
	Например:
				int(int, int)
				
	Функция этого типа получает два числа типа int и возвращает значение типа int.
	
	Разные типы могут иметь одинаковую сигнатуру вызова. 
	
	Иногда необходимо использовать несколько вызываемых объектов с одинаковой сигнатурой вызова, 
	как будто это тот же тип.			
*/
// 1.	обычная функция
int addi(int i, int j) 
{ 
	return i + j; 
}
// 2.	Указатель на функцию, принимающую два параметра int и возвращающую значение типа int
int	(*f_r_ptr)(int, int);
// 3.	лямбда-выражение, создающее безымянный класс объекта функции
auto mod = [](int i, int j) { 
	return i % j; 
};
// 4.	класс объекта функции - операторa вызова функции (function-call operator)
struct divide {
	int operator()(int denominator, int divisor) {
		return denominator / divisor;
	}
};
//	5.	объекты, созданные функцией bind()
auto f1_b = std::bind(addi, _1, _2);

// 	6.	объекты, созданные классом std::function<>
std::function<int(int, int)> 	function_r_ptr{ addi };
//auto result = function_r_ptr(33, 12);			

/*
	Каждый из этих вызываемых объектов применяет арифметическую операцию к своим параметрам. 
	
	Даже при том, что у каждого из них разный тип, сигнатура вызова у них одинакова:
		
		int(int, int)
		
	Эти вызываемые объекты можно использовать для написания простого калькулятора. 
	
	Для этого следует определить таблицу функций (function table), хранящую "указатели" на вызываемые объекты. 
	
	Когда программе понадобится выполнить некую операцию, она просмотрит таблицу и найдет соответствующую функцию.
	
	В языке С++ таблицы функций довольно просто реализовать при помощи карт (map). 
	
	В данном случае как ключ используем строку, соответствующую символу оператора; значение будет функцией,
	реализующей этот оператор. 
	
	При необходимости выполнить заданный оператор индексируется карта и осуществляется вызов возвращенного элемента. 
	
	Если бы все эти функции были автономными и необходимо было использовать только парные операторы для типа int, 
	то карту можно было бы определить так:
*/
// сопоставляет оператор с указателем на функцию, получающую два целых числа и возвращающую целое число
map<string, int(*)(int, int)> 		binops;	
/*
	Не все из шести перечисленных вызываемых объекта можно было бы использовать с такой картой.
	
	Например, у каждого лямбда-выражения есть собственный тип класса.
	
	Эту проблему можно решить при помощи нового библиотечного типа std::function, определенного в заголовке functional.
	
	Тип function — это шаблон. 
	
	Подобно другим шаблонам, при создании его экземпляра следует указать дополнительную информацию. 
	
	В данном случае этой информацией является сигнатура вызова объекта,
	который сможет представлять данный конкретный тип function. 
	
	Как и у других шаблонов, этот тип определяют в угловых скобках:
	
	std::function<int(int, int)>

	Здесь был объявлен тип function, способный представлять вызываемые объекты, 
	возвращающие целочисленный результат и имеющие два параметра типа int.
*/
int main() 
{
	
	cout << "I am Ср_14_Callable_objects.cpp" << endl;
	{
		function<int(int, int)> f1 = addi; 				// указатель на функцию
		function<int(int, int)> f2 = divide(); 			// объект класса вызова функции
		function<int(int, int)> f3 = [](int i, int j) 	// лямбда-выражение
			{ return i * j; };
			
		cout << f1(4, 2) << endl; // выводит 6
		cout << f2(4, 2) << endl; // выводит 2
		cout << f3(4, 2) << endl; // выводит 8
	}
	{
		/*
			Теперь карту можно переопределить, используя тип function:

			таблица вызываемых объектов, соответствующих всем бинарным операторам 
		
			все вызываемые объекты должны получать по два int и возвращать int
			
			элемент может быть указателем на функцию, объектом функции или лямбда-выражением
		
			map<string, function<int(int, int)>> 	binops;
		
			В эту карту можно добавить каждый из вызываемых объектов приложения, 
			будь то указатель на функцию, лямбда-выражение или объект функции:
		*/	
		map<string, function<int(int, int)>> binopsq = {
															{"+", addi}, 				// указатель на функцию
															{"-", std::minus<int>()}, 	// объект библиотечной функции
															{"/", divide()}, 			// пользовательский объект функции
															{"*", [](int i, int j) { return i * j; }}, 	// безымянное
																										// лямбда-выражение
															{"%", mod}  				// именованный объект лямбда-выражения
													  };
		/*
			В карте пять элементов. 
			
			Хотя все лежащие в основе вызываемые объекты имеют различные типы, 
			каждый из них можно хранить в общем типе function<int(int, int)>.
			
			Как обычно, при индексировании карты возвращается ссылка на ассоциированное значение. 
			
			При индексировании карты binops возвращается ссылка на объект типа function. 
			
			Тип function перегружает оператор вызова. 
			
			Этот оператор вызова получает собственные аргументы и передает их хранимому вызываемому объекту:
		*/
		cout << binopsq["+"](10, 5) << endl; // calls add(10, 5)
		cout << binopsq["-"](10, 5) << endl; // uses the call operator of the minus<int> object
		cout << binopsq["/"](10, 5) << endl; // uses the call operator of the divide object
		cout << binopsq["*"](10, 5) << endl; // calls the lambda function object
		cout << binopsq["%"](10, 5) << endl; // calls the lambda function object
	}
	{
		/*
			Перегруженные функции и тип function
			
			Нельзя непосредственно хранить имя 'перегруженной' функции в объекте типа function:
		*/
		int 		addi(int i, int j);
		Sales_data 	addi(const Sales_data&, const Sales_data&);
		
		map<string, function<int(int, int)>> 	binopsq;
		// binops.insert({"+", addi}); 							// ошибка: какой именно addi?
		
		/*
		Один из способов разрешения двусмысленности подразумевает хранение 'указателя на функцию' вместо имени функции:
		*/
		int (*fp)(int, int) = addi; 		// указатель на версию addi, получающую два int
		
		binops.insert({"+", fp}); 			// ok: fp указывает на пeрвую версию addi
		
		/*
			В качестве альтернативы для устранения неоднозначности можно использовать лямбда-выражение:
			
			ok: использование лямбда-выражения для устранения неоднозначности при выборе используемой версии addi
		*/	
		binops.insert({ "+", [](int a, int b) {return addi(a, b);} });
		/*
			Вызов в теле лямбда-выражения передает два целых числа. 
			
			Этому вызову может соответствовать только та версия функции addi(), 
			которая получает два целых числа, а следовательно, эта функция и применяется при выполнении лямбда-выражения.
		*/
	}

    return 0;
}
 