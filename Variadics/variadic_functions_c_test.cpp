/*
	Пример в Си
	
	Для реализации функций с переменным числом аргументов 
	в языке программирования 'C' нужно подключить заголовочный файл  stdarg.h. 

	Прежде использовался varargs.h, который был объявлен устаревшим. 
	
	Для C++ этот заголовочный файл называется cstdarg.
	
	stdarg.h объявляет:

	-	тип va_list, 
	
	и определяет четыре макрофункции: 
	
	-	va_start(), 
	-	va_arg(), 
	-	va_copy() 
	и 
	-	va_end().

	Макрофункция va_start() принимает два аргумента:
	
		-	объект типа va_list  
		и 
		-	ссылку на последний параметр функции (тот, что перед многоточием). 
		
	Она инициализирует объект va_list 
	для использования в va_arg() или va_copy(). 
	
	Компилятор обычно выдает предупреждение, 
	если ссылка неверная (например, ссылка на параметры, отличающиеся от последнего, или ссылка на совершенно другой объект).
	
	va_arg() принимает два аргумента, 
		
		-	объект типа va_list (ранее инициализированный) 
		и
		-	дескриптор типа. 
		
		Он расширяется на следующей переменной аргумент, 
		и имеет указанный тип. 
		
	Каждый следующий вызов возвращает следующий аргумент.
	
	va_end() принимает один аргумент типа va_list и очищает его. 
	
	Если вы хотели, например, сканировать переменное число аргументов более чем один раз, 
	вам надо будет повторно инициализировать va_list путём вызова va_end() и затем va_start().
	
	va_copy() принимает два аргумента, оба типа va_list. 
	
	Он дублирует второй (который должен был быть инициализирован) в первый.
	
*/
