/*
	https://learn.microsoft.com/ru-ru/cpp/c-runtime-library/reference/va-arg-va-copy-va-end-va-start?view=msvc-170
	
	Стандартные макросы C, определенные в STDARG.H, используются следующим образом:

	va_start() задает указатель arg_ptr 
	на первый необязательный аргументу в списке аргументов, 
	который передан функции. 
	
	Аргумент arg_ptr должен иметь тип va_list. 
	
	Аргумент 'prev_param' — это имя обязательного параметра, 
	который непосредственно предшествует первому необязательному аргументу в списке аргументов. 
	
	Если параметр 'prev_param' объявлен в классе регистрового хранения, 
	поведение макроса не определено. 
	
	va_start() необходимо использовать до первого использования va_arg().

	va_arg() извлекает значение 'type' из расположения, 
	которое задано параметром 'arg_ptr', 
	и увеличивает значение указателя 'arg_ptr', 
	чтобы он указывал на следующий аргумент в списке, 
	используя размер 'type' 
	для определения места начала следующего аргумента. 
	
	va_arg() можно использовать в функции любое количество раз, 
	чтобы получить аргументы из списка.

	va_copy() делает копию списка аргументов в текущем состоянии. 
	
	Параметр src должен быть уже инициализирован с помощью va_start(); 
	он может быть обновлен вызовами va_arg(), 
	но не должен быть сброшен с помощью va_end(). 
	
	Следующий аргумент, который извлекается va_arg() из 'dest', 
	совпадает со следующий аргументом, 
	который извлекается из 'src'.

	После получения всех аргументов, va_end() сбрасывает указатель на NULL. 
	
	va_end() должен вызываться для каждого списка аргументов, 
	который инициализируется va_start() или va_copy(), 
	до выполнения возврата функцией.
*/ 