/*.
		16.4. Шаблоны с переменным количеством аргументов
		
	Шаблон с переменным количеством аргументов (variadic template) - это шаблон функции или класса, 
способный получать переменное количество параметров. 

	Набор таких параметров называется 'пакетом параметров' (parameter pack). 
	
	Есть два вида пакетов параметров: 
	
	1. пакет параметров шаблона (template parameter pack), 
		представляющий любое количество параметров шаблона, 
	и 
	2. пакет параметров функции (function parameter pack), 
		представляющий любое количество параметров функции.
		
	Для указания, что шаблону или функции представлен пакет параметров, используется многоточие. 
	
	В списке параметров шаблона синтаксис class... или typename... означает, 
что следующий параметр представляет список любого количества типов; 

имя типа, сопровождаемое многоточием, 
представляет список из любого количества параметров значения заданного типа. 

Параметр в списке параметров функции, типом которого является пакет параметров шаблона, 
представляет собой пакет параметров функции.
.*/
template <typename T, typename ... Args>				// Args - это пакет параметров шаблона; 
void any_func (const T& t, const Args& ... rest)			// rest - пакет параметров функции
{
	cout << "\n I'm variadic templated function <void any_func (const T& t, const Args& ... rest)>" << endl;
	cout << "The first parameter is " << t << endl;
	/*
	Оператор sizeof.
	
	Когда необходимо узнать, сколько элементов находится в пакете, 
	можно использовать оператор sizeof ... . 
	Oператор sizeof ... возвращает константное выражение и не вычисляет свой аргумент:
	*/
	cout << "sizeof...(Args) - количество параметров типа == " << sizeof...(Args) << endl; 		
	cout << "sizeof...(rest) - количество дополнительных параметров функции == " << sizeof...(rest) << endl; 	
}
// Args представляет любое количество параметров типа шаблона
// rest представляет любое количество параметров функции
/*
	Этот код объявляет, что any_func() - это функция с переменным количеством аргументов, 
у которой один параметр типа по имени T и пакет параметров шаблона по имени Args. 
	Этот пакет представляет любое количество дополнительных параметров типа. 
	В списке параметров функции any_func() 
один параметр типа const & для любого типа переданного параметром T 
и пакет параметров функции rest типа const Args& ... . 
	Этот пакет представляет любое количество параметров функции.
	
	Как обычно, компилятор выводит типы параметра шаблона из аргументов функции.
	
Для шаблона с переменным количеством аргументов компилятор также выводит 'количество параметров в пакете'.

*/
void test_variadic_temple_func()
{
	int 			i 	= 4242; 
	double		d 	= 3.14; 
	string 		s 	= "how no wbrowncow";
	
	any_func ( i, s, 42, d ); 	// три параметра в пакете
	any_func ( s, 42, "hi" ); 	// двa параметра в пакете
	any_func ( d, s ) ; 			// один параметр в пакете
	any_func ( "hi" ) ; 		// пустой пакет
	/*
	Компилятор создаст четыре разных экземпляра функции any_func():
	
	void any_func(const int &, const string &, const int &, const double &);
	void any_func(const string &, const int &, const char[З] &);
	void any_func(const double &, const string &);
	void any_func(const char[З] &);

В каждом cлучае тип T выводится из типа первого аргумента. 
Остальные аргументы (если они есть) представляют количество и типы 'дополнительных аргументов функции'.
	*/
}
/*
		16.4.1. Шаблоны функции с переменным количеством аргументов

	Для определения функции, способной получать переменное количество аргументов, 
можно использовать класс initializer_list. 
	В этом случае у аргументов должен быть одинаковый тип (или типы, преобразуемые в общий тип). 
	
	Функции с переменным количеством аргументов используются тогда, 
когда не известно ни количество, ни типы аргументов.

	Для примера определим функцию, подобную прежней функции error_msg(), 
только на сей раз обеспечим и изменение типов аргумента.
	Начнем с определения функции print() с переменным количеством аргументов,
которая выводит содержимое заданного списка аргументов в указанный поток.
*/
/*
Функции с переменным количесrвом аргументов зачастую рекурсивны. 
	Первый вызов обрабатывает первый аргумент в пакете и вызывает себя для остальных аргументов. 
Новая функция print() будет работать таким же образом - каждый вызов выводит свой второй аргумент в поток,
обозначенный первым аргументом. 

	Для остановки рекурсии следует определить также обычную функцmо print(), 
которая получает поток и объект:
*/
// function to end the recursion and print the last element
// Функция для завершения рекурсии и вывода последнего элемента
// ее следует объявить перед определением версией print() с переменным количеством аргументов
template<typename T>
ostream &
print(ostream &os, const T &t)
{
    return os << t; 										// no separator after the last element in the pack
}
// эта версия print() будет вызвана для всех элементов в пакете, кроме последнего
template <typename T, typename... Args>                 
ostream &
print(ostream &os, const T &t, const Args&... rest)		// expand Args
{
    os << t << ", ";
    return print(os, rest...);                     			// expand rest
															// Здесь компилятор превратит rest...
															// в (const T &t, const Args&... rest-1)
															// А когда в rest останется только один параметр,
															// компилятор вызовет &print(ostream &os, const T &t)
}
/*
Первая версия функции print() останавливает рекурсию 
и выводит последний аргумент в начальном вызове функции print(). 
Вторая версия, с переменным количеством аргументов, выводит аргумент, связанный с t, 
и вызывает себя для вывода остальных значений в пакете параметров функции.
Ключевая часть - вызов функции print() в функции с переменным количеством аргументов:

return print(os, rest...); // рекурсивный вызов; вывод других аргументов

Версия функции print() с переменным количеством аргументов получает три параметра: 

ostream&, const Т& и пакет параметров. 

Но в этом вызове передаются только два аргумента. 

	В результате первый аргумент в пакете rest привязывается к t. 
Остальные аргументы в пакете rest формируют пакет параметров для следующего вызова функции print(). 
	Таким образом,
при каждом вызове первый аргумент удаляется из пакета и становится аргументом, связанным с t.

	Для последнего вызова в рекурсии, print(cout, 42), подходят обе версии функции print(). 
Этот вызов передает два аргумента, и типом первого являются ostream&. 
	Таким образом, подходящей является обычная версия функции print().
Версия с переменным количеством аргументов также является подходящей.
	В отличие от обычного аргумента, пакет параметров может быть пустым.
Следовательно, экземпляр версии функции print() с переменным количеством аргументов
может быть создан только с двумя параметрами: 
один - для параметра ostream& и другой - для параметра const Т&.
	Обе функции обеспечивают одинаково хорошее соответствие для вызова.
Однако не шаблонная версия с переменным количеством аргументов более специализирована, 
чем шаблонная с переменным количеством аргументов.
	Поэтому выбирается версия без переменного количества аргументов.
Объявление версии функции print() с постоянным количеством аргументов должно быть в области видимости, 
когда определяется версия с переменным количеством аргументов. 
	В противном случае функция с переменным количеством аргументов 
будет рекурсивно вызывать себя бесконечно.
*/

/*
		16.4.2. Развертывание пакета
		
	Кроме выяснения размера, единственное, что можно еще сделать с пакетом параметров, - 
это развернуть (pack expansion) его. 
	При развертывании пакета предоставляется схема (pattern), 
используемая для каждого развернутого элемента.
	Развертывание пакета разделяет его на элементы с применением схемы к каждому из них. 
Для запуска развертывания справа от схемы помещают многоточие (...).

Например, функция print() содержит два развертывания:

	template <typename T, typename... Args>                 
	ostream &
	print(ostream &os, const T &t, const Args&... rest)		// ПЕРВОЕ развертываниe - Args
	{
		os << t << ", ";
		return print(os, rest...);                     			// ВТОРОЕ развертываниe - rest
	}
В 'первом cлучае' развертывание пакета параметров шаблона Args создает список параметров функции print(). 

'Второй случай' развертывания находится в вызове функции print() - return print(os, rest...); . 

Эта схема создает список аргументов для вызова.

Развертывание пакета Args
применяет схему const Args& к каждому элементу в пакете параметров шаблона Args. 

Результатом этой схемы 
будет разделенный запятыми список из любого количества типов параметров в формате const тип&.

При развертывании пакета параметров функции возможны и более сложные схемы. 
Можно было бы написать вторую функцию с переменным количеством аргументов, 
которая вызывает функцию debug_rep() для каждого из своих аргументов, 
а затем вызывает функцию print(), чтобы вывести полученные строки:
*/
// вызвать debug_rep() для каждого аргумента в вызове print()
template <typename ... Args>
ostream & errorMsg (ostream & os, const Args& ... rest)
{
	// print( os, debug_rep(al), debug_rep(a2), ... , debug_rep(аn) )
	return print(os, debug_rep(rest)...);
}
/*
		16.4.3. Перенаправление пакетов параметров
		
	По новому стандарту можно использовать шаблоны с переменным количеством
аргументов совместно с функцией forward() для написания функций, 
которые передают свои аргументы неизменными некой другой функции. 
	Чтобы проиллюстрировать такие функции, добавим в класс StrVec функцию-член emplaceback(). 
Такая функция-член библиотечных контейнеров является шаблоном-членом с переменным количеством аргументов,
которая использует их для создания элементов непосредственно в области, управляемой контейнером.
	Версия функции emplaceback() для класса StrVec 
также должна быть с переменным количеством аргументов, поскольку у класса string много конструкторов,
которые отличаются своими параметрами.
	Поскольку желательно быть в состоянии использовать конструктор перемещения класса string, 
необходимо будет также сохранять всю информацию о типах аргументов, переданных функции emplace_back().
	Как уже упоминалось, сохранение информации типа - двухступенчатый процесс. 
1. Во-первых, для сохранения информации типа аргументов 
параметры функции emplace_back() следует определить как ссылки на R-значение параметра типа шаблона
*/
class StrVec 
{
public:
    static std::allocator<std::string> alloc; 				// allocates the elements

	// add elements
    size_t size		() const { return first_free - elements; }
	size_t capacity	() const { return cap - elements; }
	// utility functions:
	void reallocate	(){};       		// get more space and copy the existing elements
	// used by members that add elements to the StrVec
	void chk_n_alloc() { if ( size() == capacity() ) reallocate(); }
		
	template <class ... Args> 
	void emplace_back(Args&& ...);
	
	std::string *	elements;   	// pointer to the first element in the array
	std::string *	first_free; 		// pointer to the first free element in the array
	std::string *	cap;        	// pointer to one past the end of the array
};
/*
	Схема && в развертывании пакета параметров шаблона означает, 
что каждый параметр функции будет ссылкой на R-значение на соответствующий ей аргумент.

2. Во-вторых, функцию forward() следует использовать для сохранения первоначальных типов аргументов, 
когда функция emplace_back() передает их функции construct()
*/
template <class ... Args>
inline
void StrVec::emplace_back(Args&& ... args)
{
	chk_n_alloc(); 														// пересоздает StrVec при необходимости
	alloc.construct(first_free++, std::forward<Args> (args) ... );
}

/*
		16.5. Специализация шаблона
		
	Не всегда можно написать один шаблон, который наилучшим образом
подходит для всех возможных типов аргументов шаблона, для которых может быть создан его экземпляр. 
	В некоторых случаях общий шаблон просто не подходит для типа: 
он либо приводит к ошибке при компиляции, либо к неправильным действиям. 
	С другой стороны, 
иногда можно воспользоваться уникальными возможностями определенного типа 
для создания более эффективной функции, чем та, которой снабжен экземпляр общего шаблона.	
	Функция compare() - хороший пример шаблона функции, 
общее определение которого не подходит для специфического типа, а именно символьных указателей. 
	Хотелось бы, чтобы функция compare() сравнивала символьные указатели, 
используя функцию strcmp(), а не сравнивала значения указателей.
*/
	template <typename T> 
	int compare(const T & , const T &);
	// первая версия; может сравнить любые два типа
	// вторая версия, для обработки строковых литералов
	template <size_t N, size_t M>
	int compare(const char(&)[N], const char(&)[M]);
	
/*
	Для обработки символьных указателей (в отличие от массивов) 
можно определить 'специализацию шаблона' (template specialization) для первой версии функции compare(). 
	
	'Специализация' - это отдельное определение шаблона,
в котором определяется один или несколько параметров шаблона для получения 'специфического типа'.

		Специализация шаблона функции
		
	При 'специализации шаблона функции' 
следует 'предоставить аргументы' для 'каждого параметра' первоначального шаблона. 

Для указания 'специализации шаблона' используется ключевое слово template, 
сопровождаемое парой 'пустых' 'угловых скобок' ( <> ). 

Пустые скобки означают, что аргументы будут предоставлены для всех параметров первоначального шаблона:
*/	
// специальная версия compare() для работы с указателями на символьные массивы
template< >		// <> - аргументы будут предоставлены для всех параметров первоначального шаблона
int compare (const char* const & p1, const char* const & p2)
{
	return strcmp(p1, p2);
}
/*
Трудная для понимания часть этой специализации относится к типам параметра функции. 

	При определении специализации 
типы параметров функции должны совпадать с соответствующими типами ранее объявленного шаблона:

	template <typename Т> int compare(const Т&, const Т&);

В этой специализации параметры функции являются ссылками на константные типы. 

	Подобно псевдонимам типа, взаимодействие между типами параметра шаблона, 
указателями и константами может удивить.

	Необходимо определить специализацию шаблона этой функции с типом const char* для параметра T. 

	Функция потребует ссылки на константную версию этого типа. 

	Константная версия типа указателя - это константный указатель, а не указатель на константу. 

	В данной специализации следует использовать тип 
	
	const char * const & 
	
являющийся ссылкой на константный указатель на константный символ.

		Перегрузка функций или специализация шаблона функции

	При определении 'специализации шаблона функции' разработчик, по существу, выполняет задачу компилятора. 

	Таким образом, 
определение предоставляется для использования специфического экземпляра первоначального шаблона.
 
	Важно понимать, что 'специализация' - это создание экземпляра функции, а не перегрузка ее экземпляра.
	
	Специализация создает экземпляр шаблона, а не перегружает его.
	
	В результате специализация не затрагивает механизм подбора функций.
	
	КЛЮЧЕВАЯ КОНЦЕПЦИЯ. ОБЫЧНЫЕ ПРАВИЛА ОБЛАСТИ ВИДИМОСТИ ОТНОСЯТСЯ И К СПЕЦИАЛИЗАЦИИ
	
	Чтобы специализировать шаблон, объявление его оригинала должно быть в области видимости. 
	
	Кроме того, объявление специализации должно быть в области видимости перед любым кодом, 
использующим экземпляр шаблона.

	Пропуск объявления обычных классов и функций найти очень просто -
компилятор не сможет обработать такой код. 

	Но при отсутствии объявления специализации компилятор обычно создает код, 
используя первоначальный шаблон. 

	Поэтому ошибки в порядке объявления шаблона и его специализации довольно просто допустить, 
но очень трудно найти.

	Использование специализации и экземпляра первоначального шаблона с тем же набором аргументов шаблона 
является ошибкой. 

	Но компилятор вряд ли обнаружит эту ошибку.
	
	Шаблоны и их специализации должны быть объявлены в том же файле заголовка. 
	
	Объявления всех шаблонов с данным именем должны располагаться сначала, 
а затем все специализации этих шаблонов.

		Специализация шаблона класса
		
	Кроме специализации шаблонов функций, вполне можно также специализировать шаблоны классов. 

	В качестве примера определим специализацию библиотечного шаблона hash, 
который можно использовать для хранения объектов класса Sales_data в неупорядоченном контейнере. 

	По умолчанию неупорядоченные контейнеры 
используют для организации своих элементов класс hash<key_type>. 

	Чтобы использовать его с собственным типом данных, следует определить специализацию шаблона hash. 

	Специализированный класс hash должен определять следующее.
	
	Частичная специализация шаблона класса
	
	В отличие от шаблона функции, 
специализация шаблона класса не обязана предоставлять аргументы для каждого параметра шаблона. 
	Можно определить некоторые из них, но не все.

	Частичная специализация (partial specialization) шаблона класса сама является
шаблоном. 
	Пользователи должны предоставить аргументы для тех параметров шаблона, 
которые не затронуты специализацией.

	Частично можно специализировать только шаблон класса. 
	
	Нельзя частично специализировать шаблон функции.
	
	Библиотечный тип remove_reference работает с серией специализаций:
*/
// первоначальный, наиболее общий шаблон
template <class T> 
struct remove_reference
{
	typedef T type;
};

// частичные специализации, которые будут использоваться для ссылок на L- и R-значения
template <class T> 
struct remove_reference<T &> 	// ссылки на L-значение
{ 
	typedef T type; 
};
template <class T> 
struct remove_reference<T &&> 	// ссылки на R-значение
{ 
	typedef T type; 
};

/*
	Первый шаблон определяет самую общую версию. 
Его экземпляр может быть создан с любым типом; 
он использует свой аргумент шаблона как тип для своего члена type. 
	Следующие два класса - это частичные специализации первоначального шаблона.
Поскольку частичная специализация - это шаблон, начнем, как обычно, с определения параметров шаблона. 
	Подобно любой другой специализации, у частичной специализации то же имя, 
что и у специализируемого шаблона.
	Список параметров специализации шаблона включает элементы для каждого параметра шаблона, 
тип которого не был определен полностью при частичной специализации. 
	
	После имени класса располагаются аргументы для 'параметров специализируемого шаблона'. 
Эти аргументы располагаются в 'угловых скобках' после имени шаблона. 
	
	Аргументы позиционально соответствуют параметрам первоначального шаблона.
	
	Список параметров шаблона частичной специализации - 
это подмножество или специализация списка параметров первоначального шаблона. 
	В данном случае у специализаций то же количество параметров, 
что и у первоначального шаблона. 
	Но тип параметров в специализациях отличается от первоначального шаблона. 

	Специализация будут использоваться для ссылок на типы L- и R-значений соответственно:
*/
void test_remove_reference()
{
int i;
	// decltype(42) - это int, используется первоначальный шаблон
	remove_reference<decltype(42)>::type 				a;
	// decltype(i) - это int&, используется первая (Т&) частичная специализация
	remove_reference<decltype(i)>::type 				b;
	// decltype( std::move(i) ) - это int&&, используется вторая (т.е., Т&&) частичная специализация
	remove_reference<decltype( std::move(i) )>::type 	c;
	// У всех трех переменных, а, b и с, тип int
	
	std::cout 	<< "I'm <test_remove_reference()>  " 
				<< "\n type of 42	== " << type_name_as_str<decltype(42)>() 
				<< "\n type of i	== " << type_name_as_str<decltype(i)>()
				<< "\n type of a	== " << type_name_as_str<decltype(a)>()		
				<< "\n type of b	== " << type_name_as_str<decltype(b)>()	
				<< "\n type of c	== " << type_name_as_str<decltype(c)>()				
				<< std::endl;
}

