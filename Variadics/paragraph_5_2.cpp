/*
	На самом деле "T&&" имеет два разных значения. 
	
	Одно из них - конечно, rvalue-ссылка. 

	Такие ссылки ведут себя именно так, как вы ожидаете: 
	они связываются только с rvalue, 
	и их смысл заключается в идентификации объектов, 
	которые могут быть перемещены.

	Другое значение "T&&" - либо rvalue-ссылка, либо lvalue-ссылка. 
	
	Такие ссылки выглядят в исходном тексте как rvalue-ссылки (т.е. "T&&"), 
	но могут вести себя так, как если бы они были lvalue-ссылками (т.е. "T&"). 
	
	Такая дуальная природа позволяет им быть связанными как с rvalue (подобно rvalue-ссылкам),
	так и с lvalue (подобно lvalue-ссылкам).

	Кроме того, они могут быть связаны как с константными, так и с неконстантными объектами, 
	как с объектами volatile, так и с объектами, не являющимися volatile, и даже с объектами, 
	одновременно являющимися и const, и volatile. 
	
	Они могут быть связаны практически со всем. 
	
	Такие беспрецедентно гибкие ссылки заслуживают собственного имени, 
	и я называю их "универсальными ссылками" (universal reference).
*/
/*
	"Универсальные ссылки" возникают в двух контекстах. 

	Наиболее распространенным являются параметры шаблона функции, 
	такие как в приведенном  примере кода:
*/
void proc(const WidgetIn& lvalArg)	
{ cout << "I'm <void proc ( const WidgetIn& lvalArg )>" << endl; };	// Обработка lvalue 

void proc(WidgetIn&& rvalArg)	
{ cout << "I'm <void proc ( WidgetIn&& lvalArg )>" << endl; };		// Обработка rvalue

template<typename T>
void func (T&& param)				// param - универсальная ссылка - аргументом может быть и rvalue и lvalue
{
	cout << "I'm void func(T&& param)" << endl;

	proc(std::forward<T>(param));	
	/* 
		Вызовет process(WidgetIn && rvalArg)  или process(const WidgetIn & lvalArg)
		std::forward<T>(param) преобразует к T&&, если параметр rvalue
		и не станет преобразовывать, если параметр lvalue
	*/
	proc(param);					// Вызовет process(const WidgetIn& lvalArg) независимо от параметра
};	
/*
	Вторым контекстом являются объявления auto:
*/
WidgetIn&&	var11 = WidgetIn();		// rvalue - ccылкa

auto&&		var21 = var11;			// HE rvalue - ccылкa, но УНИВЕРСАЛЬНАЯ ССЫЛКА

/*
	Общее в этих контекстах - наличие вывода типа. 

	В шаблоне func выводится тип param, а в объявлении var21 выводится тип переменной var21.
*/
/*
	Если вы видите "T&&" без вывода типа, то вы смотрите на rvalue-ссылку:
*/
void	foo ( WidgetIn&& param ) {};			// Вывод типа отсутствует - param - rvalue-ccылкa 

WidgetIn&&	var1_51 = WidgetIn();				// Вывод типа отсутствует - varl - rvalue-ccылкa
/*
	Чтобы ссылка была универсальной, вывод типа необходим, но не достаточен. 

	Вид объявления ссылки также должен быть корректным, и этот вид достаточно ограничен. 

	Он должен в точности имеет вид "T&&':

	Взглянем еще раз на пример, который мы уже рассматривали ранее:
*/
template<typename T> 
void	f_of_vec(std::vector<T>&& param) {};				// param - rvalue - ccылкa
/*
	Когда вызывается f_of_vec(), тип T выводится (если только вызывающий код явно его не укажет, 
	но этот крайний случай мы не рассматриваем). 

	Однако объявление типа param не имеет вида "T&&";
	оно представляет собой std::vector<T>&&. 

	Это исключает возможность для param быть универсальной ссылкой. 

	Следовательно, param является rvаluе-ссылкой, 
	что ваши компиляторы с удовольствием подтвердят при попытке передать в функцию f_of_vec lvalue:

	Даже простого наличия квалификатора const достаточно для того, чтобы отобрать у ссылки звание универсальной:
*/
template<typename T>
void f_c(const T&& param) {};						// param - rvalue-ccылкa 
/*
	Итак, универсальная ссылка обязана иметь вид "T&&'

	Hе обязательно использовать в качестве имени символ (букву) T. 

	Например, приведенный далее шаблон принимает универсальную ссылку, 
	поскольку она имеет правильный вид ("Type&&"), 
	а тип 'param' выводится (опять же, исключая крайний случай, когда вызывающий код явно указывает тип)
*/
template < typename MyTemplateType >				
void someFunc_ ( MyTemplateType&& param ) {};			// param является универсальной ссылкой 
