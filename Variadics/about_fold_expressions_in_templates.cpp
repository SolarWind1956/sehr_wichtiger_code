/*
	===================================================================
	ИИ
		`Выражения-свертки` (`fold expressions`) в C++17 - 	это синтаксис для компактной обработки пакетов параметров
														variadic-шаблонов, 
														позволяющий применять `бинарные операции` 
														ко всем элементам без рекурсии. 
														
		Они заменяют сложные рекурсивные шаблоны, 
		повышая читаемость кода, 
		и поддерживают `унарные` (левые/правые) и `бинарные` свертки 
		с `почти всеми` операторами. 
		
		Основные типы сверток 
		(где `pack` - `пакет параметров`, `op` - `оператор`): 
		
		-	`Унарная правая` 	(pack op ...)			➔ 	(arg1 op (... op (argN-1 op argN)))
		
		-	`Унарная левая` 		(... op pack)			➔  	(((arg1 op arg2) op ...) op argN)
		
		-	`Бинарная правая` 	(pack op ... op init)		➔   	(arg1 op (... op (argN op init)))
		
		-	`Бинарная левая` 	(init op ... op pack)		➔   	(((init op arg1) op arg2) op ...) 
		
		Если ellipsis `...` находится `справа` от `пакета параметров` `pack` и `оператора`  `op`,
		то свертка называется `правой`.
		
		Если ellipsis `...` находится `слева` от `оператора`  `op` и `пакета параметров` `pack` ,
		то свертка называется `левой`.
		
		Пример использования:	
		
			Суммирование всех аргументов: 
*/			
template<typename... Args>
auto sum(Args... args) {
	cout << bright_yellow << "-------------- I'm " << __PRETTY_FUNCTION__ << reset << endl;
    return (... + args); 		// 	`Унарная левая` свертка
}
void test_1_unary_fold_expressions(){
	cout << blue << "-------------- I'm " << __PRETTY_FUNCTION__ << reset << endl;
	auto result = sum(1, 2, 3, 4); 		//	-> 1+2+3+4 = 10
	cout << cyan << "auto result = sum(1, 2, 3, 4); result == " << result << reset << endl;
}
/*
		Особенности: 
		
			Совместимость: 		Доступны начиная с стандарта C++17.
			
			Операторы: 			Поддерживаются почти все бинарные операторы, кроме
								
								., ->* 
								
								[].
								
			Пустые пакеты: 		`Унарные свертки` вызывают ошибку при `пустом пакете` 
								(кроме &&, ||, ,), 
								`бинарные свертки` (с init) `корректно работают с `пустым пакетом`, 
								возвращая `init`. 
	ИИ	
	===================================================================	
*/
/*
	===================================================================
	ИИ
	Основные фишки:
	
		Скобки обязательны: 		Выражение всегда должно быть заключено в (круглые скобки).
		
		Пустые пакеты: 			Для большинства операторов пустой пакет - это ошибка. 
		
		Исключения: 			-	`&&` 		(даст true), 
								-	`||` 			(даст false) 
								и 
								-	`,` 			(даст void()).
								
		Эффективность: 			Компилятор разворачивает `свертку` в `плоский код`, 
								что быстрее и проще для оптимизации, 
								чем старая добрая рекурсия шаблонов.
	ИИ
	===================================================================	
*/
template<typename... Args>
void printAll(Args... args) {
    (cout << ... << args) << '\n'; 		// 	Левая бинарная свертка
}
template<typename... Args>
bool allTrue(Args... args) {
    return (... && args); 				// 	Вернет `true`, если `все аргументы `истинны`
}
void test_2_unary_fold_expressions(){
	cout << blue << "-------------- I'm " << __PRETTY_FUNCTION__ << reset << endl;
	
	printAll('a', ' ', "Hello, World!", ' ', 42, ' ', 3.14);
}
/*
	===================================================================
	ИИ
		В контексте `вариативных шаблонов` (variadic templates) 
		важно различать два похожих по названию, 
		но разных по функциям оператора:
		
		1. 	Оператор sizeof...(Ts)
			
			Это специальный оператор, 
			предназначенный для работы с `пакетами параметров` (parameter packs). 


			Что делает: 	возвращает 	`количество типов` в `пакете параметров` `Ts` 
			(или `количество аргументов` в `пакете значений`).
			
			Пример: 		если вы вызвали шаблон как 
						
						func<int, double, char>(), 
						
						то sizeof...(Ts) вернет 3. 

		2. 	Оператор sizeof(Ts)

			`Обычный` оператор `sizeof`, 
			примененный к `пакету параметров` `напрямую`, 
			приведет к ошибке компиляции, 
			так как `он ожидает` 
			`конкретный тип` или `выражение`, 
			а `не целый пакет`. 

			Чтобы использовать `обычный sizeof` 
			для `каждого типа из пакета`, 
			нужно использовать `распаковку` (pack expansion):

			sizeof(Ts)... 
			
			возвращает 	`последовательность `размеров каждого типа` в байтах.

			Применение: 	часто используется `внутри выражений свертки` (fold expressions) 
							или для `инициализации массивов`. 
							
							Причем, в свертках не имеет значение, слева или справа от оператора
							находится многоточие:
							
							(sizeof(Ts) + ... + sizeof(T))
														
							(sizeof(T) + ... + sizeof(Ts))
							
							Эти две свертки эквивалентны
		Сравнение:

		------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		Оператор 			Пример использования					Результат
		------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		sizeof...(Ts)			std::size_t 	count 	= sizeof...(Ts);		Общее количество типов в пакете
		
		sizeof(Ts)...			std::size_t 	sizes[] 	= { sizeof(Ts)... };		Массив с размерами каждого типа в байтах.
		
		sizeof(Ts)			sizeof(Ts)								Ошибка: 	пакет параметров 
																				нельзя использовать 
																				так `напрямую`.
		------------------------------------------------------------------------------------------------------------------------------------------------------------------------																		

		Пример кода:
*/
template <typename T, typename... Ts>
void 	info() 
{
	cout << bright_white << "-------------- I'm " << __PRETTY_FUNCTION__ << reset << endl;
	
    // 	Количество дополнительных типов
    constexpr std::size_t 	count 		= 	sizeof...(Ts) + 1; 
    cout <<	"Количество дополнительных типов + 1 : " <<  count << endl;
	
    // 	Сумма размеров всех типов в байтах 
    constexpr std::size_t 	total_size 		= (sizeof(Ts) + ... + sizeof(T)); 	//	В свертке, повидимому,
																				//	sizeof(Ts) + ...
																				//	эквивалентно 
																				//	sizeof(Ts)...
	constexpr std::size_t 	total_size_answ 	= (sizeof(T) + ... + sizeof(Ts));	//	В свертке, повидимому,
																				//	... + sizeof(Ts) 
																				//	также эквивалентно 
																				//	sizeof(Ts)...
	assert(total_size == total_size_answ && "total_size != total_size_answ"); 
	
	cout <<	"Сумма размеров всех типов в байтах : " <<  total_size << endl;
	
	std::size_t 	sizes[sizeof...(Ts) + 1] 	= { sizeof(T), sizeof(Ts)... };
	
	for (auto elem : sizes)
		cout << elem << "  ";
	cout << endl;
	
	
}
void 	test_info_function(){
	cout << bright_white << "-------------- I'm " << __PRETTY_FUNCTION__ << reset << endl;
	
	info<bool, int, long, std::string>(); 
} 
