#include <cassert>
#include "Matrix.h"

using namespace Numeric_lib;

//------------------------------------------------------------------------------
double 	f_square	(double 	a) { 
	return a * a; 
}

//------------------------------------------------------------------------------
double 	f_product	(double 	a, 	double 	b) { 
	return a * b; 
}
 
//------------------------------------------------------------------------------
double 	scale	(double 	d, 	double 	s) { 
	return d * s; 
}

//------------------------------------------------------------------------------

void 	scale_in_place	(double& 	d, 	double 	s) 	{ 
	d *= s; 
}

//------------------------------------------------------------------------------

int main()
{
    Matrix<int,1> a1(8);          // a1 is a 1D Matrix of ints
    Matrix<int>   a(8);           // means Matrix<int,1> a(8);

	/*
		У каждого объекта класса Мatrix 
		можно запросить 
		общее количество элементов 
		и 
		количество элементов в определенном измерении. 
		
		У одномерной матрицы эти параметры совпадают.
	*/
    a.size();                     // number of elements in Matrix
    a.dim1();                     // number of elements in 1st dimension

    int  i = 4;
    int  n = 7;
    int* p = a.data();            // extract data as a pointer to an array

    a(i);                         // ith element (Fortran style), but range checked
    a[i];                         // ith element (C-style), range checked
    //a(1,2);                     // error: a is a 1D Matrix

	/*
		Многие алгоритмы обращаются к 'части матрицы' Мatrix. 
		
		Такая часть называется "срезкой" (slice), 
		представляет собой 'подматрицу', 
		или 'диапазон элементов', 
		и создается функцией slice(). 
		
		В классе Мatrix есть два варианта этой функции.
	*/
    a.slice(i);                   				// the elements from the a[i] to the last
    a.slice(i, n);                				// the n elements from the a[i]to a[i+n-1]
	/*
		Индексы и срезки можно использовать 
		как в левой части оператора присваивания, 
		так и в правой. 
		
		Они ссылаются на элементы объекта класса Мatrix, 
		не создавая их копии.
	*/
    a.slice(4, 4) 	= 	a.slice(0, 4);  		// assign first half of a to second half
    a.slice(4) 		= 	a.slice(0, 4);    		// assign first half of a to second half

    Matrix<int> 	a2 	= 	a;           		// copy initialization
    a 	= 	a2;                       			// copy assignment
    a 	*= 	7;                       			// scaling: a[i] *= 7 for each i (also +=, -=, /=, etc.)
    a 	= 	7;                        			// a[i] = 7 for each i

    a.apply(f_square);                   		// a[i] = f_square(a[i]) for each element a[i]
    a.apply(f_product, 7);                		// a[i] = f_product(a[i], 7) for each element a[i]

    Matrix<int> b = apply(abs, a); 				// make a new Matrix with b(i)==abs(a(i)) 

    b = a * 7;                     				// b[i] = a[i]*7 for each i
    a *= 7;                       				// a[i] = a[i]*7 for each i
	//	В результате мы получим а == b. 
	//	assert (a == b);	error: no match for 'operator==' (operand types are 'Numeric_lib::Matrix<int, 1>' 
	// 	and 'Numeric_lib::Matrix<int, 1>')
	
    Matrix<double> x(10);
    Matrix<double> y = apply(f_square, x);		// y[i] = f_square(x[i]) for each i
    x.apply(f_square);                   		// x[i] = f_square(x[i]) for each i
	//	assert (x == y);	error: no match for 'operator==' (operand types are 'Numeric_lib::Matrix<int, 1>' 
	// 	and 'Numeric_lib::Matrix<int, 1>')
   	/*
		В результате мы получим х == у. 
 
		В языке Fortran второй вариант функции apply() 
		называется 'функцией трансляции' (broadcast function). 
		
		В этом языке чаще пишут вызов f_square(x), 
		а не apply(f_square, х). 
		
		Для того чтобы эта возможность стала доступной для каждой функции f()
		(а не только для некоторых отдельных функций, как в языке Fortran), 
		мы должны присвоить операции трансляции конкретное имя. 
		
		Поэтому (повторно) использовали имя apply. 
		
		Кроме того, для того чтобы 
		обеспечить соответствие с вариантом функции-члена apply() 
		с двумя аргументами (а.apply (f, х)), 
		мы предоставили 
		b = apply (f, a, x); // b[i}=f (a [i } , x) для каждого i 
		------------------------------------------------------------------------------------------------
	*/
    b = apply(f_product, a, 7);            		// b[i] = f_product(a[i], x) for each i
	
	/*
		Обратите внимание на то, что "автономная" функция apply() 
		принимает в качестве аргумента функцию, возвращаюшую результат, 
		вычисляя его по переданным ей аргументам, 
		а затем использует этот результат 
		для инициализации результирующего объекта типа Мatrix. 
		
		Как правило, это не приводит к изменению матрицы, 
		к которой эта функция применяется. 
*/
    b = apply(scale, a, 7);         			// b[i] = a[i]*7 for each i
/*		
		Функция-член apply() отличается тем, 
		что принимает в качестве аргумента функцию, 
		модифицируюшую ее аргументы; 
		т.е. эта функция модифицирует элементы матрицы,
		к которым применяется. 
	*/
    x.apply(scale_in_place, 7);    				// a[i] *= 7 for each i

	
	//	В классе Мatrix предусмотрены также наиболее полезные функции 
	//	из традиционных математических библиотек: 
	
	// Слитное умножение и сложение 
    Matrix<int> a3  = scale_and_add(a, 8, a2); 	// fused multiply and add
	/*
		Операцию scale_and_add() часто называют 'слитным умножением и сложением' (fused multiply-add), 
		или просто fтa;
		ее определение выглядит так: 
		
		result(i) = arg1(i) * arg2 + arg3(i) 
		
		для каждого i в матрице. 
	*/
	
	// Скалярное произведение 
    int r = dot_product(a3, a);               	// dot product
	/*
		'Скалярное произведение', 
		известно также под именем inner_product; 
		его определение выглядит так: 
		
		result += arg1(i) * arg2(i) 
		
		для каждого i в матрице, 
		где изначальное значение result обычно равно нулю. 
	*/	
}
/*
	***********************************************************************************
	Одномерные массивы очень широко распространены; 
	их можно представить как в виде встроенного массива, 
	так и с помощью классов vector и Мatrix. 
	
	Класс Мatrix следует применять тогда, 
	когда необходимо выполнять матричные операции, 
	такие как *=, 
	или когда одномерная матрица должна взаимодействовать 
	с другими матрицами с более высокой размерностью. 
	
	Полезность этой библиотеки можно объяснить тем, 
	что она "лучше согласована с математическими операциями", 
	а также тем, что при ее использовании 
	для работы с каждым элементом матрицы не приходится писать циклы. 
	
	В любом случае в итоге мы получаем более короткий код 
	и меньше возможностей сделать ошибку. 
	
	Операции класса Мatrix, 
	такие как 
	-	копирование, 
	-	присваивание всем элементам 
	и 
	-	операции над всеми элементами, 
	позволяют не использовать циклы 
	(а значит, можно не беспокоиться о связанных с ними проблемах). 
*/
//------------------------------------------------------------------------------
