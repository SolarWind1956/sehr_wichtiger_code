/*
	С целью исследования некоторого объекта, или некоторой системы, проводятся опыты (experiment) - 
	осуществляемые при определенных условиях. 
	Опыты могут быть реальными или гипотетическими.
	Любое наблюдаемое изменение параметров объекта или системы, 
	вызванное взаимодействием с внешней средой или внутренними процессами,
	возникающее в процессе опыта,
	называется явлением (phenomenon).
	Если при при неоднократном воспроизведении одного и того жe опыта
	явление	протекает каждый раз несколько по-иному, 
	оно называется случайным явлением (random phenomenon).
	Совокупность наблюдаемых параметров системы, зафиксированная по окончании проведения опыта, 
	называется исходом (outcome).
	Все возможные варианты совокупностей наблюдаемых параметров объекта или системы,
	полученных в результате многократно проведенных опытов,
	образуют пространство исходов - множество всех возможных исходов.
	В зависимости от характера и цели исследования одного и того же объекта или системы,
	совокупности могут включать в себя большее или меньшее количество наблюдаемых параметров.
	Если в соответствии с особенностями исследуемого объекта или системы 
	дальнейшее уменьшение количества наблюдаемых параметров уже не имеет смысла,
	исходы называются элементарными.
	Множество всех возможных элементарных исходов 
	образует пространство элементарных событий  (sample space).
	Подмножества пространства элементарных событий представляет собой события (event). 
	
*/

/*
 ══════════════════════════════════════════════════════════════════════
 💡 СИНТЕЗ: Цепочка понятий (Ваш вариант + уточнения)
 ══════════════════════════════════════════════════════════════════════

 1. Опыт (Experiment): Процесс осуществления условий и действий, 
    при которых наблюдается случайное явление.
 
 2. Исход (Outcome): Конкретный результат одного опыта (значение параметров).
 
 3. Элементарный исход: Исход, который нельзя детализировать в рамках 
    данной модели (атом Ω).
 
 4. Пространство элементарных исходов (Sample Space, Ω): Множество всех 
    возможных элементарных исходов опыта.
 
 5. Событие (Event): Любое подмножество пространства Ω.
    - Элементарное событие: Событие, состоящее ровно из одного элементарного исхода.
    - Достоверное событие: Событие, совпадающее с самим Ω.
 
 💡 СИНТЕЗ: 
    События — это инструмент для группировки элементарных исходов. 
    Мы "склеиваем" элементарные исходы в подмножества, чтобы придать 
    им вероятностный смысл.
 ══════════════════════════════════════════════════════════════════════
*/

/*
 ══════════════════════════════════════════════════════════════════════
 ⚠️ КРИТИЧЕСКАЯ ТОЧКА: Терминологическая синонимия
 ══════════════════════════════════════════════════════════════════════
 Термины: [Элементарный исход] ≡ [Элементарное событие]
 
 Ситуация: В стандарте ISO 3534 и многих учебниках эти понятия 
            отождествляются при определении пространства Ω.
 
 Почему так: 
   В теории вероятностей элементарный исход ω (точка) и 
   одноэлементное событие {ω} (множество) настолько тесно связаны, 
   что авторы часто "схлопывают" их в один термин для краткости.
 
 💡 СИНТЕЗ (Рабочее правило):
   - Если видите "Пространство элементарных событий" — читайте как "Множество всех элементарных исходов".
   - Исход (Outcome) — это "физический результат" (точка).
   - Событие (Event) — это "логическое множество" (подмножество Ω).
 ══════════════════════════════════════════════════════════════════════
*/