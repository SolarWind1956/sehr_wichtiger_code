/*
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
	💡 СИНТЕЗ: Исходы и События
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
	[Термины] : Элементарный исход (outcome) ↔ Элементарное событие (elementary event)
	
	1. Исход (Outcome):
		- Это фундаментальный результат одного испытания. 
		- Например, при броске кости исходы - {1, 2, 3, 4, 5, 6}.
		- "Элементарный" означает, что его нельзя разбить на еще более мелкие 
		  результаты в рамках данного опыта.
	
	2. Событие (Event):
		- Это любое подмножество множества всех возможных исходов.
		- Например, "выпало четное число" - это событие {2, 4, 6}.
		- Оно состоит из трех `элементарных исходов`.
	
	💡 СИНТЕЗ (Инженерная логика):
		- Исход - это "точка" в пространстве элементарных исходов Ω.
		- Событие - это "область" в пространстве Ω.
		
		Когда мы говорим "произошло элементарное событие", мы математически 
		констатируем, что реализовался ровно один `исход` из множества `Ω`.
		
		Терминологическая путаница возникает потому, что в простом опыте 
		(как бросок монеты) "исход" и "элементарное событие" - это одно и то же.
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
*/
