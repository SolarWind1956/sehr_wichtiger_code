/*
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
	💡 СИНТЕЗ: Исходы и События
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
	[Термины] : Элементарный исход (outcome) ↔ Элементарное событие (elementary event)
	
	1. Исход (Outcome):
		- Это фундаментальный результат одного испытания. 
		- Например, при броске кости исходы - {1, 2, 3, 4, 5, 6}.
		- "Элементарный" означает, что его нельзя разбить на еще более мелкие 
		  результаты в рамках данного опыта.
	
	2. Событие (Event):
		- Это любое подмножество множества всех возможных исходов.
		- Например, "выпало четное число" - это событие {2, 4, 6}.
		- Оно состоит из трех `элементарных исходов`.
	
	💡 СИНТЕЗ (Инженерная логика):
		- Исход - это "точка" в пространстве элементарных исходов Ω.
		- Событие - это "область" в пространстве Ω.
		
		Когда мы говорим "произошло элементарное событие", мы математически 
		констатируем, что реализовался ровно один `исход` из множества `Ω`.
		
		Терминологическая путаница возникает потому, что в простом опыте 
		(как бросок монеты) "исход" и "элементарное событие" - это одно и то же.
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
*/
/*
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
	Понятие		: 	Событие (event)
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
		 
	[Вентцель] 	: 	Под `событием` понимается всякий факт, 
					который в результате `опыта` может произойти или не произойти.
	
	[Пугачев]  	: 	Результаты опыта (исходы) можно характеризовать `качественно` и `количественно`. 

					`Качественная характеристика` опыта состоит в регистрации какого-нибудь факта, 
					т.e. в определении того, обладают результаты опыта каким-либо свойством или нет. 
					
					Любой такой факт называется `событием`. 
					
					При этом говорят, что «событие появилось (произошло)» 
					или «событие не появилось (не произошло)» в результате опыта.
	
					`Количественная характеристика` `опыта` 
					состоит в определении значений некоторых величин, 
					полученных в результате опыта. 
					
					Такие величины, которые могут принимать в результате опыта различные значения, 
					причем до опыта невозможно предвидеть, какими именно они будут, 
					называются `случайными величинами`.
					
	[ISO 3534] 	: 	 Событие 	- 	Подмножество пространства элементарных событий - 
									множества всех возможных элементарных исходов
	
	[Gemini (AI)] 	:	`Событие` - это результат `опыта`.
	
	💡 СИНТЕЗ	: 	В.С. Пугачев вводит так же понятие "случайного события", 
					а Е.С. Вентцель и стандарт ISO 3534 полагают, что в контексте теории вероятностей
					событие уже предполагается `случайным` - оно может или не может произойти
	══════════════════════════════════════════════════════════════════════════════════════════════════════════
*/

