/*
	Что важно помнить?

	• 	Важен порядок аргументов: 
		
		В унарной форме (с одним контейнером) `сначала` передается `функция `редукции`, 
		а затем - `трансформации`.
	
	• 	Требования к операциям: 
	
		Операция `редукции` (например, сложение, умножение) 
		должна быть строго `ассоциативной` и `коммутативной`. 
		
		Если передать туда `операцию`, `зависящую от порядка` 
		(например, вычитание или конкатенацию несимметричных строк), 
		результат выполнения будет непредсказуемым.
	
	• 	Параллельное выполнение: 
		
		Чтобы задействовать всю мощь процессора на больших массивах, 
		передайте `первым` аргументом `политику выполнения` из <execution>:
*/
void third_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
	
		
	std::vector<int> vec1 = {1, 3, 5};
    std::vector<int> vec2 = {2, 4, 6};

    // 	`По умолчанию: 	std::plus для `редукции` 
	//	и 
	//`					std::multiplies для `трансформации`
    int dot_product 
			= std::transform_reduce	(	std::execution::par
									,	vec1.begin()
									, 	vec1.end()
									,   vec2.begin()
									, 	0
									,	std::plus<>()		// 	Бинарная операция (Редукция)
									,	std::multiplies<>()	// 	Унарная операция (Трансформация)
									);

    cout << dot_product << "\n"; 	// 	Выведет: 44 (1*2 + 3*4 + 5*6)
}

/*
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	Представим, что мы обрабатываем данные о заказах в интернет-магазине.
	
	У нас есть `список цен товаров` и `список примененных скидок` (в процентах). 
	
	Нам нужно посчитать `финальную выручку` с `учетом скидок`, 
	но `только для тех позиций`, 
	`итоговая стоимость` которых 
	`после скидки` 
	`превысила `определенный `порог` (например, 100 рублей) - 
	чтобы оценить оборот по «крупным» чекам.
*/
// 	Структуры для демонстрации разных типов
struct 	Price 		{ double value; };
struct 	Discount 	{ double percent; }; 	// 	Например, 0.10 означает 10%

void forth_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';

	// 	1. 	Исходные данные (два разных диапазона)
    std::vector<Price> 		prices 		= { {150.0}, {80.0}, {300.0}, {50.0} };
    std::vector<Discount> 	discounts 	= { {0.10}, {0.0}, {0.20}, {0.50} };

    // 	2.	 Опорный объект (init)
    double pivot_object = 0.0;

    // 	3. 	Функция ТРАНСФОРМАЦИИ (Бинарная)
    // 	Принимает элемент 1-го диапазона и элемент 2-го диапазона.
    // 	Возвращает итоговую стоимость товара.
    auto transform_function = [](const Price& price, const Discount& discount) -> double {
								return price.value * (1.0 - discount.percent);
							};

    // 	4. 	Функция РЕДУКЦИИ (Бинарная)
    // 	Собирает (аккумулирует) трансформированные значения.
    // 	Порог: учитываем в общей сумме только товары дороже 100.0
    auto reduce_function = 	[](double accumulated_sum, double transformed_price) -> double {
								if (transformed_price > 100.0) {
									return accumulated_sum + transformed_price;
								}
								return accumulated_sum;
							};

    // 	5. 	Вызов std::transform_reduce
    decltype(pivot_object)		total_major_revenue 	= 
						std::transform_reduce	(	std::execution::par	// 	Политика выполнения
											,	prices.begin()      	// 	Начало 1-го диапазона
											,	prices.end()			// 	Конец 1-го диапазона
											,	discounts.begin()    	// 	Начало 2-го диапазона
											,	pivot_object  		// 	Опорный объект (init)
											,	reduce_function		// 	Сначала РЕДУКЦИЯ
											,	transform_function  	// 	Затем ТРАНСФОРМАЦИЯ
											);

    // 	Математика внутри:
    
	// 	Пара 1: 	150 	* (1 - 0.10) 	= 135.0 	( > 100, берем)
    // 	Пара 2: 	80 	* (1 - 0.0)   	= 80.0  	( <= 100, игнорируем)
    // 	Пара 3: 	300 	* (1 - 0.20) 	= 240.0 	( > 100, берем)
    // 	Пара 4: 	50 	* (1 - 0.50)  	= 25.0  	( <= 100, игнорируем)
	
    // 	Результат: 135.0 + 240.0 = 375.0

    cout << "Выручка по крупным позициям: " << total_major_revenue << " руб.\n";
}
