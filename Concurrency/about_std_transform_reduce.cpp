auto count_visits_per_page(const std::vector<std::string>& 	log_lines) -> visit_map_type 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
	
	/*
		[ log_lines.begin(), log_lines.end() ) 
		std::vector<std::string>& 	log_lines
		
		Каждый элемент этого вектора - это строка, состоящая из двух подстрок, разделенных пробелом:
		первая подстрока  - это `URL`, например, 
		/home.html
		вторая подстрока  - это его `IP-адрес`, например, 
		192.168.1.1
		
		`Опорный элемент` `visit_map_type` - пустой ассоциированный массив, 
		`ключом` которого является `URL`
		из строк вектора `log_lines` а `значением` является количество таких `URL`,
		встретившихся при проходе по вектору функции трансформации.
		
		Функция трансформации 
		auto parse_log_line(const std::string& 	line) -> log_info 
		получает на вход очередной элемент контейнера `log_lines` - 
		строку, состоящую из двух подстрок.
		
		Она делает грамматический разбор этой очередной строки 
		и возвращает структуру `log_info`,
		содержащую первую подстроку элемента контейнера, 
		и признак валидности этой подстроки.
		
		Функция редукции (схлопывания или свертки) -
		функтор структуры `combine_visits` (их четыре перегрузки)
		с попадающими ей двух параметров - в данном случае:
		опорного элемента - ассоциативного массива и объекта структуры `log_info`,
		в котором первым элементом выступает `URL` из очередной строки вектора - 
		это `ключ` ассоциативного масссива, `значение` по ключу 
		будет устанавливать операцией инкремента
		эта самамая функция редукции. 
		
		Перегрузка будет выбрана из четырех возможных,
		в которой первым параметром является ассоциативный массив, 
		а вторым - структура `log_info`.
		
		Возвращаемым значение будет уже заполненный функцией редукции опорный элемент -
		первонацально пустой ассоциативный массив, ключи которого 
		будут содержать URL строк исходного контейнера-вектора, 
		а значениями будут количества строк с такими URL.
	*/
    try {
		cerr << "-------------- [DEBUG 2] " << '\n';
		visit_map_type	result = 
			std::transform_reduce(
					std::execution::par,      	// 	Параллельное выполнение
					log_lines.begin(),          	// 	Начало диапазона
					log_lines.end(),            	// 	Конец диапазона
					visit_map_type(),           	// 	Опорный объект (init) - пустая карта
					combine_visits(),           	// 	Шаг 1: Редукция (Схлопывание результатов)
					parse_log_line              	// 	Шаг 2: Трансформация (Парсинг строки)
				);
		cerr << "-------------- [DEBUG 3] " << '\n';
		return result;
    }
    catch (const std::exception& exc) {
        // 	Уильямс обращает внимание: если хотя бы один поток выбросит исключение,
        // 	std::transform_reduce немедленно прервет работу (сгенерирует std::terminate 
        // 	или пробросит исключение наружу в вызывающий поток).
        cerr << "[Error in parallel reduction]: " << exc.what() << "\n";
        
        // 	Возвращаем пустую карту или пробрасываем дальше в зависимости от архитектуры
        throw; 
    }
}

