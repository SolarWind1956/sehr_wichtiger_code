// 	Определяем типы по Уильямсу
using 	visit_map_type 	= 	std::unordered_map<std::string, unsigned long long>;

// 	Простая структура, возвращаемая шагом трансформации
struct 	log_info {
    std::string 	page_url;
	
    bool 		is_valid 	= 	false;
};

// 	1. 	Функция ТРАНСФОРМАЦИИ (Парсер строки лога)
auto parse_log_line(const std::string& 	line) -> log_info 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
    if (line.empty()) {
        return {.page_url = "", .is_valid = false};
    }
     
    // 	Пример бизнес-логики: если строка содержит "CRITICAL_ERROR", 
    // 	бросаем исключение, чтобы проверить обработку ошибок в параллельном коде.
    if 	(line.contains("CRITICAL_ERROR")) {
        throw std::runtime_error("Log file is corrupted (Critical error entry found)!");
    }

    // 	Для примера просто ищем URL (первое слово)
    std::size_t 	space_pos = line.find(' ');
	
    if (space_pos != std::string::npos) {
        return { .page_url = line.substr(0, space_pos), .is_valid = true };
    }
                     
    return { .page_url = line, .is_valid = true };
} 

// 	2. 	Функция РЕДУКЦИИ (Объединение результатов)
struct combine_visits 
{
    // 	Сценарий А: Слияние двух карт (основной рабочий сценарий для reduce)
    auto operator()(visit_map_type lhs, visit_map_type rhs) const -> visit_map_type 
	{
		cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
        if (lhs.size() < rhs.size()) {
            std::swap(lhs, rhs);
        }
        
        // 	В C++17/C++20 можно использовать lhs.merge(rhs), 
        // 	но классический вариант Уильямса через итераторы выглядит так:
        for (const auto& [page, count] : rhs) {
            lhs[page] += count;
        }
		
        return lhs;
    }

    // 	Сценарий Б: 	Карта + сырой объект (нужен для промежуточных фаз алгоритма)
    auto operator()(visit_map_type lhs, const log_info& rhs) const -> visit_map_type 
	{
		cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
        if (rhs.is_valid) {
            lhs[rhs.page_url]++;
        }
		cerr << "-------------- [DEBUG 1] " << '\n';
        return lhs;
    }
    auto operator()(const log_info& lhs, visit_map_type rhs) const -> visit_map_type  
	{
		cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
        if (lhs.is_valid) {
            rhs[lhs.page_url]++;
        }
		
        return rhs;
    }

    // 	Сценарий В: 	Два сырых объекта (если поток взял ровно две строки лога)
    auto operator()(const log_info& lhs, const log_info& rhs) const -> visit_map_type 
	{
		cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
        visit_map_type 	map;
		
        if (lhs.is_valid) { map[lhs.page_url]++; }
        if (rhs.is_valid) { map[rhs.page_url]++; }
		
        return map;
    }
};

