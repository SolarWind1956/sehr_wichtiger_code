/*
	*****************************************************************************************************
	*
	*	std::reduce, std::transform and std::transform_reduce
	*
	*****************************************************************************************************
	std::reduce 			- 	это функция стандартной библиотеки C++, 
							добавленная в C++17 (заголовочный файл <numeric>), 
							предназначенная для `свёртки` (`редукции`) диапазона элементов 
							в одно значение. 
							
							`По умолчанию` она вычисляет `сумму` всех элементов.
							
	Главная особенность std::reduce 
	по сравнению с классической std::accumulate 
	заключается в том, 
	что она `не гарантирует` 
	`последовательный `порядок `обработки элементов`. 
	
	Это позволяет эффективно распараллеливать вычисления.
	
	----------------------------------------------------------------------------------------------------------------------------------------------------------
	std::transform 		-	это стандартный алгоритм C++, 
							определенный в заголовочном файле <algorithm>, 
							который применяет заданную функцию 
							к элементам одного или двух диапазонов 
							и записывает результат в целевой диапазон.
							
	В отличие от std::for_each, 
	который предназначен в основном для поочередного перебора (вызова side-effects) 
	и гарантирует строгий порядок следования, 
	std::transform не гарантирует выполнение строго по порядку 
	и используется именно для трансформации данных («отображения» / map).
	
	----------------------------------------------------------------------------------------------------------------------------------------------------------
	std::transform_reduce 	- 	это эффективный алгоритм стандартной библиотеки C++ 
							(начиная с C++17), 
							определенный в заголовочном файле <numeric>. 
							
	Он совмещает в себе `две операции`: 
	
	-	сначала преобразует элементы диапазона (как std::transform), 
	а затем 
	-	складывает/агрегирует полученные результаты (как std::reduce).
*/	
/*
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	Главное отличие std::transform_reduce от связки std::transform + std::accumulate 
	это возможность параллельного выполнения 
	и отсутствие промежуточного выделения памяти 
	под преобразованный массив.
	
	Какую проблему он решает?

	Для параллельного вычисления (например, через std::execution::par) 
	операция редукции обязана быть `ассоциативной` и `коммутативной` 
	(изменение порядка действий не должно менять результат).
	
	Если бы мы сначала делали std::transform, 
	нам пришлось бы создавать `временный вектор`. 
	
	А если использовать std::accumulate / std::reduce со сложной лямбдой, 
	то при параллельном расчете 
	нарушается математическая логика 
	(поскольку трансформация привязана к шагу аккумуляции, 
	которая в std::reduce происходит не по порядку). 
	
	std::transform_reduce разделяет 
	фазу трансформации каждого отдельного элемента 
	и 
	фазу их слияния.
	
	---------------------------------------------------------------------------------------------------------------------------------------------------------
	Два основных варианта использования

	1. 	Унарная форма (Один диапазон)

	Применяет функцию трансформации к каждому элементу одного контейнера, 
	а затем собирает их вместе.
	
	Пример: 	Подсчет суммы квадратов элементов
*/
void first_example() 
{
	cerr << "-------------- I'm " <<  __PRETTY_FUNCTION__ << '\n';
	
	std::vector<int> vect = {1, 2, 3, 4};

    int sum_of_squares = 
				std::transform_reduce	(	vect.begin()
									, 	vect.end()
									,	0				// 	Начальное значение (init)
									,	std::plus<>()	// 	Бинарная операция (Редукция)
									,	[](int x_par) -> auto { return x_par * x_par; }       
														// 	Унарная операция 
														//	(Трансформация)
									);
									
    cout << sum_of_squares << "\n"; 	// 	Выведет: 	30 == (1 + 4 + 9 + 16)
}
