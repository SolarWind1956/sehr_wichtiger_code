/*
	Конечно, если у вас есть способ узнать, 
	что данный фьючерс не удовлетворяет условиям, приводящим к специальному поведению деструктора 
	(например, в силу логики программы), 
	вы можете быть уверены, что этот фьючерс не приведет к блокировке деструктора. 
	
	Например, претендовать на особое поведение могут только общие состояния, 
	получающиеся в результате вызовов std::async(), 
	но есть и иные способы создания этих общих состояний. 
	
	Один из них - использование std::packaged_task. 
	
	Объект std::packaged_task подготавливает функцию (или иной вызываемый объект) 
	к асинхронному выполнению, "заворачивая" ее таким образом, 
	что ее результат помещается в общее состояние. 
	
	Фьючерс, ссылающийся на это общее состояние, 
	может быть получен с помощью функции get_future() объекта std::packaged_task.
*/
int doAsyncWork_74()
{
	for (auto i{0}; i < 3; i++)
	{
		cout << "I'm int doAsyncWork() - thread_id is: " << std::this_thread::get_id() << endl;
		std::this_thread::sleep_for(1s);
	}
	return 74;
};

void packaged_task_step_1()
{
	cout << "\nI'm void packaged_task_step_1() - thread_id is: " << std::this_thread::get_id() << endl;

	{
		// Заворачивание в объект класса std::packaged_task функцию doAsyncWork_74() для асинхронного выполнения 
		std::packaged_task<int()> pckg_tsk(doAsyncWork_74);		// int() - сигнатура вызываемой функции
		cout << "Type of the pckg_tsk:  " << type_name_as_str<decltype(pckg_tsk)>() << endl;
		// class std::packaged_task<int __cdecl(void)>
		
		// Получение фьючерса для pckg_tsk
		auto futur_pckg_tsk		= pckg_tsk.get_future();
		cout << "Type of the futur_pckg_tsk:  " << type_name_as_str<decltype(futur_pckg_tsk)>() << endl;
		//  class std::future<int>
		/*
			В этой точке мы знаем, что фьючерс futur_pckg_tsk не ссылается на общее состояние, 
			созданное вызовом std::async, так что его деструктор будет вести себя нормально. 

			Будучи созданным, объект pckg_tsk типа std::packaged_task может быть запущен в потоке. 
			(Он может быть запущен и с помощью вызова std::async, 
			но если вы хотите выполнить задачу с использованием std::async, 
			то нет смысла создавать std::packaged_task, 
			поскольку std::async делает все, что делает std::packaged_task до того, 
			как планировщик начинает выполнение задачи.) 
		
			Объекты std::packaged_task не копируются, так что, когда pckg_tsk передается в конструктор std::thread, 
			он должен быть приведен к rvalue (с помощью std::move; ).
		
			Этот пример дает некоторое представление о нормальном поведении деструкторов
			фьючерсов, но его легче увидеть, если собрать весь код вместе в одном блоке:
		*/
		std::thread		thrd_futur_pckg_tsk(std::move(pckg_tsk));
		cout << "Type of the thrd_futur_pckg_tsk:  " << type_name_as_str<decltype(thrd_futur_pckg_tsk)>() << endl;
		// class std::thread
		thrd_futur_pckg_tsk.join();
		
		// Вот только теперь работает :)
		cout << "packaged_task_step_1() - pckg_tsk.get_future().get();  = " << futur_pckg_tsk.get() << endl;

		cout << " А можно и так :" << endl;

		std::packaged_task<int()>	task(doAsyncWork_74);
		std::future<int>			futr = task.get_future();
		task();													// Запуск задачи в этом же потоке
		int							result = futr.get();
		cout << "packaged_task_step_1() - result = futr.get();  = " << result << endl;
	}
};
/*
	Наиболее интересный код скрывается за троеточием " ... ", 
	следующим за созданием объекта thrd типа std::thread и предшествующим концу блока. 
	
	Имеются три основные возможности. 
	
	•	С thrd ничего не происходит.	В этом случае thrd в конце области видимости будет неподключаемым. 
										Это приведет к завершению программы. 

	•	Для thrd вызывается функция-член join().	В этом случае фьючерсу futr не требуется блокировать деструктор, 
													так как вызов join() уже имеется в вызывающем коде. 

	•	Для thrd вызывается функция-член detach().	В этом случае фьючерсу futr не требуется 
													вызывать detach() в деструкторе, 
													поскольку вызывающий код уже сделал это. 

	Другими словами, когда у вас есть фьючерс, соответствующий общему состоянию, 
	получившемуся из-за применения std::packaged_task, 
	обычно не требуется принимать специальную стратегию деструкции, 
	так как решение о прекращении выполнения программы, 
	подключении или отключении потока принимается в коде, 
	работающем с потоком std::thread, в котором выполняется std::packaged_task.
*/
