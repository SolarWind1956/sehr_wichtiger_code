void third_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';

	// 	1. 	Оборачиваем функцию в `packaged_task`. 	Указываем сигнатуру double(double)
    std::packaged_task<double(double)> 	task(super_heavy_work);

    // 	2. 	Забираем фьючерс ДО запуска потока
    std::future<double> 				future_result 	= 	task.get_future();

    // 	3. 	Запустим функцию в этом же потоке
    task(2.0);

    cout << "[Главный поток] Поток запущен, начинаю ждать...\n";

    try {
        // 	4. 	Блокируем главный поток, пока `super_heavy_work` не выполнится
        auto result	=	future_result.get(); 
        
		cout << "[Главный поток] Сигнал от get() получен! Выводим результат. " << result << '\n';
    } catch (const std::exception& excptn) {
        cout << "[Главный поток] Перехвачено исключение из потока: " << excptn.what() << "\n";
    }
}
/*
	===================================================================
	На первый взгляд это кажется бессмысленным: 
	зачем оборачивать функцию в std::packaged_task и std::future, 
	если мы всё равно выполняем её здесь же? 
	
	Однако этот паттерн критически важен в реальном проектировании.
	
	Вот основные сценарии, когда и зачем это нужно:

	1. Собственные пулы потоков (Thread Pools) и планировщики (Schedulers)

	Это самый частый сценарий. 
	
	Представьте, что у вас есть очередь задач (например, std::queue), 
	которую обрабатывают фоновые потоки.
	
	• 	Вы не хотите создавать std::thread на каждую чих, 
		вы хотите упаковать вызов функции с её аргументами в один объект 
		и положить в очередь.
		
	• 	Фоновый поток достает этот объект из очереди 
		и просто вызывает его как функцию: task().
	
	• 	Для фонового потока это выглядит точно так же, как в примере: 
		он просто запускает задачу в своем потоке. 
		
		Но профит в том, что std::future остался у того, 
		кто эту задачу в очередь положил - 
		и он сможет забрать результат из совсем другого места программы.

	2. 	Динамический выбор: 	
		
		выполнять асинхронно или прямо сейчас?

		Иногда во время выполнения программы нужно решить: 
		стоит ли отправлять задачу в другой поток 
		или безопаснее/быстрее сделать её прямо здесь?
		
	• 	Пример: 
	
		Если фоновый пул потоков перегружен, 
		или если у системы осталось мало свободных ядер, 
		или если задача слишком маленькая 
		(накладные расходы на переключение контекста потоков будут выше, чем само вычисление).
		
	• 	Вы можете написать универсальный код, который принимает std::packaged_task. 
	
		В зависимости от условий, вы либо отдадите её в std::thread, 
		либо вызовете прямо на месте: 
		
		task(2.0). 
		
		Вся остальная логика получения результата через .get() останется неизменной.

	3. 	Гарантированный перехват исключений и унификация интерфейса

		std::packaged_task - это потрясающий инструмент для «сглаживания» интерфейсов. 
		
		Допустим, у вас есть библиотека, которая строго требует, 
		чтобы все результаты (и ошибки) возвращались через std::future.
		
	• 	Если функция выполняется прямо здесь, 
		но внутри неё происходит 
		
		throw std::runtime_error, 
		
		этот вызов не обрушит программу сразу.
		
	• 	std::packaged_task поймает это исключение и бережно сохранит его внутри std::future. 
	
		Вы сможете обработать его позже, в привычном блоке try-catch вокруг future.get(), 
		сохраняя единообразие кода.

	4. 	Отложенное выполнение (Lazy Evaluation) в одном потоке

		Вы можете создать задачу, 
		передать её в другую часть программы, 
		и она будет лежать там невызванной. 
		
		Тот код, который её получил, сам решит, 
		в какой именно момент её запустить (вызовом task()), 
		но результат вернется автору задачи через сохраненный `future`.

	💡 	Простая аналогия для понимания

		Представьте, что std::packaged_task - это письмо в конверте с обратным адресом.
		
	• 	Когда вы отдаете его в std::thread, 
		вы нанимаете курьера, 
		который 
		-	берет конверт, 
		-	уносит его в другой офис, 
		-	там вскрывает, 
		-	выполняет поручение 
		и 
		-	отправляет вам ответ.
		
	• 	В вашем third_example() вы не стали нанимать курьера. 
		
		Вы просто 
		-	сели за свой же стол, 
		-	вскрыли этот конверт 	
		и 
		-	выполнили поручение сами. 
		
		Но ответ вы всё равно положили в ячейку «для ответов» (std::future), 
		откуда потом его и забрали.
*/
