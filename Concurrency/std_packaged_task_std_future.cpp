// Функция, которая ничего не возвращает (void)
void heavy_work() {
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		
    std::this_thread::sleep_for(std::chrono::seconds(2));
    
	cout << "[Фоновый поток] Работа завершена!\n";
    // 	Исключение для проверки (раскомментируйте, чтобы проверить проброс)
    throw std::runtime_error("Что-то пошло не так!");
}
void first_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
	// 	1. 	Оборачиваем функцию в `packaged_task`. 	Указываем сигнатуру void()
    std::packaged_task<void()> 	task(heavy_work);

    // 	2. 	Забираем фьючерс ДО запуска потока
    std::future<void> 			future_result 	= 	task.get_future();

    // 	3. 	Создаем поток. 	Передаем `task` по rvalue-ссылке (std::move), так как он non-copyable
    std::thread worker(std::move(task));

    cout << "[Главный поток] Поток запущен, начинаю ждать...\n";

    try {
        // 4. Блокируем главный поток, пока heavy_work не выполнится
        future_result.get(); 
        cout << "[Главный поток] Сигнал от get() получен! Идем дальше.\n";
    } catch (const std::exception& excptn) {
        cout << "[Главный поток] Перехвачено исключение из потока: " << excptn.what() << "\n";
    }

    // 	5. 	Обязательный join() для самого потока, чтобы избежать std::terminate
    if (worker.joinable()) {
        worker.join();
    }
}
/*
	
	🔍 	В чем разница между get() и .join() в данном контексте?

-----------------------------------------------------------------------------------------------------------------------------------------------------------------
Критерий				std::future::get()						std::thread::join()
-----------------------------------------------------------------------------------------------------------------------------------------------------------------
Объект ожидания			Ожидает готовности результата 		Ожидает полного завершения 
						(сигнала от shared state задачи).		операционной системой 
															физического потока.
															
Исключения				Перехватывает исключение .			Если поток упал с исключением, 
						из фоновой функции 					программа просто 
						и возвращает его в try-catch			аварийно завершится (std::terminate).
						
Гибкость					Позволяет не блокировать 			Блокирует поток строго 
						поток намертво 						до победного конца.
						(можно использовать 
						wait_for или wait_until).
-----------------------------------------------------------------------------------------------------------------------------------------------------------------

	Резюме: 		Для void-функций std::future::get() служит своеобразным «чекпоинтом». 
				Результата (данных) нет, но сам вызов гарантирует: 
				«На этом этапе фоновая задача точно успешно выполнилась (или упала с ошибкой), 
				и мы можем безопасно использовать её сайд-эффекты».
	----------------------------------------------------------------------------------------------------------------------------------------------------------
*/
auto super_heavy_work(double param) -> double {
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		
    std::this_thread::sleep_for(std::chrono::seconds(2));
    
	double	result 	= 	std::numbers::pi * param;
	
	cout << "[Фоновый поток] Работа завершена!\n";
    // 	Исключение для проверки (раскомментируйте, чтобы проверить проброс)
	if (param > std::numeric_limits<double>::max())	{
		throw std::runtime_error("Что-то пошло не так!");
	} else	// NOLINT(readability-else-after-return)
	{
		return	result;
	}	
}

void second_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		
	// 	1. 	Оборачиваем функцию в `packaged_task`. 	Указываем сигнатуру double(double)
    std::packaged_task<double(double)> 	task(super_heavy_work);

    // 	2. 	Забираем фьючерс ДО запуска потока
    std::future<double> 				future_result 	= 	task.get_future();

    // 	3. 	Создаем поток. 	Передаем `task` по rvalue-ссылке (std::move), так как он non-copyable
    std::thread 						worker(std::move(task), 2.0);

    cout << "[Главный поток] Поток запущен, начинаю ждать...\n";

    try {
		future_result.wait();				// Так можно делать, можно не делать
		/*
			Вызов get() внутри себя автоматически делает то же самое ожидание (wait), 
			что и метод wait(). 
			
			Единственное отличие - wait() просто ждет завершения 
			(не возвращая данные и не выбрасывая исключения), 
			а get() 
			-	и ждет, 
			-	и возвращает результат, 
			-	и пробрасывает ошибки.
		*/	
        // 4. Блокируем главный поток, пока `super_heavy_work` не выполнится
        auto result	=	future_result.get(); 
        
		cout << "[Главный поток] Сигнал от get() получен! Выводим результат. " << result << '\n';
    } catch (const std::exception& excptn) {
        cout << "[Главный поток] Перехвачено исключение из потока: " << excptn.what() << "\n";
    }

    // 	5. 	Обязательный join() для самого потока, чтобы избежать std::terminate
    if (worker.joinable()) {
        worker.join();
    }
}
