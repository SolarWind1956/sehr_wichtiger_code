		string			filename = 	"data/filename.in";
		ifstream 		file_content(filename);
		
		// Создадим строку, посимвольно переписывая в нее содержимое всего файла, 
		// включая символы "возврата каретки" и "перевода строки" разделяющие строки в файле
		string 			strs_of_file(istreambuf_iterator<char>(file_content), (istreambuf_iterator<char>()));
		// cout << strs_of_file << endl;
		// Удалим символы "возврата каретки" и "перевода строки" разделяющие строки в файле
		std::replace(strs_of_file.begin(), strs_of_file.end(), '\r', ' ');
		std::replace(strs_of_file.begin(), strs_of_file.end(), '\n', ' ');
		cout << strs_of_file << endl;
		
		// Цикл	будет последовательно вызывать regex_search() для поиска всех соответствий в файле
		// Когда итератор sregex_iterator связывается со строкой и объектом класса regex, 
		// итератор автоматически позиционируется на первое соответствие в заданной строке. 
		sregex_iterator 	it(strs_of_file.begin(), strs_of_file.end(), rgx_expr);
