#include <regex>
#include <iostream>
#include <stdexcept>
#include <exception>
#include <string>
#include <fstream>
#include <cassert>
using namespace std;
#include "std_lib_facilities.h"

//------------------------------------------------------------------------------
/*
	23. 9. Сопоставление регулярных выражений 

	Регулярные выражения в основном используются в двух ситуациях. 

	• 	Поиск строки, соответствующей регулярному выражению в (произвольно длинном) потоке данных, - 
		функция regex_search() 
		ищет этот шаблон как подстроку в потоке. 
		
	• 	Сопоставление регулярного выражения строке (известного размера) - 
		функция regex_match() 
		ищет полное соответствие шаблона и строки.

KLASSE 		Класс
ANTAL 		Количество
DRENGE 		Мальчики
PIGER 		Девочки
ELEVER 		Студенты
IALT		Всего

*/
int main()
try
{
	cout << "-------------- I'm int " <<  __func__  << "()" << endl;
    ifstream 	in("table.txt");    				// input file
    if (!in) 
		error("no input file\n");

    string line;    // input buffer
    int lineno = 0;
	/*
		Для того чтобы проанализировать эту таблицу, 
		нам нужны два шаблона: 
		
		один - для заголовка и второй -для остальных строк. 
		------------------------------------------------------------------------------------------
	*/
    regex 	header	("^[\\w ]+(	[\\w ]+)*$"); 					// header line
	//					  \s  \t   \s
	
	//	+	'один или больше'
	//	*	'ноль или больше'
	//	^	'начало строки'
	//	$	'конец строки'
	
	/*
		Строка ЗАГОЛОВКА в таблице 
		содержит четыре словарных поля 
		(буквенно-цифровых поля, разделенных знаками табуляции). 

		KLASSE  	ANTAL DRENGE  	ANTAL PIGER  	ELEVER IALT
                \t				 \t				 \t
		Эти поля могут содержать пробелы, 
		поэтому мы не можем просто использовать управляющий символ \w, 
		чтобы задать эти символы. 
		
		Вместо этого мы используем выражение [\w ], 
		т.е. словообразующий символ (букву, цифру или знак подчеркивания) или пробел. 
		
		"Один (или более)" такой символ задается выражением [\w ]+. 
		
		Мы хотим найти тот из них, который стоит в 'начале строки', 
		поэтому пишем выражение ^[ \w ]+. 
		
		"Шапочка" (^) означает "начало строки". 
		
		Каждое из оставшихся полей можно выразить как 'знак табуляции', 
		за которым следуют некие слова: ( [\w ]+). 
		
		До конца строки их может быть сколько угодно: ( [\w ]+)*$. 
		
		Знак доллара ($) означает "конец строки". 
		
		Мы не можем увидеть, 
		что 'знак табуляции' действительно является таковым, 
		но в данном случае он раскрывается в ходе набора текста 
		и распознается сам.
		---------------------------------------------------------------------------------
	*/
    regex 	row		("^[\\w ]+(	\\d+)(	\\d+)(	\\d+)$"); 		// data line
	//						   \t     \t      \t
	//	+	'один или больше'
	/*
		После вставки в необработанный строковый литерал он превращается в 
		
		R"(^[\w ]+( \d+) ( \d+) ( \d+) $)" 
	*/
	regex 	row_regex	(R"(^[\w ]+(	\d+)(	\d+)(	\d+)$)"); 		
	//						   		  \t      \t      \t
	
	//	assert(row_regex == row && "Шаблоны должны были получиться одинаковыми");
	//	НЕ КАТИТ для типа std::regex 
	
	/*
		Шаблон для строк, из которых мы хотим извлекать числовые данные. 
		
		Первое поле вновь имеет такой же шаблон, как и в предыдущем случае: 
		"^[\w ]+. 
		
		За ним следуют 'ровно три числовых поля', 
		перед каждым из которых стоит 'знак табуляции': ( \d+).
		-------------------------------------------------------------------------------------
	*/
	//	Проверяем строку заголовка
    if (getline(in, line)) {       // check header line
        std::smatch 	matches;
        // if (!regex_search(line, matches, header))
		if (!regex_match(line, matches, header))	
            error("no header");
		else 
			cout << "Формат заголовка проверен" << endl;
	}	
	//	Проверяем строки данных таблицы
    while (getline(in, line)) {    // check data line
        ++lineno;
        std::smatch 	matches;
        // if (!regex_search(line, matches, row_regex)) 
		if (!regex_match(line, matches, row_regex)) 	
            error("bad line", lineno);
		else {
			cout << "Формат очередной строки проверен" << endl;
		}
    }
	/*
		Мы проверяем все символы в каждой строке, 
		поэтому вызываем функцию 
		regex_match(), 
		а не 
		regex_search(). 
		
		Разница между ними заключается только в том, 
		что функция regex_match() 
		должна сопоставлять с шаблоном 'каждый символ' (character) из 'потока ввода', 
		а функция regex_search() проверяет 'поток ввода', 
		пытаясь найти соответствующую подстроку. 
		
		Ошибочное использование функции regex_match(), 
		когда подразумевалось использование функции regex_search() (и наоборот), 
		может оказаться самой трудно обнаруживаемой ошибкой. 
		
		Однако обе эти функции используют свои аргументы совершенно одинаково.
	*/
}
catch (std::exception& e) {
    cerr << "error: " << e.what() << '\n'; 
    return 1;
}
catch (...) {
    cerr << "Oops: unknown exception!\n"; 
    return 2;
}

