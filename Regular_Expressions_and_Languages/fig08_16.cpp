// fig08_16.cpp
// Matching entire strings to regular expressions.
#include <format>
using std::format;
#include <iostream>
using std::cout; using std::endl; using std::boolalpha; using std::cin; using std::cerr;
#include <regex>

int main() 
{
	// fully match a pattern of literal characters
	std::regex 	r1{"02215"};
	/*
		Функция regex_match() из заголовка <regex> возвращает true, 
		если 
		вся строка в первом аргументе 
		совпадает 
		с шаблоном во втором аргументе. 
		
		По умолчанию сравнение с шаблоном чувствительно к регистру; 
		далее мы покажем, как выполнять аналогичные операции без учета регистра. 
		
		Давайте для начала сравним между собой короткие последовательности символов. 
		
		Мы создали объект std::regex с именем r1, 
		содержащий простой шаблон "02215" из пяти цифровых литералов. 
		
		При сравнении этого шаблона с другой строкой 
		совпадение будет найдено только в том случае, 
		если сравниваемая строка ничем не отличается от шаблона, 
		то есть состоит из этих же пяти литералов в этой же последовательности. 
		
		Мы сравниваем шаблон со строками "02215" и "51220",
		дважды вызывая функцию regex_match(). 

		Обе сравниваемые строки составлены из одних и тех же цифровых литералов, 
		но только в строке "02215" последовательность цифр такая же, как в шаблоне. 
	*/
	cout 	<< "Matching against: 02215\n"
			<< format	("02215: {}; 51220: {}\n\n",
								 std::regex_match("02215", r1), 
										   std::regex_match("51220", r1)
						);

	/*
		'Метасимвоnы' и 'символьные классы' 

		Как правило, реrулярные выражения содержат специальные символы, 
		называемые 'метасимволами' ( metacharacters ): 
		
		[ ] { } ( ) \ * + ^ $ ? . |
		
		С метасимвола 'обратного слэша' '\' (slash - с англ. — «разрез, порез», «резкий удар», «косая черта») 
		начинаются все 'символьные классы' (character classes). 
		
		В таблице перечислены важнейшие символьные классы и указано, 
		каким символам они соответствуют. 
		-------------------------------------------------------------------------------------------------
		Символьный класс 			Соответствие 
		-------------------------------------------------------------------------------------------------
		\d 							Любая цифра (0-9) 
		\D 							Любой символ, кроме цифры 
		
		\s 							Любой 'символ пропуска' (пробел, табуляция, перевод строf(и и др.) 
		\S 							Любой символ, кроме 'символа пропуска' 

		\w 							Любой 'словообразующий символ' (word character), которым 
									может быть любая заrлавная или строчная буква анrлийскоrо алфавита, 
									любая цифра или символ подчеркивания 
									
		\W 							Любой символ, кроме 'словообразующего символа' 
		-------------------------------------------------------------------------------------------------
	
		Чтобы включить в шаблон любой 'метасимвол' в виде 'обычного литерала', 
		добавьте перед ним обратный слеш. 
		
		Например, шаблон \$ соответствует символу доллара ($), 
		а шаблон \\ соответствует обратному слешу (\).
		
		Без предваряющего обратного слэша метасимвол в шаблоне носит управляющие функции.
	*/
	// fully match five digits	-	в строке должно быть пять любых цифр
	std::regex 	r2{R"(\d{5})"};			//	Необработанный строковый литерал
	/*
		Символьный класс -	это еsсаре-последовательность, соответствующая какому-либо одному символу. 
		
		Чтобы найти пять любых цифр подряд, мы добавили 'квантификатор' (quantifier) {5}, 
		который повторяет \d пять раз, что аналогично шаблону \d\d\d\d\d.
		
		Квантификатор 	— 	это специальный ограничитель, 
							который указывает количество возможных повторений символа, 
							группы символов или класса символов, 
							находящихся в регулярном выражении перед ним.
	*/
	cout 	<< R"(Matching against: \d{5})" << "\n"
			<< format("02215: {}; 9876: {}\n\n",
							  std::regex_match("02215", r2),
									   std::regex_match("9876", r2));
	/*
		Пользовательские символьные классы 
		
		Символами в квадратных скобках [] 
		определяется 'пользовательский символьный класс' (custom character class), 
		который тоже соответствует какому-то одному символу. 
		
		Например, 
		[A-Z] 			- 	любая заглавная буква от А до Z; 
		[a-z] 			- 	любая строчная буква от а до z; 
		[a-zA-Z] 		- 	любая буква английского алфавита 
		[A-Z][a-z]*		- 	пользовательский символьный класс 
							для проверки имени пользователя, 
							которое не должно содержать пробелы и знаки препинания. 
	*/
	// 	match a word that starts with a capital letter - 
	// Шаблон: любое слово, которое начинается с заглавной буквы A-Z 
	std::regex 	r3{"[A-Z][a-z]*"};
	cout 	<< "Matching against: [A-Z][a-z]*\n"
			<< format("Wally: {}; eva: {}\n\n",
							  std::regex_match("Wally", r3), 
									  std::regex_match("eva", r3));
	/*
		Квантификатор '*' после какого-либо элемента регулярного выражения обозначает, 
		что этот элемент (в данном случае класс [a-z], то есть любая буква от а до z) 
		повторяется "ноль или более раз подряд".
	*/
	// match any character that's not a lowercase letter
	std::regex 	r4{"[^a-z]"};
	cout 	<< "Matching against: [^a-z]\n"
			<< format("A: {}; a: {}\n\n",
						  std::regex_match("A", r4), 
								 std::regex_match("a", r4));
	/*
		Пользовательский символьный класс, который начинается с 'метасимвола' '^', 
		соответствует любому символу, кроме указанных после '^'.
	*/
	// match metacharacters as literals in a custom character class
	std::regex 	r5{"[*+$]"};
	cout 	<< "Matching against: [*+$]\n"
			<< format("*: {}; !: {}\n\n",
						  std::regex_match("*", r5), 
								 std::regex_match("!", r5));
	/*
		Метасимволы в пользовательском классе обрабатываются как литералы, то есть как обычные символы. 
		
		Например, шаблон [*+$] соответствует любому из трех символов: *, + или $. 
	*/
	// matching a capital letter followed by at least one lowercase letter 
	std::regex 	r6{"[A-Z][a-z]+"};
	cout 	<< "Matching against: [A-Z][a-z]+\n"
			<< format("Wally: {}; E: {}\n\n",
							  std::regex_match("Wally", r6), 
									std::regex_match("E", r6));
	/*
		Сравнение квантификаторов + и * 
	
		Если в имени пользователя должна быть хотя бы одна строчная буква, 
		замените квантификатор * на +. 
		
		Квантификатор '+' после какого-либо элемента регулярного выражения обозначает, 
		что этот элемент повторяется 'один или более раз подряд'.
		
		Квантификаторы * и + являются жадными (greedy). 
		
		Жадным называется квантификатор, 
		обозначающий наибольшее возможное количество последовательных символов. 
		
		Например, регулярное выражение [A-Z][a-z]+ 
		соответствует словам "Al", "Eva", "Samantha", "Benjamin" и любым другим словам, 
		начинающимся с заглавной буквы, за которой следует хотя бы одна строчная буква. 
		
		Вы можете добавить символ '?' после квантификатора * и +, 
		чтобы сделать его ленивым (lazy): 
		
		*? или +?. 
		
		Ленивым называется квантификатор, 
		обозначающий 'наименьшее возможное количество последовательных символов'. 
	*/
	// matching zero or one occurrences of a subexpression
	std::regex 	r7{"labell?ed"};
	cout 	<< "Matching against: labell?ed\n"
			<< format("labelled: {}; labeled: {}; labellled: {}\n\n",
								 std::regex_match("labelled", r7),
											 std::regex_match("labeled", r7),
															std::regex_match("labellled", r7));
	/*
		Другие квантификаторы 
		
		Квантификатор '?' сам по себе обозначает, 
		что элемент слева от него повторяется 
		ноль или один раз. 
		
		Вы можете использовать квантификатор {п, }, 
		чтобы обозначить 'п' или более последовательных повторений элемента слева от него. 
	*/
	// matching n(3) or more occurrences of a subexpression
	std::regex 	r8{R"(\d{3,})"};
	cout 	<< R"(Matching against: \d{3,})" << "\n"
			<< format("123: {}; 1234567890: {}; 12: {}\n\n",
							std::regex_match("123", r8),
											std::regex_match("1234567890", r8),
													std::regex_match("12", r8));
	/*
		Вы можете использовать квантификатор {п,m}, 
		чтобы обозначить от n до m (включительно) 
		последовательных повторений элемента слева от него. 
	*/
	// matching n to m inclusive (3-6), occurrences of a subexpression
	std::regex 	r9{R"(\d{3,6})"};		//	Пробелы после запятой недопустимы
	cout << R"(Matching against: \d{3,6})" << "\n"
		<< format("123: {}; 123456: {}; 1234567: {}; 12: {}\n",
						std::regex_match("123", r9), 
									std::regex_match("123456", r9),
												std::regex_match("1234567", r9), 
														std::regex_match("12", r9));
}
