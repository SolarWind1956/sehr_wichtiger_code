//
// This is example code from Chapter 23.7 "Searching with regular expressions" of
// "Programming -- Principles and Practice Using C++" by Bjarne Stroustrup
//
#include <regex>
#include <iostream>
#include <stdexcept>
#include <string>
#include <fstream>
using namespace std;

//------------------------------------------------------------------------------
int main()
try
{
    ifstream 	in	{"file.txt"};    						// input file
	if (!in) 
		cerr << "no file\n";

	// Шаблон индекса
	auto 		pat			{R"(\w{2}\s*\d{5}(-\d{4})?)"};	// Необработанный Raw (сырой) литерал
	cout << "pattern: " << pat << '\n';
	/*
		Шаблон 'regex_patrn' является разновидностью строки, 
		так что мы инициализируем его строкой. 
		
		Здесь мы использовали необработанный строковый литерал. 
		
		Однако std::regex - это не только строка, 
		но и некоторый сложный механизм сопоставления строки шаблону, 
		который скрыто создается 
		при инициализации объекта типа std::regex нашим шаблоном 
		для почтового индекса (или при присваивании ему этого шаблона) 
		и который выходит за рамки нашей книги. 
		
		Однако после инициализации объекта std::regex строкой-шаблоном 
		его можно  применять к каждой строке нашего файла. 
	*/
    std::regex 	regex_patrn	{pat};	    				// 	ZIP code pattern
    
    int 	lineno = 0;
    string 	line;    									// 	input buffer
    while (getline(in, line)) {
        ++lineno;
		// Совпавшие строки
		/*
			Переменная matches имеет тип std::smatch. 
			
			Буква 's' в нем означает "sub" (или "string" - что вам больше нравится). 
			
			По сути тип std::smatch представляет собой вектор совпадений с подшаблонами. 
			
			Первый элемент matches[О] представляет собой полное совпадение. 
			
			Мы можем интерпретировать элемент matches[i] как строку, 
			если i < matches.size(). 
			
			Итак, если для данного регулярного выражения 
			максимальное количество подшаблонов равно N, 
			выполняется условие matches.size() == N + 1. 
			
			Что же такое 'подшаблон' (sub-pattern)? 
			
			Можно просто сказать: 
			"Все, что заключено в (круглые скобки) внутри шаблона". 
			
			Глядя на шаблон 
			
			\w{ 2}\s*\d{ 5} (-\d{ 4}) ?, 
			
			мы видим (круглые скобки) вокруг четырехзначного расширения индекса. 
			
			Таким образом, мы видим только один 'подшаблон', 
			так что 
			matches.size() == 2. 
			
			Можно предположить, 
			что у нас есть простой доступ к этим четырем последним цифрам.
		*/
        std::smatch 	matches;    					// 	matched strings go here
		/*
			Функция regex_search(line, matches, regex_patrn) ищет в строке 'line' все, 
			что соответствует регулярному выражению, хранящемуся в объекте regex_patrn, 
			и если она находит какое-либо соответствие, то сохраняет его в объекте matches. 
			
			Естественно, если соответствие не обнаружено. 
			функция regex_search(line, matches, regex_patrn) возвращает значение false.
		*/
        if 	(std::regex_search	(	line				//	Считанная из файла строка
								, 	matches				//	Найденные в соответствии с regex-шаблоном строки
								, 	regex_patrn			//	Шаблон регулярного выражения
								)
			) 		{
			// 	Полное соответствие	
            cout << lineno << ": " << matches[0] << '\n';
			
            if (1 < matches.size() && matches[1].matched)
                cout  << "\t: " << matches[1] << '\n';  	// 	sub-match - подшаблон
			/*
				Строго говоря, мы не обязаны проверять выражение 1 < matches.size(), 
				поскольку уже рассмотрели шаблон, 
				но к этому нас подталкивает легкая паранойя 
				(поскольку мы экспериментируем с разными шаблонами, 
				хранящимися в объекте regex_patrn, и не все они содержат только один подшаблон). 
				
				Мы можем проверить, обнаружен ли подшаблон, 
				просматривая его член 'matched', 
				в данном случае - matches[1].matched. 
				
				В случае, если вам это интересно, когда значение 
				
				matches[i].matched == false, 
				
				то подшаблоны matches[i], 
				у которых нет соответствия, 
				выводятся как 'пустые строки'.
				
				Аналогично, если подшаблон не существует, 
				например matches[17] для приведенного выше шаблона, 
				то он рассматривается как подшаблон, соответствие которому не найдено. 
			*/
        }
    }
	
	/*
		Шаблон для непустой строки буквенно-цифровых символов, 
		заключенной в двойные кавычки, 
		может выглядеть так: 
	*/	
	std::string 	str_0		{"[[:alnum:]]+"}; 
	std::regex		regex_str_0	{str_0};
	/*
		Чтобы поместить это реrулярное выражение в строковый литерал. к кавычкам надо добавить обратные косые черты, сделав их управляющими символами: 
string s = 11\ " [ [ : alnwn: ] ] +\ 11
11 ; 
Более того, чтобы поместить этот строковый литерал в объект класса 
regex, следует сделать управляющими символами не только кавычки, но и 
саму обратную косую черту: 
reqex s { "\\\" [ [ : alnwn: ] ] +\\\ 11 11 }; 
Применение необработанных строковых литералов существенно упрощает 
жизнь программиста: 
reqex s2 {R" (" [ [ : alnwn: ] ] +" } 11 }; 
	*/
}
catch (std::exception& e) {
    cerr << "error: " << e.what() << '\n'; 
    return 1;
}
catch (...) {
    cerr << "Oops: unknown exception!\n"; 
    return 2;
};

