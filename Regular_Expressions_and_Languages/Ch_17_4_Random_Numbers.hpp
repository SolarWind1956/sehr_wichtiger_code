/*
	 Параграф 17.4. Случайные числа
	 
	 Программы нередко нуждаются в источнике случайных чисел. 
	 
	 До нового стандарта языки С и С++ полагались на простую библиотечную функцию языка С по имени rand(). 
	 
	 Эта функция создает псевдослучайные целые числа, 
	 "равномерно распределенные" 
	 в диапазоне от нуля до зависимого от системы максимального значения, 
	 которое по крайней мере не меньше 32767.
	 
	 У функции rand() несколько проблем: 
	 многим, если не всем, программам нужны случайные числа в совершенно другом диапазоне,
	 отличном от используемого функцией rand(). 
	 
	 Некоторые приложения требуют случайных чисел с плавающей запятой, 
	 другим нужны числа с неоднородным распределением. 
	 
	 Когда разработчики пытаются преобразовывать 
	  - диапазон, 
	  - тип 
	 или 
	  - распределение чисел, 
	 созданных функцией rand(), их случайность зачастую теряется.
	 
	 Библиотека случайных чисел, определенная в заголовке <random>,
	 решает эти проблемы за счет набора взаимодействующих классов: 
	 
	  - классов "процессора случайных чисел" (random-number engine) 
	  и 
	  - классов "распределения случайного числа" (random-number distribution). 
	  
	 Эти классы описаны в табл. 17.14. 
	 
	 "Процессор" создает "последовательность" беззнаковых случайных чисел, 
	 а 
	 "распределение" использует процессор для создания случайных чисел 
	 определенного типа 
	 в заданном диапазоне,
	 распределенном согласно "указанному вероятностному распределению".
	 
	 Таблица 17.14. Компоненты библиотеки случайных чисел
	 
	 Процессор  	- 	Типы, создающие последовательность случайных беззнаковых целых чисел
	 
	 Распределение  - 	Типы, использующие процессор для возвращения чисел 
						согласно заданному распределению вероятности 
		  
	 Программы С++ больше не должны использовать библиотечную функцию rand(). 
	 
	 Для этого следует использовать класс "default_random_engine" наряду с соответствующим объектом распределения
*/
/*
	 *********************  17.4.1. Процессоры случайных чисел и распределения
	 
	 "Процессоры случайных чисел"  —  это классы объектов функции, 
									  определяющие оператор вызова, 
									  не получающий никаких аргументов 
									  и возвращающий случайное беззнаковое число. 
	 
	 Вызвав объект типа процессора случайных чисел, можно получить простые случайные числа:
*/
void test_Random_Numbers_step_1()
{ 
	 cout << "\nI'm void test_Random_Numbers_step_1()" << endl;
	 
	 std::default_random_engine  	number_by_random_engine; 	// создает случайное беззнаковое число
	 cout << "std::default_random_engine   :   ";
	 for (size_t i = 0; i < 10; ++i)
		// number_by_random_engine() "вызывает" объект для создания следующего случайного числа
		cout << number_by_random_engine() << " ";	// Это, как я понимаю, 'oператор вызова функции' () 
													// класса default_random_engine
		cout << endl;
};
