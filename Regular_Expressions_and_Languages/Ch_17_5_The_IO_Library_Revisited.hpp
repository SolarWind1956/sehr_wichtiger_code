/*
	Параграф 17.5. 	Еще о библиотеке ввода и вывода

	Глава 8 познакомила вас с базовой архитектурой и наиболее часто используемой частью библиотеки ввода-вывода. 
	
	В этом разделе рассматриваются три более специализированных средства,
	поддерживаемых библиотекой ввода-вывода: 
	
		-	управление форматом, 
		
		-	неформатированный ввод-вывод 
		
		и 
		
		-	произвольный доступ.
	
	------------------------------- 17.5.1. Форматированный ввод и вывод
 
	Кроме 'флага состояния', каждый объект iostream имеет также "флаг формата", 
	контролирующий подробности формата ввода и вывода. 
	
	"Флаг формата" контролирует такие аспекты, 
	как 'формат записи целочисленных значений', 
	'точность значений с плавающей запятой',
	'ширина выводимого элемента'
	и т.д.

	Библиотека определяет набор "манипуляторов" (manipulator), изменяющих "флаг формата потока". 
	
	"Манипулятор" 	— 	это функция или объект, влияющие на состояние потока
						и применяемые как операнд оператора ввода или вывода. 
	
	Как и операторы ввода и вывода, манипулятор возвращает потоковый объект, 
	к которому он применяется; 
	таким образом, можно объединить манипуляторы и данные в один оператор.
	
	--------------------------------  Большинство манипуляторов изменяет флаг формата
	
	Манипуляторы используются для двух общих категорий управления выводом: 
	
		-	контроль представления числовых значений, 
		а также 
		-	контроль количества и расположения заполнителей. 
		
	Большинство 'манипуляторов, изменяющих флаг формата', 
	'предоставлены парами' для 'установки и сброса';
	один манипулятор устанавливает флаг формата в новое значение, 
	а другой сбрасывает его, восстанавливая стандартное значение.
	
	Манипуляторы, изменяющие 'флаг формата потока', 
	обычно оставляют флаг формата измененным для всего последующего ввода-вывода.
	
	Тот факт, что манипулятор вносит постоянное изменение во флаг формата, 
	может оказаться полезным, когда имеется ряд операций ввода-вывода, 
	использующих одинаковое форматирование. 
	
	Действительно, некоторые программы используют эту особенность манипуляторов 
	для изменения поведения одного или нескольких правил форматирования ввода или вывода. 
	
	В таких случаях факт изменения потока является желательным.
	
	Но большинство программ (и что еще важней, разработчиков) ожидают, 
	что состояние потока будет соответствовать стандартным библиотечным значениям. 
	
	В этих случаях оставленный в нестандартном состоянии поток может привести к ошибке. 
	
	В результате обычно лучше отменить изменение состояния, 
	как только оно больше не нужно.
	
	--------------------------------  Контроль формата логических значений
	
	Хорошим примером манипулятора, изменяющего состояние формата своего объекта, 
	является манипулятор boolalpha. 
	
	По умолчанию значение типа bool выводится как 1 или 0. 
	
	Значение true выводится как целое число 1, а значение false как 0. 
	
	Это поведение можно переопределить, применив к потоку манипулятор boolalpha:
	
	cout 	<< "default bool values: " 
			<< true << " " << false << "\nalpha bool values: " 
			<< boolalpha << true << " " << false << endl;
 
	Эта программа выводит следующее:
	
	default bool values: 1 0
	alpha bool values: true false
 
 	Как только манипулятор boolalpha "записан" в поток cout, способ вывода логических значений изменяется. 
	
	Последующие операции вывода логических значений отобразят их как "true" или "false".
	
	Чтобы отменить изменение флага формата потока cout, применяется манипулятор noboolalpha:
	
	bool bool_val = get_status();
	
	cout 	<< boolalpha    	// устанавливает внутреннее состояние cout
			<< bool_val
			<< noboolalpha; 	// возвращает стандартное внутреннее состояние
	
	Здесь формат вывода логических значений изменен только для вывода значения bool_val. 
	
	Как только это значение будет выведено, поток немедленно возвращается в первоначальное состояние.
*/
/*
	******************************* 17.5.2. Не форматированные операции ввода-вывода
 
	До сих пор в программах использовались только операции форматированного ввода-вывода (formatted IO). 
	
	Операторы ввода и вывода (<< и >>) 
	форматируют читаемые и выводимые данные согласно их типу.
	
	Операторы ввода игнорируют отступ; операторы вывода применяют дополнение, точность и т.д.
	
	Библиотека предоставляет также набор низкоуровневых функций не форматированного ввода-вывода (unformatted IO). 
	
	Эти функции позволяют работать с потоком 
	как с последовательностью неинтерпретируемых байтов.
	
	----------------------------	Однобайтовые операции
	
	Некоторые из не форматированных операций имеют дело с обработкой потока по одному байту за раз. 
	
	Они описаны в табл. 17.19 и читают данные, не игнорируя отступ. 
	
	Например, функции не форматированного ввода-вывода get() и put() 
	позволяют читать и записывать символы по одному:
	
	char ch;
	while (cin.get(ch))
	cout.put(ch);
 
	Эта программа сохраняет отступ во вводе. 
	
	Ее вывод идентичен вводу.
	
	Она работает так же, как и предыдущая программа, использовавшая манипулятор noskipws.
*/
/*
	-----------------------------  Возвращение во входной поток
	
	Иногда необходимо читать отдельные символы так, 
	чтобы знать, к чему быть готовым. 
	
	В таких случаях символы желательно возвращать в поток.
	
	Библиотека предоставляет три способа сделать это, 
	и у каждого из них есть свои отличия.
	
	• 	Функция peek() возвращает копию следующего символа во входном потоке, 
		но не изменяет поток. 
		
		Возвращенное значение остается в потоке.
		
	• 	Функция unget() создает резервную копию входного потока, 
		чтобы независимо от того, какое значение было последним возвращенным, 
		оно все еще оставалось в потоке. 
		
		Функцию unget() можно вызвать, даже не зная, 
		какое значение было извлечено из потока последним.
		
	• 	Функция putback() — это более специализированная версия функции unget(): 
		она возвращает последнее прочитанное из потока значение, 
		но получает аргумент, 
		который должен совпадать с последним прочитанным значением.
		
	Таким образом, они гарантируют возможность 
	вернуть в поток как минимум одно значение 
	перед следующим чтением. 
	
	Следовательно, 
	гарантированно не получится 
	вызвать функции putback() или unget() последовательно, 
	без промежуточной операции чтения.
	
	------------------------------ Возвращение значения типа int из операций ввода 
	
	Функция peek() и версия функции get() без аргументов 
	возвращают прочитанный символ из входного потока как значение типа int. 
	
	Этот факт может удивить; 
	казалось бы, более естественным было бы возвращение типа char.
	
	Причина возвращения этими функциями типа int в том, 
	чтобы позволить им возвратить маркер конца файла. 
	
	Полученный набор символов
	позволяет использовать каждое значение в диапазоне типа char 
	и представлять фактические символы. 
	
	Но в этом диапазоне 
	нет никакого специального значения для представления конца файла.
	
	Функции, возвращающие тип int, 
	преобразуют возвращаемый символ в тип unsigned char, 
	а затем преобразуют это значение в тип int. 
	
	В результате, даже если в наборе символов будут символы, 
	соответствующие отрицательным значениям, 
	возвращенный этими функциями тип int будет иметь положительное значение. 
	
	Библиотека использует "отрицательное значение" 
	для представления "конца файла",
	гарантируя таким образом его отличие 
	от любого настоящего символьного значения. 
	
	Чтобы не обязывать разработчиков знать фактическое возвращаемое значение, 
	заголовок iostream определяет 'константу' "EOF",
	которую можно использовать для проверки, 
	не является ли возвращенное функцией get() значение концом файла. 
	
	Вот почему для содержания значения, 
	возвращаемого этими функциями, используется переменная типа int.
*/

