/*
	Для улучшения производительности 
	необходимо предварительно вычислить `длину итоговой строки`, 
	просуммировав длины всех аргументов функции concat_variadic(). 
	
	Это позволит сразу зарезервировать достаточный объем памяти для итоговой строки. 
	
	Поскольку каждый аргумент concat_variadic() 
	может иметь один из трех перечисленных выше типов, 
	определим набор перегружаемых вспомогательных функций `extent()`, 
	вычисляющих длину последовательности символов 
	в соответствии с каждым возможным типом аргумента:
*/
#include <cstring>   	// 	std::strlen
std::size_t str_extent(char)                 	{ return 1; }
std::size_t str_extent(const char* s)        	{ return std::strlen(s); }
std::size_t str_extent(const std::string& s) 	{ return s.length(); }
/*
	Нам все еще необходима та часть вычисления, 
	которая суммирует длины нескольких фрагментов, 
	и самый простой способ сделать это без ввода дополнительного имени – 
	разрешить `str_extent()` принимать 
	произвольное (переменное) количество аргументов:
*/
// 	Базовый случай рекурсии
std::size_t str_extent() 						{ return 0; }   

template <typename T, typename... Ts>
std::size_t str_extent(const T& arg_first, const Ts&... args_rest)
{
	return str_extent(arg_first) + str_extent(args_rest...);
}
/*
	Вариант перегрузки без параметров обрабатывает пустые пакеты параметров. 
	
	Версия с переменным количеством аргументов 
	отделяет первый аргумент и 
	прибавляет размер занимаемой им памяти 
	к рекурсивно вычисляемой сумме длин остальных фрагментов.
	
	После того как вычислен окончательный размер результируюей строки,
	и создан объект std::string соответствующей вместимости для сохранения результата, 
	возвращаемое значение `concat_variadic` 
	можно вычислить с помощью аналогичного рекурсивного шаблона функции, 
	например `stringAppend()`, 
	который поочередно добавляет каждый аргумент в итоговую строку:
*/
// 	Базовый случай рекурсии
void stringAppend(std::string&) 
{ }   
template <typename S0, typename... S>
void stringAppend	(	std::string& 	result
					, 	const S0& 		s0
					, 	const S&... 		s
					)
{
    result += s0;
    stringAppend(result, s...);
}
/*
	Структура функции stringAppend() уже известна: 
	она добавляет свой второй аргумент (s0) в `result`, 
	а затем вызывает рекурсивный экземпляр самой себя 
	для добавления третьего и всех последующих аргументов. 
	
	Окончательная версия шаблона функции concat_variadic() не является рекурсивной, 
	но вызывает два рекурсивных шаблона, которые мы только что определили:
*/
// 	Создание итоговой строки и резервирование достаточного пространства памяти,
// 	чтобы избежать повторных операций перераспределения
template <typename... Ts>
std::string 	concat_variadic(const Ts&... args)
{
    std::string 	result_str;
    result_str.reserve(str_extent(args...));

	// 	Добавление каждой строки из пакета параметров `args` в `result_str`
    stringAppend(result_str, args...);

	return result_str;
}
