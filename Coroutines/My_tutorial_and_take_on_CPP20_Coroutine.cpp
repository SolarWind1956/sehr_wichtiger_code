	cout << "-------------- I'm inline void " <<  __func__  << "()" << endl;
	
	std::coroutine_handle<> 		handle;
	std::coroutine_handle<void> 	handle_is_same;
	
	static_assert(std::is_same_v<std::coroutine_handle<>, std::coroutine_handle<void>>);
	
