/*
	--------------------------------------------------------------------------------------------------
	Оператор		co_return​
	
	До сих пор наши сопрограммы создавали бесконечный поток целых чисел, 
	а наша основная функция просто уничтожала состояние сопрограммы 
	после чтения первых трех целых чисел. 
	
	Что, если вместо этого наша сопрограмма 
	хочет создать только конечное число значений, 
	прежде чем сигнализировать об условии завершения сопрограммы?

	Чтобы сигнализировать об окончании сопрограммы, 
	C++ добавляет новый оператор co_return. 
	
	Сопрограмма может 'сообщить о своем завершении' 
	тремя способами:

		1.	Сопрограмма может использовать «co_return 	e;» для возврата конечного значения 'e'.

		2.	Сопрограмма может использовать «co_return;» без значения (или с выражением void), 
			чтобы завершить сопрограмму без конечного значения.

		3.	Сопрограмма может допустить, чтобы выполнение прерывалось до конца функции, 
			что аналогично предыдущему случаю.

	В случае 1 компилятор вставляет вызов 
	
	promise.return_value(e) объекта обещания promise. 
	
	В случаях 2–3 компилятор вызывает promise.return_void(). 
	
	Чтобы узнать, завершена ли сопрограмма, 
	вы можете вызвать handle.done() дескриптора сопрограммы handle. 
	
	Не путайте 
	
	coroutine_handle::done() 
	
	с 
	
	coroutine_handle::operator bool(). 
	
	Последний просто проверяет, 
	содержит ли дескриптор сопрограммы ненулевой указатель на память сопрограммы, 
	а не проверяет, завершено ли выполнение.

	Вот новая версия счетчика, в которой сама сопрограмма counter() 
	решает выдавать только 3 значения, 
	в то время как основная, вызывающая, функция просто продолжает печатать значения, 
	пока сопрограмма не завершится. 
	
	Нам нужно внести еще одно изменение в promise_type::final_suspend(), 
	но давайте сначала посмотрим на новый код, 
	а затем обсудим объект обещания ниже.													-------->
*/
