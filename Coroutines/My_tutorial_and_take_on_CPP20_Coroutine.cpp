/*
	----------------------------------------------------------------------------------------------------------
	promise_type 	destroyed
	
	Есть несколько вещей, на которые стоит обратить внимание co_return. 
	
	Обратите внимание, что в предыдущих примерах 
	у нашего объекта обещания не было метода return_void(). 
	
	Это нормально, пока мы не использовали co_return. 
	
	В противном случае, если вы используете co_return, 
	но не имеете соответствующего метода return_void() или return_value(), 
	вы получите ошибку компиляции об отсутствующем методе. 
	
	Это хорошие новости. 
	
	Плохая новость заключается в том, 
	что если вы потеряете конец функции и у вас в promise_type не будет метода return_void(), 
	вы получите неопределенное поведение. 
	
	Я расскажу об этом подробнее в редакционной статье ниже, 
	но достаточно сказать, что неопределенное поведение - дело действительно очень плохое — 
	например, плохое использование после освобождения или переполнение границ массива. 
	
	Поэтому будьте осторожны и не оставьте конец сопрограммы, 
	в объекте обещания которой отсутствует метод return_void()!

	Еще одна вещь, на которую следует обратить внимание, 
	co_return	-	это то, 	что 
	
	promise_type::return_void() 
	и 
	promise_type::return_value(v)
	
	оба возвращают void; 
	
	в частности, они не возвращают ожидаемые объекты. 
	
	Вероятно, это связано с желанием унифицировать обработку возвращаемых значений и исключений 
	(о которых мы поговорим ниже). 
	
	Тем не менее, существует важный вопрос о том, что делать в конце сопрограммы. 
	
	Должен ли компилятор обновить состояние сопрограммы 
	и приостановить ее в последний раз, 
	чтобы даже после оценки co_return, 
	код основной функции мог получить доступ к объекту обещания 
	и разумно использовать coroutine_handle? 
	
	Или возврат из сопрограммы должен автоматически уничтожать состояние сопрограммы, 
	как неявный вызов coroutine_handle::destroy()?

	Этот вопрос решается методом final_suspend() на promise_type. 
	
	В спецификации C++ говорится, 
	что тело функции сопрограммы фактически заключено в следующий псевдокод:

    {
		promise-type promise promise-constructor-arguments ;
		try {
			co_await 	promise.initial_suspend() ;
			function-body
		} catch ( ... ) {
			if (!initial-await-resume-called)
              throw ;
			promise .unhandled_exception() ;
        }
    final-suspend :
		co_await 	promise .final_suspend() ;
    }
    // "The coroutine state is destroyed when control flows off the end of the coroutine"

	Когда сопрограмма возвращается, 
	вы неявно получаете co_await результат promise.final_suspend(). 
	
	Если final_suspend() фактически приостанавливает сопрограмму, 
	то состояние сопрограммы будет обновлено в последний раз 
	и останется действительным, 
	а код вне сопрограммы будет отвечать за освобождение объекта сопрограммы 
	путем вызова метода destroy() дескриптора сопрограммы. 
	
	Если final_suspend() не приостановит сопрограмму, 
	то состояние сопрограммы будет автоматически уничтожено.

	Если вы никогда не планируете снова трогать состояние сопрограммы 
	(возможно, потому, что сопрограмма только что обновила какую-то глобальную переменную 
	и/или выпустила семафор перед этим co_return, 
	и это все, что вас волнует), 
	то нет причин платить за сохранение состояния в последний раз 
	и беспокоиться о ручном освобождении состояния сопрограммы, 
	чтобы вы могли получить std::suspend_never final_suspend(). 
	
	С другой стороны, если вам нужно получить доступ к дескриптору сопрограммы или объекту обещания 
	после возврата сопрограммы, 
	вам нужно будет  std::suspend_always final_suspend() вернуть 
	(или какой-либо другой ожидаемый объект, который приостанавливает сопрограмму).

	Чтобы сделать это более конкретным, вот что произойдет, 
	если мы изменим в
	
	ReturnObject5::promise_type::final_suspend() 
	return std::suspend_never
	вместо 
	std::suspend_always:																	------->
*/
